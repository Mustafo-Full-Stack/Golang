// ============================================================================
// ФАЙЛ: cmd/api/main.go
// ЗАЧЕМ НУЖЕН: это "входная дверь" (точка входа) во всю программу.
// Когда ты запускаешь проект командой `go run ./cmd/api`, компилятор Go
// ищет именно пакет `main` и функцию `main()`, чтобы начать выполнение с первой строчки.
//
// ПОЧЕМУ В ЭТОМ ФАЙЛЕ ТАК МАЛО КОДА?
// Это золотое правило архитектуры в Go: файл main.go должен быть крошечным.
// Он только нажимает кнопку "Старт" (вызывает app.Run()) и, если случилась
// критическая ошибка при запуске, выводит её на экран. Вся сборка приложения
// вынесена в пакет `internal/app`.
//
// ШПАРГАЛКА ПО БАЗОВЫМ ПОНЯТИЯЯМ В ЭТОМ ФАЙЛЕ:
//
// 1. ЧТО ТАКОЕ ПАКЕТ (package)?
//    Пакет — это папка с файлами .go, объединёнными одной темой.
//    Бывает два вида пакетов:
//      а) `package main` — главный исполняемый пакет. Из него получается программа (.exe / бинарник).
//      б) Все остальные (`package config`, `package auth`) — это пакеты-библиотеки (помощники).
//         Их нельзя запустить сами по себе, но их можно подключить через `import`.
//
// 2. ЧТО ТАКОЕ ФУНКЦИЯ (func)?
//    Функция — это кусок кода с именем, который можно вызывать.
//    Примеры объявления функций в Go:
//      func sayHello() { ... }                  // ничего не принимает, ничего не возвращает
//      func add(a int, b int) int { return a+b } // принимает 2 числа, возвращает 1 число
//      func Run() error { ... }                 // ничего не принимает, возвращает ошибку (error)
//
// 3. ЧТО ТАКОЕ `error` И `nil` (И ПЕРВОЕ ЗНАКОМСТВО С ИНТЕРФЕЙСАМИ)?
//    В других языках (Python, Java, JS) при ошибке программа "бросает исключение" (throw/try/catch).
//    В Go исключений нет! В Go ошибка — это ОБЫЧНОЕ ЗНАЧЕНИЕ, которое функция возвращает.
//
//    Тип `error` в Go — это встроенный ИНТЕРФЕЙС (подробно интерфейсы разобраны в handler.go):
//      type error interface {
//          Error() string // любой тип, у которого есть метод Error(), считается ошибкой!
//      }
//    А `nil` — это специальное слово в Go, означающее "ПУСТО / НИЧЕГО / НЕТ ЗНАЧЕНИЯ".
//      - Если функция вернула `err == nil` → значит, ошибки НЕТ, всё прошло отлично!
//      - Если функция вернула `err != nil` (не пусто) → значит, внутри лежит ошибка, надо её обработать!
//
// ============================================================================
// 🧒 ОБЪЯСНЕНИЕ ДЛЯ 10-ЛЕТНЕГО РЕБЁНКА (НА ПАЛЬЦАХ С ПРИМЕРАМИ):
// ============================================================================
//
// 1. ЧТО ТАКОЕ `main.go`?
//    Представь радиоуправляемую машинку. Внутри неё спрятаны моторчик, батарейки,
//    шестерёнки и провода — но снаружи на корпусе есть всего ОДНА большая красная кнопка "СТАРТ".
//    Файл `main.go` и функция `func main()` — это и есть та самая красная кнопка!
//    Когда ты нажимаешь её (`go run ./cmd/api`), кнопка сама ничего не чинит и не крутит колёса,
//    она просто подаёт ток в моторчик: вызывает `app.Run()`.
//
// 2. КАК ПОНЯТЬ `if err := app.Run(); err != nil`?
//    Представь, что мама отправила тебя в магазин за молоком (`app.Run()`).
//    Когда ты возвращаешься домой, мама спрашивает: "Какие-то проблемы были?" (`err`).
//      - Если ты отвечаешь: "Ноль проблем, пусто!" (`err == nil`) — мама спокойна, всё хорошо.
//      - А если ты говоришь: "Магазин закрыт на замок!" (`err != nil`, то есть проблема НЕ пустая) —
//        тогда срабатывает `log.Fatal(err)`: мама громко объявляет всем на кухне причину проблемы,
//        и поход за молоком отменяется!
//
// ============================================================================
// 🍕 ПРИМЕРЫ НА РЕСТОРАНЕ (2 НАГЛЯДНЫХ ПРИМЕРА):
// ============================================================================
//
// ПРИМЕР 1: Главный рубильник ресторана (`func main()` и `app.Run()`)
//   Представь большой ресторан. Внутри него есть кухня, печи, холодильники и касса (это пакет `internal/app`).
//   Но снаружи у входной двери есть всего ОДНА кнопка включения света — это файл `main.go`.
//   Утром приходит управляющий и нажимает кнопку:
//     func main() {
//         app.Run() // Включаем весь ресторан!
//     }
//   Сама кнопка пиццу не печёт, она только запускает работу ресторана.
//
// ПРИМЕР 2: Проверка проблем перед открытием ресторана (`if err := app.Run(); err != nil`)
//   Когда управляющий пытается открыть ресторан утром (`err := app.Run()`), возможны 2 случая:
//     - Случай А (`err == nil`): электричество есть, холодильники гудят, повара на месте.
//       Ошибок ноль (`nil`), ресторан спокойно работает весь день!
//     - Случай Б (`err != nil`): на кухне прорвало трубу! Переменная `err` НЕ пустая (`!= nil`).
//       Тогда срабатывает `log.Fatal(err)`: управляющий вешает на дверь табличку с причиной поломки
//       и мгновенно закрывает ресторан, пока трубу не починят.
// ============================================================================

// package main — говорит компилятору Go: "это главный пакет, собери из него запускаемую программу".
// Разбор строки по каждому слову:
//   - `package` — ключевое слово "объявляем имя пакета для этого файла";
//   - `main`    — специальное зарезервированное имя главного пакета, с которого стартует программа.
package main

// import — блок подключения других пакетов, чтобы мы могли пользоваться их функциями.
// Важное правило Go: если ты написал пакет в import, но ни разу не использовал в коде,
// программа даже не запустится — Go очень строгий и не любит лишний мусор.
// Разбор строки по каждому слову:
//   - `import` — ключевое слово "подключаем другие пакеты";
//   - `(`      — открываем список подключаемых пакетов.
import (
	// "log" — встроенный (стандартный) пакет Go для вывода сообщений с датой и временем в терминал.
	// Например: 2026/11/05 21:00:00 ошибка подключения к базе.
	// Разбор строки:
	//   - `"log"` — имя стандартного пакета в кавычках.
	"log"

	// "habit-tracker/internal/app" — подключаем наш собственный пакет `app`.
	// Почему путь начинается с "habit-tracker"? Потому что так называется наш модуль
	// в первой строчке файла `go.mod` (`module habit-tracker`).
	// Разбор строки:
	//   - `"habit-tracker/internal/app"` — полный путь от корня модуля `habit-tracker` до папки `internal/app`.
	"habit-tracker/internal/app"
	// `)` — закрываем список импортов.
)

// func main() — главная функция. У неё никогда нет параметров в скобках () и она ничего не возвращает.
// Как только код внутри фигурных скобок { ... } функции main закончится, вся программа выключится.
// Разбор строки по каждому слову от начала до конца:
//   - `func`   — ключевое слово "объявляем функцию";
//   - `main`   — имя главной функции (всегда должно быть `main`);
//   - `()`     — пустые круглые скобки: функция не принимает никаких входных параметров;
//   - (после скобок ничего нет) — функция ничего не возвращает назад;
//   - `{`      — открываем тело функции (здесь начинается код).
func main() {
	// Разберём конструкцию `if err := app.Run(); err != nil` по кусочкам!
	// Это сокращённая (и очень популярная в Go) запись из двух шагов, разделённых точкой с запятой `;`.
	//
	// Полная запись без сокращения выглядела бы так:
	//   err := app.Run()   // Шаг 1: вызываем функцию Run() из пакета app и кладём ответ в переменную err.
	//   if err != nil {    // Шаг 2: проверяем: в переменной err НЕ пусто (есть ошибка)?
	//       log.Fatal(err)
	//   }
	//
	// Зачем пишут в одну строчку через `;`?
	// Чтобы переменная `err` жила ТОЛЬКО внутри этого блока `if` и не засоряла код дальше.
	//
	// Разбор строки по каждому слову от начала до конца:
	//   - `if`         — ключевое слово "если" (условие);
	//   - `err`        — создаём новую переменную с именем `err` (для хранения ошибки);
	//   - `:=`         — оператор "создай новую переменную и сразу положи в неё значение";
	//   - `app.Run()`  — вызываем функцию `Run()` из пакета `app` (круглые скобки `()` означают "вызвать сейчас");
	//   - `;`          — разделитель: "сначала выполни `err := app.Run()`, а потом проверь условие справа";
	//   - `err != nil` — само условие: `err` (наша переменная) `!=` (не равна) `nil` (пустоте), то есть "ошибка есть?";
	//   - `{`          — открываем блок кода, который выполнится, ТОЛЬКО если ошибка действительно есть.
	if err := app.Run(); err != nil {
		// Сюда мы попадаем, ТОЛЬКО если `err != nil` (то есть что-то сломалось:
		// например, забыли указать секрет JWT_SECRET или не запущена база данных PostgreSQL).
		//
		// log.Fatal(err) делает два действия подряд:
		//   1) Печатает дату, время и текст ошибки в терминал.
		//   2) Вызывает os.Exit(1) — мгновенно останавливает программу с кодом ошибки 1.
		//
		// Разбор строки по каждому слову:
		//   - `log`    — обращаемся к стандартному пакету логирования;
		//   - `.Fatal` — вызываем функцию `Fatal` из пакета `log`;
		//   - `(err)`  — передаём внутрь нашу переменную `err` с ошибкой.
		log.Fatal(err)
		// `}` — закрываем блок `if`.
	}
	// `}` — закрываем функцию `main`. Когда программа доходит сюда, она завершает работу.
}
