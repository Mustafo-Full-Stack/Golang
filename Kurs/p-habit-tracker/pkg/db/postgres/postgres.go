// ============================================================================
// ФАЙЛ: pkg/db/postgres/postgres.go
// ЗАЧЕМ НУЖЕН: подключается к базе данных PostgreSQL и возвращает "пул соединений".
//
// ПОЧЕМУ ПАПКА НАЗЫВАЕТСЯ `pkg`, А НЕ `internal`?
// В Go-проектах принято делить код на две большие зоны:
//   1. `internal/` — закрытый код ТОЛЬКО для нашего проекта (наши привычки, наши правила).
//      Сам компилятор Go запретит другому проекту импортировать что-то из чужой папки `internal`.
//   2. `pkg/` — универсальные "кирпичики", которые не знают ничего про трекер привычек.
//      Эту папку `pkg/db/postgres` можно скопировать в интернет-магазин или чат-бот, и она будет работать!
//
// ============================================================================
// ШПАРГАЛКА ПО GO: ЧТО ТАКОЕ ПУЛ СОЕДИНЕНИЙ И ЧТО ТАКОЕ МЕТОД (Method)?
// ============================================================================
//
// 1. ЧТО ТАКОЕ ПУЛ СОЕДИНЕНИЙ (`*pgxpool.Pool`)?
//    Представь, что установка соединения с базой данных — это как дозвониться в банк
//    и пройти проверку паспорта (занимает много времени).
//    Если на каждый HTTP-запрос пользователя звонить в базу заново и класть трубку,
//    сервер будет работать очень медленно.
//
//    Пул соединений (Pool) решает это так: при старте программы он заранее открывает,
//    например, 10 телефонных линий с базой и держит трубку снятой.
//    Когда приходит запрос — он берёт свободную линию на миллисекунду и возвращает её обратно в пул!
//
// 2. ЧТО ТАКОЕ МЕТОД (Method) И ЧЕМ ОН ОТЛИЧАЕТСЯ ОТ ОБЫЧНОЙ ФУНКЦИИ?
//    Обычная функция сама по себе:
//      func buildDSN(cfg Config) string { ... }
//      Вызов: buildDSN(cfg)
//
//    А МЕТОД — это функция, которую "прикрепили" к конкретной структуре!
//    Посмотри на функцию `dsn()` внизу этого файла:
//      func (cfg Config) dsn() string { ... }
//           ^^^^^^^^^^^^
//           Вот эта часть перед названием функции называется ПОЛУЧАТЕЛЬ (Receiver).
//
//    Благодаря получателю `(cfg Config)`, структура `Config` "научилась" сама собирать свой адрес:
//      Вызов: cfg.dsn()  — читается как "эй, настройка cfg, дай мне свой dsn!".
//
//    Простой пример из жизни:
//      type Dog struct { Name string }
//      // Прикрепляем метод Bark (лаять) к структуре Dog:
//      func (d Dog) Bark() {
//          fmt.Println(d.Name, "говорит: Гав!")
//      }
//      rex := Dog{Name: "Рекс"}
//      rex.Bark() // Выведет: Рекс говорит: Гав!
//
// ============================================================================
// 🧒 ОБЪЯСНЕНИЕ ДЛЯ 10-ЛЕТНЕГО РЕБЁНКА (НА ПАЛЬЦАХ С ПРИМЕРАМИ):
// ============================================================================
//
// 1. ЧТО ТАКОЕ БАЗА ДАННЫХ И ПУЛ СОЕДИНЕНИЙ (`*pgxpool.Pool`)?
//    Когда ты выключаешь компьютер, всё, что было в памяти программы, стирается!
//    Чтобы пользователи и их привычки не исчезали после перезагрузки, мы храним их
//    в специальном железном сейфе — базе данных PostgreSQL.
//
//    А зачем нужен "Пул соединений" (`Pool`)?
//    Представь, что наша программа — это школа, а база данных — это библиотека через реку.
//    Чтобы сходить за книжкой, нужно построить мост через реку.
//    Если для каждого ученика строить новый мост, брать одну книжку и сразу ломать мост —
//    урок закончится раньше, чем все получат учебники!
//    Поэтому директор утром один раз строит 10 крепких мостов (`pgxpool.New`) и не убирает их.
//    Эти 10 готовых мостов и называются ПУЛОМ (`Pool`). Ученики бегают по ним туда-сюда мгновенно!
//
// 2. ЗАЧЕМ НУЖЕН `pool.Ping(ctx)`?
//    Построить мост — это полдела. Нужно проверить, не закрыта ли дверь на том берегу!
//    `Ping` — это когда мы кричим в рацию: "База данных, приём! Ты меня слышишь?!".
//    Если база отвечает "Слышу отлично!" (`err == nil`), мы начинаем работу.
//    А если в рации тишина — мы сразу говорим директору, что библиотека сегодня закрыта.
//
// 3. ЧТО ТАКОЕ МЕТОД `(cfg Config) dsn()` ДЛЯ 10-ЛЕТНЕГО?
//    Обычная функция — это инструмент в ящике (например, отвёртка сама по себе).
//    А МЕТОД — это суперспособность, встроенная прямо в робота или покемона!
//    Когда мы написали `func (cfg Config) dsn()`, мы подарили коробке настроек `Config`
//    суперспособность самой называть свой секретный адрес по команде `cfg.dsn()`.
//
// ============================================================================
// 🍕 ПРИМЕРЫ НА РЕСТОРАНЕ (2 НАГЛЯДНЫХ ПРИМЕРА):
// ============================================================================
//
// ПРИМЕР 1: Пул соединений (`*pgxpool.Pool`) как 10 окошек выдачи на продуктовом складе ресторана
//   База данных PostgreSQL — это огромный подземный склад продуктов нашего ресторана.
//     - Если бы пула НЕ было: каждый раз, когда повару нужна одна помидорка, он спускается в подвал,
//       отпирает тяжёлую железную дверь ключом, берёт помидорку и снова запирает дверь на 5 оборотов.
//       Очередь из гостей в зале будет ждать обед три часа!
//     - Как работает Пул (`pgxpool.New`): утром при открытии ресторана мы сразу открываем 10 скоростных
//       лифтов-окошек на склад и держим их открытыми весь день. Когда повару нужен продукт,
//       он за долю секунды берёт его через свободное окошко из пула!
//
// ПРИМЕР 2: Метод `(cfg Config) dsn()` и проверка `pool.Ping(ctx)` в ресторане
//   1) Метод `cfg.dsn()`:
//      У карточки склада `cfg` есть встроенная кнопка `cfg.dsn()`. Нажимаешь её — и карточка сама
//      собирает пропуск-адрес для экспедитора: `"postgres://шеф:пароль@склад:5432/ресторан"`.
//   2) Проверка `pool.Ping(ctx)`:
//      Прежде чем впускать голодных гостей в зал ресторана, шеф-повар звонит по внутреннему телефону
//      на склад (`pool.Ping(ctx)`): "Алло, кладовщик на месте? Свет в холодильниках горит?".
//      Если со склада ответили (`err == nil`) — открываем ресторан!
// ============================================================================

// package postgres — имя пакета по названию папки.
// Разбор строки по каждому слову:
//   - `package`  — ключевое слово объявления пакета;
//   - `postgres` — имя пакета.
package postgres

// Подключаем нужные пакеты.
// Разбор строки: `import (` — открываем список импортов.
import (
	// "context" — позволяет отменить зависшее подключение к базе (например, если база не отвечает).
	"context"
	// "fmt" — для оборачивания ошибок через fmt.Errorf.
	"fmt"
	// "net" — для функции net.JoinHostPort (склеивает хост "localhost" и порт "5432" в "localhost:5432").
	"net"
	// "net/url" — помогает безопасно собрать URL-адрес подключения к базе.
	"net/url"

	// "github.com/jackc/pgx/v5/pgxpool" — сторонняя библиотека (драйвер PostgreSQL).
	// Это самый быстрый и популярный инструмент для работы с PostgreSQL в мире Go.
	"github.com/jackc/pgx/v5/pgxpool"
)

// Config — анкета с данными для входа в базу данных PostgreSQL.
// Разбор строки по каждому слову:
//   - `type`   — создаём новый тип данных;
//   - `Config` — имя типа (снаружи пакета пишется как `postgres.Config`);
//   - `struct` — структура (набор полей);
//   - `{`      — открываем поля структуры.
type Config struct {
	// Host — адрес компьютера, где живёт база ("localhost" или имя контейнера в Docker).
	// Разбор строки: `Host` (имя поля) `string` (тип: строка).
	// Разбор строки по каждому слову:
	//   - `Host`   — имя публичного поля структуры;
	//   - `string` — тип поля: строка.
	Host string
	// Port — номер двери (порта), на котором слушает база (стандартно "5432").
	// Разбор строки: `Port` (имя поля) `string` (тип: строка).
	// Разбор строки по каждому слову:
	//   - `Port`   — имя публичного поля структуры;
	//   - `string` — тип поля: строка.
	Port string
	// User — логин в базе данных.
	// Разбор строки: `User` (имя поля) `string` (тип: строка).
	// Разбор строки по каждому слову:
	//   - `User`   — имя публичного поля структуры;
	//   - `string` — тип поля: строка.
	User string
	// Password — пароль от базы данных.
	// Разбор строки: `Password` (имя поля) `string` (тип: строка).
	// Разбор строки по каждому слову:
	//   - `Password` — имя публичного поля структуры;
	//   - `string`   — тип поля: строка.
	Password string
	// Database — имя конкретной базы данных (внутри одного PostgreSQL может быть много разных баз).
	// Разбор строки: `Database` (имя поля) `string` (тип: строка).
	// Разбор строки по каждому слову:
	//   - `Database` — имя публичного поля структуры;
	//   - `string`   — тип поля: строка.
	Database string
	// SSLMode — нужно ли шифровать трафик до базы ("disable" — выключено, "require" — обязательно).
	// Разбор строки: `SSLMode` (имя поля) `string` (тип: строка).
	// Разбор строки по каждому слову:
	//   - `SSLMode` — имя публичного поля структуры;
	//   - `string`  — тип поля: строка.
	SSLMode string
}

// New — создаёт пул соединений с базой и проверяет связь.
// Принимает контекст `ctx` и структуру настроек `cfg`.
// Возвращает указатель на пул `*pgxpool.Pool` и ошибку `error`.
//
// Разбор строки по каждому слову от начала до конца:
//   - `func`                   — ключевое слово объявления функции;
//   - `New`                    — имя функции-конструктора (вызывается как `postgres.New(...)`);
//   - `(ctx context.Context,`  — 1-й входной параметр: переменная `ctx` с типом-интерфейсом `context.Context`;
//   - `cfg Config)`            — 2-й входной параметр: переменная `cfg` с типом структуры `Config`;
//   - `(*pgxpool.Pool, error)` — функция возвращает ДВА значения:
//                                1) `*pgxpool.Pool` — указатель (`*`) на пул соединений;
//                                2) `error`         — ошибку (или `nil`);
//   - `{`                      — открываем тело функции.
func New(ctx context.Context, cfg Config) (*pgxpool.Pool, error) {
	// ШАГ 1. Собираем конфигурацию пула по строке подключения `cfg.dsn()`.
	// Важная тонкость: `pgxpool.New` проверяет только правильность текста строки подключения,
	// но может ещё НЕ стучаться в саму базу по сети.
	//
	// Разбор строки по каждому слову:
	//   - `pool, err`                   — создаём две переменные: `pool` (для пула) и `err` (для ошибки);
	//   - `:=`                          — оператор создания и присваивания;
	//   - `pgxpool.New(ctx, cfg.dsn())` — вызываем функцию `New` из пакета `pgxpool`, передавая ей
	//                                     контекст `ctx` и результат вызова метода `cfg.dsn()`.
	pool, err := pgxpool.New(ctx, cfg.dsn())

	// Разбор строки по каждому слову:
	//   - `if`         — если;
	//   - `err != nil` — ошибка не равна `nil` (есть ошибка);
	//   - `{`          — открываем блок обработки ошибки.
	if err != nil {
		// Если строка подключения кривая — возвращаем nil вместо пула и ошибку.
		// Разбор строки по каждому слову:
		//   - `return`                                     — выходим из функции;
		//   - `nil,`                                       — 1-й результат: `nil` вместо пула;
		//   - `fmt.Errorf("create postgres pool: %w", err)` — 2-й результат: обёрнутая ошибка `err`.
		return nil, fmt.Errorf("create postgres pool: %w", err)
	}

	// ШАГ 2. Делаем `pool.Ping(ctx)` — настоящую проверку связи по сети!
	// Ping отправляет в базу короткий сигнал "Тук-тук, ты жива?" и проверяет логин/пароль.
	//
	// Разбор строки по каждому слову:
	//   - `if`                     — если;
	//   - `err := pool.Ping(ctx);` — вызываем метод `Ping(ctx)` у нашего `pool` и сохраняем результат в `err`;
	//   - `err != nil`             — условие: вернулась ли ошибка от базы?;
	//   - `{`                      — если база не ответила, заходим внутрь блока.
	if err := pool.Ping(ctx); err != nil {
		// Если база выключена или пароль не подошёл — аккуратно закрываем созданный пул
		// и возвращаем ошибку, чтобы программа сразу сообщила об этом при старте.
		// Разбор строки: `pool.Close()` — вызываем метод `Close()` у пула соединений.
		// Разбор строки по каждому слову:
		//   - `pool`     — переменная пула соединений;
		//   - `.Close()` — метод закрытия всех соединений пула.
		pool.Close()
		// Разбор строки: `return nil, fmt.Errorf(...)` — возвращаем `nil` и ошибку пинга.
		// Разбор строки по каждому слову:
		//   - `return`                              — выйти из функции;
		//   - `nil,`                                — 1-й результат: `nil` вместо пула;
		//   - `fmt.Errorf("ping postgres: %w", err)` — 2-й результат: ошибка с префиксом `"ping postgres: "` и вложенной `err`.
		return nil, fmt.Errorf("ping postgres: %w", err)
	}

	// База ответила! Возвращаем готовый рабочий пул и `nil` (ошибок нет).
	// Разбор строки по каждому слову:
	//   - `return` — вернуть из функции;
	//   - `pool,`  — 1-й результат: указатель на рабочий пул соединений;
	//   - `nil`    — 2-й результат: ошибок нет (`nil`).
	return pool, nil
}

// dsn — приватный МЕТОД структуры `Config` (привязан через получатель `(cfg Config)`).
// DSN (Data Source Name) — это полная строка подключения к базе в формате URL.
// Пример того, что возвращает этот метод:
//
//	"postgres://postgres:secret@localhost:5432/habits?sslmode=disable"
//
// Почему мы собираем её через `url.URL`, а не просто плюсуем строки `"postgres://" + cfg.User + ...`?
// Потому что если в пароле встретится символ `@`, `:` или `/`, обычная склейка строк сломает адрес!
// А `url.URL` автоматически закодирует спецсимволы в безопасный вид.
//
// Разбор строки по каждому слову от начала до конца:
//   - `func`         — ключевое слово объявления функции/метода;
//   - `(cfg Config)` — ПОЛУЧАТЕЛЬ (receiver): привязывает этот метод к структуре `Config`.
//                      Внутри метода через переменную `cfg` доступны все поля (`cfg.Host`, `cfg.Port` и т.д.);
//   - `dsn`          — имя метода (с маленькой буквы = приватный, виден только внутри пакета `postgres`);
//   - `()`           — дополнительных входных параметров нет;
//   - `string`       — метод возвращает одну строку `string`;
//   - `{`            — открываем тело метода.
func (cfg Config) dsn() string {
	// Разбор строки по каждому слову:
	//   - `u`        — создаём переменную `u`;
	//   - `:=`       — оператор объявления и присваивания;
	//   - `url.URL{` — создаём структуру `URL` из пакета `net/url`.
	u := url.URL{
		// Протокол: "postgres://"
		// Разбор строки: `Scheme:` (поле схемы) `"postgres",` (значение).
		// Разбор строки по каждому слову:
		//   - `Scheme:`     — поле схемы протокола в структуре `url.URL`;
		//   - `"postgres",` — строка `"postgres"` (даст `"postgres://"`).
		Scheme: "postgres",
		// Логин и пароль: "user:password@"
		// Разбор строки: `User:` (поле пользователя) `url.UserPassword(cfg.User, cfg.Password),` (упаковка логина и пароля).
		// Разбор строки по каждому слову:
		//   - `User:`                                  — поле данных авторизации в `url.URL`;
		//   - `url.UserPassword(cfg.User, cfg.Password),` — функция безопасной упаковки логина `cfg.User` и пароля `cfg.Password`.
		User: url.UserPassword(cfg.User, cfg.Password),
		// Хост и порт: "localhost:5432"
		// Разбор строки: `Host:` (поле хоста) `net.JoinHostPort(cfg.Host, cfg.Port),` (склейка хоста и порта через `:`).
		// Разбор строки по каждому слову:
		//   - `Host:`                                 — поле адреса сервера в `url.URL`;
		//   - `net.JoinHostPort(cfg.Host, cfg.Port),` — функция склеивания хоста и порта через двоеточие `:` (например, `"localhost:5432"`).
		Host: net.JoinHostPort(cfg.Host, cfg.Port),
		// Имя базы данных после слэша: "/habits"
		// Разбор строки: `Path:` (поле пути) `cfg.Database,` (имя БД).
		// Разбор строки по каждому слову:
		//   - `Path:`         — поле пути в `url.URL`;
		//   - `cfg.Database,` — имя базы данных из настроек `cfg`.
		Path: cfg.Database,
		// Параметры после знака вопроса: "?sslmode=disable"
		// Разбор строки: `RawQuery:` (поле query-параметров) `url.Values{"sslmode": {cfg.SSLMode}}.Encode(),` (кодирование параметров).
		// Разбор строки по каждому слову:
		//   - `RawQuery:`                                    — поле строки параметров после `?`;
		//   - `url.Values{"sslmode": {cfg.SSLMode}}.Encode(),` — формируем параметр `"sslmode=disable"` и кодируем его в строку URL.
		RawQuery: url.Values{"sslmode": {cfg.SSLMode}}.Encode(),
	}
	// Превращаем структуру `url.URL` в готовую текстовую строку.
	// Разбор строки по каждому слову:
	//   - `return`     — вернуть результат из метода;
	//   - `u.String()` — вызвать метод `String()` у переменной `u`, который собирает весь URL в одну строку.
	return u.String()
}
