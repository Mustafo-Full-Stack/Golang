// ============================================================================
// ФАЙЛ: internal/app/app.go
// ЗАЧЕМ НУЖЕН: это "сборочный цех" нашего приложения.
// Здесь все отдельные слои программы соединяются друг с другом как детали LEGO:
//
//   [1. Config (Настройки)]
//            ↓
//   [2. Postgres Pool (База данных)]
//            ↓
//   [3. Repositories (Запросы в БД: userrepo, habitrepo)]
//            ↓
//   [4. Services (Бизнес-логика: authService, habitService)]
//            ↓
//   [5. Handler (HTTP-обработчики и роутер)]
//            ↓
//   [6. http.ListenAndServe (Запуск веб-сервера)]
//
// ============================================================================
// ШПАРГАЛКА ПО GO: DEPENDENCY INJECTION, CONTEXT И DEFER
// ============================================================================
//
// 1. ЧТО ТАКОЕ DEPENDENCY INJECTION (Внедрение зависимостей)?
//    Звучит страшно, но на деле всё элементарно!
//    Это правило: "Деталь НЕ создаёт сама то, от чего она зависит, а получает это готовым снаружи".
//
//    Пример:
//      Плохо: Сервис привычек сам внутри себя читает настройки и сам подключается к базе.
//      Хорошо (Dependency Injection): Мы в `app.go` создали подключение к базе `pool`,
//      передали его в `habitrepo.NewRepository(pool)`, а готовый репозиторий передали в
//      `habit.NewService(habits)`.
//      Каждый слой занимается только своим делом!
//
// 2. ЧТО ТАКОЕ `context.Context` (Контекст)?
//    `context.Context` — это встроенный ИНТЕРФЕЙС в Go, который передаётся ПЕРВЫМ параметром
//    почти во все функции, работающие с сетью или базой данных: `func(ctx context.Context, ...)`.
//
//    Зачем он нужен? У него две главные задачи:
//      а) ОТМЕНА ОПЕРАЦИЙ (Cancellation / Timeout):
//         Представь, что пользователь нажал кнопку в приложении, запрос ушёл в базу данных,
//         но через секунду пользователь закрыл вкладку браузера.
//         Зачем базе данных продолжать считать тяжёлый запрос для пользователя, который уже ушёл?
//         Контекст подаёт сигнал "Отбой!", и база мгновенно прекращает работу.
//      б) ПЕРЕДАЧА ДАННЫХ ЗАПРОСА:
//         Например, в `middleware.go` мы кладём в контекст `userID` проверенного пользователя,
//         чтобы обработчик знал, кто именно прислал запрос.
//
// 3. ЧТО ТАКОЕ `defer` (Отложенный вызов)?
//    Слово `defer` перед вызовом функции говорит Go:
//    "Запомни эту команду, но НЕ выполняй её сейчас. Выполни её в самый последний момент,
//    когда текущая функция будет завершаться (перед самым выходом из `return`)".
//
//    Пример:
//      func readFile() {
//          file := open("notes.txt")
//          defer close(file) // Вызовется САМЫМ ПОСЛЕДНИМ, когда функция readFile закончится!
//          // ... тут работаем с файлом, и даже если случится ошибка и ранний return,
//          // Go всё равно не забудет закрыть файл!
//      }
//
// ============================================================================
// 🧒 ОБЪЯСНЕНИЕ ДЛЯ 10-ЛЕТНЕГО РЕБЁНКА (НА ПАЛЬЦАХ С ПРИМЕРАМИ):
// ============================================================================
//
// 1. КАК РАБОТАЕТ `app.go` НА ПРИМЕРЕ ОТКРЫТИЯ ПИЦЦЕРИИ?
//    Представь, что наш проект — это ресторан-пиццерия. В файле `app.go` директор открывает смену:
//      - Шаг 1 (`config.Load`): Директор читает правила на стене (во сколько открываемся, какой код от сейфа).
//      - Шаг 2 (`postgres.New`): Директор открывает большой холодильник с продуктами (Базу Данных `pool`).
//      - Шаг 3 и 4 (`NewRepository` и `NewService`):
//          а) Сначала директор зовёт Кладовщика (`Repository`) и даёт ему ключи от холодильника (`pool`).
//             Кладовщик не умеет готовить пиццу, он умеет только доставать помидоры и сыр с полок.
//          б) Потом директор зовёт Шеф-повара (`Service`) и знакомит его с Кладовщиком (`Repository`).
//             Шеф-повар сам в холодильник не лазит! Он кричит кладовщику: "Дай сыр!" и готовит по рецепту.
//      - Шаг 5 (`handler.New`): Директор ставит у входа Официанта (`Handler`) и знакомит его с Шеф-поваром.
//        Официант принимает заказ у гостей в зале и передаёт на кухню Шеф-повару.
//      - Шаг 6 (`http.ListenAndServe`): Директор переворачивает табличку на двери на "ОТКРЫТО" и ждёт гостей!
//
//    То, что директор сам раздаёт каждому работнику нужные ключи и помощников в руки,
//    взрослые программисты умным словом называют **Dependency Injection** (Внедрение зависимостей)!
//
// 2. ЧТО ТАКОЕ `defer pool.Close()` ДЛЯ 10-ЛЕТНЕГО?
//    Когда ты достаёшь мороженое из морозилки, мама клеит тебе на лоб стикер `defer`:
//    "Как только закончишь дела на кухне — ОБЯЗАТЕЛЬНО закрой дверцу морозилки!".
//    Даже если тебе позвонит друг и ты убежишь гулять раньше времени, стикер `defer`
//    напомнит закрыть морозилку (`pool.Close()`) перед самым выходом из комнаты!
//
// ============================================================================
// 🍕 ПРИМЕРЫ НА РЕСТОРАНЕ (2 НАГЛЯДНЫХ ПРИМЕРА):
// ============================================================================
//
// ПРИМЕР 1: Dependency Injection (Внедрение зависимостей) на примере двух цехов ресторана
//   Посмотри на Шаг 3 и Шаг 4 в коде ниже — в нашем ресторане работают два цеха:
//     - Цех №1 (Регистрация VIP-гостей):
//       Директор даёт ключи от склада `pool` → Кладовщику анкет (`users := userrepo.NewRepository(pool)`),
//       а Кладовщика анкет передаёт → Менеджеру клубных карт (`authService := auth.NewService(users, ...)`).
//     - Цех №2 (Заказы блюд / Привычки):
//       Директор даёт ключи от склада `pool` → Кладовщику кухни (`habits := habitrepo.NewRepository(pool)`),
//       а Кладовщика кухни передаёт → Шеф-повару (`habitService := habit.NewService(habits)`).
//     - Затем директор знакомит Старшего Официанта (`h := handler.New(...)`) сразу с обоими:
//       и с Менеджером клубных карт (`authService`), и с Шеф-поваром (`habitService`)!
//
// ПРИМЕР 2: Как работают `context.Context` и `defer` на кухне ресторана
//   1) Контекст (`ctx`):
//      Гость заказал стейк, повар начал жарить, но через минуту гость передумал и ушёл из ресторана.
//      Официант нажимает кнопку отмены на пейджере (`ctx`), и повар тут же снимает стейк с плиты,
//      чтобы не переводить продукты зря!
//   2) Отложенный вызов (`defer pool.Close()`):
//      Утром директор открыл склад (`pool`) и сразу повесил у выхода табличку `defer pool.Close()`.
//      Как только смена ресторана (`func Run()`) закончится — склад автоматически закроется на замок!
// ============================================================================

// package app — пакет сборки приложения.
// Разбор строки по каждому слову:
//   - `package` — ключевое слово объявления пакета;
//   - `app`     — имя пакета (совпадает с папкой `internal/app`).
package app

// Разбор строки: `import (` — открываем список подключаемых пакетов.
import (
	// "context" — для создания базового контекста при старте программы.
	"context"
	// "fmt" — для добавления пояснений к ошибкам через fmt.Errorf.
	"fmt"
	// "log" — для вывода сообщения в консоль о том, что сервер успешно запустился.
	"log"
	// "net/http" — стандартная библиотека Go для запуска HTTP-сервера.
	"net/http"

	// Подключаем наши внутренние пакеты:
	"habit-tracker/internal/config"
	"habit-tracker/internal/handler"

	// ЗАЧЕМ ТУТ НАПИСАНО `habitrepo` ПЕРЕД КАВЫЧКАМИ?
	// У нас есть две папки с одинаковым именем `habit`:
	//   1) `internal/repository/habit` (работа с базой)
	//   2) `internal/service/habit`    (бизнес-логика)
	// Если подключить обе без переименования, Go запутается: кто из них `habit`?
	// Поэтому первому пакету мы даём псевдоним (кличку) `habitrepo`, а второму оставляем имя `habit`.
	//
	// Разбор строки по каждому слову:
	//   - `habitrepo`                           — псевдоним (новое имя пакета в этом файле);
	//   - `"habit-tracker/internal/repository/habit"` — путь к пакету репозитория привычек.
	habitrepo "habit-tracker/internal/repository/habit"

	// Разбор строки по каждому слову:
	//   - `userrepo`                           — псевдоним для репозитория пользователей;
	//   - `"habit-tracker/internal/repository/user"` — путь к пакету репозитория пользователей.
	userrepo "habit-tracker/internal/repository/user"

	// `"habit-tracker/internal/service/auth"` — пакет сервиса авторизации.
	"habit-tracker/internal/service/auth"
	// `"habit-tracker/internal/service/habit"` — пакет сервиса привычек.
	"habit-tracker/internal/service/habit"
	// `"habit-tracker/pkg/db/postgres"` — наш пакет подключения к базе данных PostgreSQL.
	"habit-tracker/pkg/db/postgres"
)

// Run — собирает и запускает приложение.
// Имя начинается с большой буквы `R`, чтобы функцию можно было вызвать из пакета `main` (`app.Run()`).
//
// Разбор строки по каждому слову от начала до конца:
//   - `func`  — ключевое слово объявления функции;
//   - `Run`   — имя функции (с Большой буквы = публичная);
//   - `()`    — пустые скобки: функция не принимает входных аргументов;
//   - `error` — функция возвращает ошибку (интерфейс `error`) или `nil`;
//   - `{`     — открываем тело функции.
func Run() error {
	// ========================================================================
	// ШАГ 1. Загружаем настройки из переменных окружения
	// ========================================================================
	// Разбор строки по каждому слову:
	//   - `cfg, err`      — создаём две переменные: `cfg` (настройки `*config.Config`) и `err` (ошибка `error`);
	//   - `:=`            — оператор создания и присваивания;
	//   - `config.Load()` — вызываем функцию `Load()` из пакета `config`.
	cfg, err := config.Load()

	// Разбор строки по каждому слову:
	//   - `if`         — если;
	//   - `err != nil` — ошибка не равна `nil` (не удалось загрузить настройки);
	//   - `{`          — открываем блок ошибки.
	if err != nil {
		// Что делает `%w` в `fmt.Errorf("load config: %w", err)`?
		// Это "оборачивание ошибки" (Error Wrapping), как матрёшка:
		// Если внутри `err` было `"JWT_SECRET is required"`, то снаружи станет:
		// `"load config: JWT_SECRET is required"`.
		// Так по тексту ошибки в консоли сразу видно всю цепочку: ГДЕ и ЧТО сломалось!
		//
		// Разбор строки по каждому слову:
		//   - `return`                            — выходим из функции `Run()` и возвращаем ошибку в `main()`;
		//   - `fmt.Errorf("load config: %w", err)` — создаём новую ошибку с префиксом `"load config: "` и вложенной `err`.
		return fmt.Errorf("load config: %w", err)
	}

	// ========================================================================
	// ШАГ 2. Подключаемся к базе данных PostgreSQL
	// ========================================================================
	// `context.Background()` создаёт самый первый, "пустой" корневой контекст,
	// который никогда сам не отменяется. Его всегда используют в `main` / `Run` на старте.
	//
	// Разбор строки по каждому слову:
	//   - `ctx`                  — имя новой переменной контекста;
	//   - `:=`                   — создать и присвоить;
	//   - `context.Background()` — вызвать функцию `Background()` из пакета `context`.
	ctx := context.Background()

	// Создаём пул подключений к базе, передавая туда настройки `cfg.Postgres`.
	// Разбор строки по каждому слову:
	//   - `pool, err`                       — создаём переменные `pool` (`*pgxpool.Pool`) и `err` (`error`);
	//   - `:=`                              — создать и присвоить;
	//   - `postgres.New(ctx, cfg.Postgres)` — вызываем функцию `New` из пакета `postgres`, передавая `ctx` и `cfg.Postgres`.
	pool, err := postgres.New(ctx, cfg.Postgres)

	// Разбор строки: `if err != nil {` — если база не ответила или пароль неверный:
	// Разбор строки по каждому слову:
	//   - `if`         — если;
	//   - `err != nil` — переменная `err` не равна `nil` (произошла ошибка подключения к БД);
	//   - `{`          — открываем блок ошибки.
	if err != nil {
		// Разбор строки: `return fmt.Errorf("connect postgres: %w", err)` — возвращаем обёрнутую ошибку подключения к БД.
		// Разбор строки по каждому слову:
		//   - `return`                                 — выходим из функции `Run()`;
		//   - `fmt.Errorf("connect postgres: %w", err)` — возвращаем ошибку с пояснением `"connect postgres: "` и вложенной `err`.
		return fmt.Errorf("connect postgres: %w", err)
	}

	// Ставим на охрану `defer pool.Close()`.
	// Когда программа когда-нибудь завершится, Go автоматически закроет все соединения с базой.
	// Разбор строки по каждому слову:
	//   - `defer`        — ключевое слово "выполни это в самом конце перед выходом из функции Run()";
	//   - `pool.Close()` — вызываем метод `Close()` у пула соединений.
	defer pool.Close()

	// ========================================================================
	// ШАГ 3. Собираем модуль Авторизации (Репозиторий → Сервис)
	// ========================================================================
	// 1) Создаём репозиторий пользователей и даём ему пул базы данных `pool`.
	// Разбор строки по каждому слову:
	//   - `users`                        — создаём переменную репозитория пользователей;
	//   - `:=`                           — создать и присвоить;
	//   - `userrepo.NewRepository(pool)` — вызываем конструктор `NewRepository` из пакета `userrepo`, передавая `pool`.
	users := userrepo.NewRepository(pool)

	// 2) Создаём сервис авторизации и даём ему репозиторий `users`, секрет и время жизни токена.
	// Разбор строки по каждому слову:
	//   - `authService`                                     — создаём переменную сервиса авторизации;
	//   - `:=`                                              — создать и присвоить;
	//   - `auth.NewService(users, cfg.JWTSecret, cfg.JWTTTL)` — вызываем конструктор `NewService` из пакета `auth`.
	authService := auth.NewService(users, cfg.JWTSecret, cfg.JWTTTL)

	// ========================================================================
	// ШАГ 4. Собираем модуль Привычек (Репозиторий → Сервис)
	// ========================================================================
	// 1) Создаём репозиторий привычек и даём ему тот же пул базы данных `pool`.
	// Разбор строки по каждому слову:
	//   - `habits`                        — создаём переменную репозитория привычек;
	//   - `:=`                            — создать и присвоить;
	//   - `habitrepo.NewRepository(pool)` — вызываем конструктор `NewRepository` из пакета `habitrepo`.
	habits := habitrepo.NewRepository(pool)

	// 2) Создаём сервис привычек и даём ему репозиторий привычек `habits`.
	// Разбор строки по каждому слову:
	//   - `habitService`            — создаём переменную сервиса привычек;
	//   - `:=`                      — создать и присвоить;
	//   - `habit.NewService(habits)` — вызываем конструктор `NewService` из пакета `habit`, передавая `habits`.
	habitService := habit.NewService(habits)

	// ========================================================================
	// ШАГ 5. Создаём HTTP-слой (Handler)
	// ========================================================================
	// Передаём оба сервиса в наш Handler, чтобы он мог вызывать их при HTTP-запросах.
	// Разбор строки по каждому слову:
	//   - `h`                                    — создаём переменную обработчика `h`;
	//   - `:=`                                   — создать и присвоить;
	//   - `handler.New(authService, habitService)` — вызываем конструктор `New` из пакета `handler`, передавая оба сервиса.
	h := handler.New(authService, habitService)

	// ========================================================================
	// ШАГ 6. Запускаем HTTP-сервер!
	// ========================================================================
	// Выводим в терминал подсказку, на каком порту слушает сервер (например, ":8080").
	// Разбор строки по каждому слову:
	//   - `log.Printf(...)`                — печатаем строку по шаблону в консоль;
	//   - `"http server listening on :%s"` — текст сообщения, где `%s` заменится на значение `cfg.HTTPPort`;
	//   - `cfg.HTTPPort`                   — порт из настроек (например, `"8080"`).
	log.Printf("http server listening on :%s", cfg.HTTPPort)

	// `http.ListenAndServe` запускает бесконечный цикл ожидания HTTP-запросов:
	//   - Первый аргумент `":" + cfg.HTTPPort` — адрес и порт (например, ":8080").
	//   - Второй аргумент `h.Routes()` — маршрутизатор (объект, реализующий интерфейс `http.Handler`),
	//     который решает, какую функцию вызвать на каждый пришедший запрос.
	// Функция `ListenAndServe` "зависает" и работает всё время, пока включён сервер.
	// Она вернёт управление (и ошибку) только если порт уже занят другой программой или сервер упадёт.
	//
	// Разбор строки по каждому слову от начала до конца:
	//   - `return`               — вернуть ошибку, если сервер остановится;
	//   - `http.ListenAndServe(` — вызвать функцию запуска HTTP-сервера из пакета `net/http`;
	//   - `":" + cfg.HTTPPort,`  — 1-й аргумент: склеиваем двоеточие `":"` и порт `"8080"` → `":8080"`;
	//   - `h.Routes()`           — 2-й аргумент: вызываем метод `Routes()` у `h`, возвращающий роутер (`http.Handler`);
	//   - `)`                    — закрываем вызов функции.
	return http.ListenAndServe(":"+cfg.HTTPPort, h.Routes())
}
