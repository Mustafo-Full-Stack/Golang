// Service — структура сервиса авторизации.
// Разбор строки по каждому слову:
//   - `type`    — создаём новый тип данных;
//   - `Service` — имя структуры (снаружи пакета пишется как `auth.Service`);
//   - `struct`  — это структура;
//   - `{`       — открываем список полей.
type Service struct {
	// users — указатель на репозиторий пользователей (чтобы сохранять и искать людей в БД).
	// Разбор строки: `users` (имя приватного поля) `*userrepo.Repository` (тип: указатель на репозиторий).
	// Разбор строки по каждому слову:
	//   - `users`                — имя приватного поля структуры;
	//   - `*userrepo.Repository` — тип поля: указатель (`*`) на структуру `Repository` из пакета `userrepo`.
	users *userrepo.Repository
	// jwtSecret — секретный ключ сервера в виде среза байтов `[]byte`, которым мы подписываем токены.
	// Разбор строки: `jwtSecret` (имя поля) `[]byte` (тип: срез байтов).
	// Разбор строки по каждому слову:
	//   - `jwtSecret` — имя приватного поля структуры;
	//   - `[]byte`    — тип поля: срез байтов (`[]` = срез, `byte` = один байт).
	jwtSecret []byte
	// jwtTTL — сколько времени живёт выданный токен (например, 24 часа).
	// Разбор строки: `jwtTTL` (имя поля) `time.Duration` (тип длительности времени).
	// Разбор строки по каждому слову:
	//   - `jwtTTL`        — имя приватного поля структуры;
	//   - `time.Duration` — тип поля: отрезок времени из пакета `time`.
	jwtTTL time.Duration
}

// NewService — конструктор сервиса авторизации.
// Разбор строки по каждому слову от начала до конца:
//   - `func`                        — ключевое слово объявления функции;
//   - `NewService`                  — имя функции-конструктора;
//   - `(users *userrepo.Repository,` — 1-й параметр: указатель на репозиторий пользователей;
//   - `jwtSecret string,`           — 2-й параметр: секретный ключ в виде строки `string`;
//   - `jwtTTL time.Duration)`       — 3-й параметр: время жизни токена типа `time.Duration`;
//   - `*Service`                    — функция возвращает указатель (`*`) на созданную структуру `Service`;
//   - `{`                           — открываем тело функции.
func NewService(users *userrepo.Repository, jwtSecret string, jwtTTL time.Duration) *Service {
	// Разбор строки: `return &Service{` — создаём структуру `Service` и значком `&` возвращаем её адрес.
	// Разбор строки по каждому слову:
	//   - `return`    — ключевое слово возврата результата из функции;
	//   - `&Service{` — создаём экземпляр структуры `Service` и оператором `&` берём адрес в памяти (указатель `*Service`).
	return &Service{
		// Разбор строки: `users: users,` — сохраняем репозиторий в поле `users`.
		// Разбор строки по каждому слову:
		//   - `users:` — имя поля структуры `Service`;
		//   - `users,` — переданный параметр `users` (плюс запятая `,`).
		users: users,
		// Превращаем строку `jwtSecret` в `[]byte` один раз при старте программы,
		// чтобы не тратить время на это преобразование при каждом запросе пользователя.
		// Разбор строки: `jwtSecret: []byte(jwtSecret),` — переводим строку в байты и кладём в поле `jwtSecret`.
		// Разбор строки по каждому слову:
		//   - `jwtSecret:`        — имя поля структуры `Service`;
		//   - `[]byte(jwtSecret)` — приведение типа: превращаем строку `jwtSecret` в срез байтов `[]byte`;
		//   - `,`                 — запятая в конце строки при заполнении структуры.
		jwtSecret: []byte(jwtSecret),
		// Разбор строки: `jwtTTL: jwtTTL,` — сохраняем время жизни токена в поле `jwtTTL`.
		// Разбор строки по каждому слову:
		//   - `jwtTTL:` — имя поля структуры `Service`;
		//   - `jwtTTL,` — значение параметра `jwtTTL` (плюс запятая `,`).
		jwtTTL: jwtTTL,
	}
}

// Register — регистрирует нового пользователя.
// Принимает `in models.RegisterInput` (имя, почту, пароль) и возвращает созданного `*models.User`.
//
// Разбор строки по каждому слову от начала до конца:
//   - `func`                     — ключевое слово объявления функции/метода;
//   - `(s *Service)`             — получатель (receiver): привязывает метод к структуре `Service` (внутри `s` — наш сервис);
//   - `Register`                 — имя метода (с Большой буквы, чтобы вызывать из `handler`);
//   - `(ctx context.Context,`    — 1-й входной параметр: переменная `ctx` с типом-интерфейсом `context.Context`;
//   - `in models.RegisterInput)` — 2-й входной параметр: переменная `in` с типом структуры `models.RegisterInput` (имя, почта, пароль);
//   - `(*models.User, error)`    — метод возвращает ДВА значения:
//                                  1) `*models.User` — указатель на созданного пользователя (или `nil` при ошибке);
//                                  2) `error`        — ошибку (или `nil`);
//   - `{`                        — открываем тело метода.
func (s *Service) Register(ctx context.Context, in models.RegisterInput) (*models.User, error) {
	// ШАГ 1. Проверяем и очищаем входные данные (обрезаем пробелы, проверяем длину пароля).
	// Разбор строки по каждому слову:
	//   - `if`                    — если;
	//   - `err := in.Validate();` — вызываем метод `Validate()` у структуры `in` и сохраняем результат в `err`;
	//   - `err != nil`            — если ошибка не равна `nil` (данные плохие);
	//   - `{`                     — открываем блок ошибки.
	if err := in.Validate(); err != nil {
		// Разбор строки: `return nil, err` — возвращаем `nil` вместо пользователя и саму ошибку `err`.
		// Разбор строки по каждому слову:
		//   - `return` — выйти из метода и вернуть значения;
		//   - `nil,`   — 1-й результат: пустой указатель `*models.User` (пользователь не создан);
		//   - `err`    — 2-й результат: ошибка валидации.
		return nil, err
	}

	// ШАГ 2. Хешируем пароль с помощью алгоритма bcrypt.
	// `bcrypt.DefaultCost` (равен 10) — это "тяжесть" вычисления (2^10 раундов перемешивания).
	// Это сделано специально, чтобы один хеш считался ~0.07 секунды:
	// для обычного человека при регистрации это незаметно, а хакеру на перебор миллионов паролей потребуются годы!
	//
	// Разбор строки по каждому слову:
	//   - `hash, err`                    — создаём переменные `hash` (срез байтов хеша) и `err` (ошибка);
	//   - `:=`                           — объявляем и присваиваем;
	//   - `bcrypt.GenerateFromPassword(` — вызываем функцию хеширования из пакета `bcrypt`;
	//   - `[]byte(in.Password),`         — 1-й аргумент: превращаем строку пароля в срез байтов `[]byte`;
	//   - `bcrypt.DefaultCost)`          — 2-й аргумент: сложность хеширования по умолчанию (10).
	hash, err := bcrypt.GenerateFromPassword([]byte(in.Password), bcrypt.DefaultCost)
	// Разбор строки: `if err != nil { return nil, err }` — если хеширование вернуло ошибку, выходим.
	// Разбор строки по каждому слову:
	//   - `if`         — если;
	//   - `err != nil` — переменная `err` не равна `nil` (случилась ошибка при хешировании);
	//   - `{`          — открываем блок обработки ошибки.
	if err != nil {
		// Разбор строки по каждому слову:
		//   - `return` — выйти из метода;
		//   - `nil,`   — 1-й результат: `nil` вместо `*models.User`;
		//   - `err`    — 2-й результат: ошибка хеширования.
		return nil, err
	}

	// ШАГ 3. Собираем структуру пользователя для сохранения в базу.
	// Обрати внимание: вместо настоящего пароля мы кладём только `string(hash)`.
	// Разбор строки по каждому слову:
	//   - `user`          — имя новой переменной;
	//   - `:=`            — создать и присвоить;
	//   - `&models.User{` — создаём структуру `models.User` и берём её адрес `&` (тип `*models.User`).
	user := &models.User{
		// `Name: in.Name,` — заполняем поле `Name` очищенным именем.
		// Разбор строки по каждому слову:
		//   - `Name:`    — имя поля структуры `models.User`;
		//   - `in.Name,` — очищенное имя из входной структуры `in`.
		Name: in.Name,
		// `Email: in.Email,` — заполняем поле `Email` очищенной почтой.
		// Разбор строки по каждому слову:
		//   - `Email:`    — имя поля структуры `models.User`;
		//   - `in.Email,` — очищенная почта из входной структуры `in`.
		Email: in.Email,
		// `PasswordHash: string(hash),` — превращаем байты `hash` обратно в строку `string(hash)` и кладём в `PasswordHash`.
		// Разбор строки по каждому слову:
		//   - `PasswordHash:` — имя поля структуры `models.User`;
		//   - `string(hash),` — переводим байты хеша `hash` в строку `string` и ставим запятую `,`.
		PasswordHash: string(hash),
	}

	// ШАГ 4. Просим репозиторий сохранить пользователя в PostgreSQL.
	// Если почта уже занята, репозиторий вернёт `models.ErrUserExists` (Handler ответит 409 Conflict).
	// Разбор строки по каждому слову:
	//   - `if`                                — если;
	//   - `err := s.users.Create(ctx, user);` — вызываем метод `Create` у репозитория `s.users`;
	//   - `err != nil`                        — если база данных вернула ошибку;
	//   - `{ return nil, err }`               — возвращаем `nil` и эту ошибку.
	if err := s.users.Create(ctx, user); err != nil {
		// Разбор строки по каждому слову:
		//   - `return` — выйти из метода;
		//   - `nil,`   — 1-й результат: `nil` вместо пользователя;
		//   - `err`    — 2-й результат: ошибка базы данных (например, `ErrUserExists`).
		return nil, err
	}

	// Возвращаем готового пользователя (с заполненным `user.ID` и `user.CreatedAt`).
	// Разбор строки: `return` (вернуть) `user,` (указатель на пользователя) `nil` (ошибок нет).
	// Разбор строки по каждому слову:
	//   - `return` — завершаем метод и возвращаем результат;
	//   - `user,`  — 1-й результат: указатель `*models.User` на созданного пользователя;
	//   - `nil`    — 2-й результат: ошибок нет.
	return user, nil
}

// Login — проверяет почту и пароль пользователя и, если всё верно, выдаёт JWT-токен.
// Разбор строки по каждому слову от начала до конца:
//   - `func`                  — ключевое слово "объявляем функцию/метод";
//   - `(s *Service)`          — получатель (receiver): привязывает метод к структуре `Service` (внутри `s` — наш сервис);
//   - `Login`                 — имя метода (с Большой буквы, вызывается из обработчика как `h.auth.Login(...)`);
//   - `(ctx context.Context,` — 1-й входной параметр: переменная `ctx` с типом-интерфейсом `context.Context`;
//   - `in models.LoginInput)` — 2-й входной параметр: переменная `in` с типом структуры `models.LoginInput` (почта и пароль);
//   - `(string, error)`       — метод возвращает ДВА значения:
//                               1) `string` — строку готового JWT-токена (или `""` при ошибке);
//                               2) `error`  — ошибку (или `nil`, если вход успешен);
//   - `{`                     — открываем тело метода.
func (s *Service) Login(ctx context.Context, in models.LoginInput) (string, error) {
	// ШАГ 1. Проверяем, что почта и пароль не пустые.
	// Разбор строки по каждому слову:
	//   - `if`                    — если;
	//   - `err := in.Validate();` — вызываем метод `Validate()` у входных данных `in`;
	//   - `err != nil`            — если вернулась ошибка (почта или пароль пустые);
	//   - `{`                     — открываем блок ошибки.
	if err := in.Validate(); err != nil {
		// Разбор строки: `return "", err` — возвращаем пустую строку `""` вместо токена и ошибку `err`.
		// Разбор строки по каждому слову:
		//   - `return` — выйти из метода;
		//   - `"",`    — 1-й результат: пустая строка вместо JWT-токена;
		//   - `err`    — 2-й результат: ошибка валидации.
		return "", err
	}

	// ШАГ 2. Ищем пользователя в базе по почте.
	// Разбор строки по каждому слову:
	//   - `user, err`                         — создаём переменные `user` (`*models.User`) и `err` (`error`);
	//   - `:=`                                — объявляем и присваиваем;
	//   - `s.users.GetByEmail(ctx, in.Email)` — просим репозиторий `s.users` найти пользователя по почте `in.Email`.
	user, err := s.users.GetByEmail(ctx, in.Email)

	// Разбор строки по каждому слову:
	//   - `if`                                — если;
	//   - `errors.Is(err, models.ErrNotFound)` — ошибка `err` равна `models.ErrNotFound` (такой почты нет в БД);
	//   - `{`                                 — открываем блок.
	if errors.Is(err, models.ErrNotFound) {
		// ВАЖНОЕ ПРАВИЛО БЕЗОПАСНОСТИ:
		// Если почта не найдена, мы возвращаем общую ошибку "неверная почта ИЛИ пароль" (`ErrInvalidCredentials`),
		// а НЕ "такой почты не существует". Иначе злоумышленник мог бы перебирать чужие почты и узнавать,
		// кто зарегистрирован в нашем сервисе!
		// Разбор строки: `return "", models.ErrInvalidCredentials` — возвращаем пустую строку `""` и ошибку неверных данных.
		// Разбор строки по каждому слову:
		//   - `return`                       — выйти из метода;
		//   - `"",`                          — 1-й результат: пустая строка вместо токена;
		//   - `models.ErrInvalidCredentials` — 2-й результат: ошибка "неверная почта или пароль".
		return "", models.ErrInvalidCredentials
	}
	// Разбор строки: `if err != nil { return "", err }` — если случилась другая техническая ошибка БД, возвращаем её.
	// Разбор строки по каждому слову:
	//   - `if`         — если;
	//   - `err != nil` — переменная `err` не равна `nil` (произошла системная ошибка БД);
	//   - `{`          — открываем блок ошибки.
	if err != nil {
		// Разбор строки по каждому слову:
		//   - `return` — выйти из метода;
		//   - `"",`    — 1-й результат: пустая строка;
		//   - `err`    — 2-й результат: техническая ошибка БД.
		return "", err
	}

	// ШАГ 3. Сверяем введённый пароль `in.Password` с хешем из базы `user.PasswordHash`.
	// Разбор строки по каждому слову:
	//   - `if`                                                                     — если;
	//   - `err := bcrypt.CompareHashAndPassword([]byte(user.PasswordHash), []byte(in.Password));` — сверяем хеш и пароль;
	//   - `err != nil`                                                             — если пароль НЕ подошёл;
	//   - `{`                                                                      — открываем блок ошибки.
	if err := bcrypt.CompareHashAndPassword([]byte(user.PasswordHash), []byte(in.Password)); err != nil {
		// Пароль не подошёл — возвращаем ту же самую ошибку `ErrInvalidCredentials` (HTTP 401).
		// Разбор строки: `return "", models.ErrInvalidCredentials`.
		// Разбор строки по каждому слову:
		//   - `return`                       — выйти из метода;
		//   - `"",`                          — 1-й результат: пустая строка вместо токена;
		//   - `models.ErrInvalidCredentials` — 2-й результат: ошибка "неверная почта или пароль".
		return "", models.ErrInvalidCredentials
	}

	// ШАГ 4. Почта и пароль верные! Генерируем и возвращаем подписанный JWT-токен.
	// Разбор строки по каждому слову:
	//   - `return`                 — вернуть из метода `Login`;
	//   - `s.createToken(user.ID)` — вызываем наш приватный метод `createToken` для `user.ID`.
	return s.createToken(user.ID)
}

// Authenticate — проверяет строку JWT-токена и достаёт из неё `id` пользователя.
// Вызывается охранником `authMiddleware` перед каждым защищённым запросом.
//
// Разбор строки по каждому слову от начала до конца:
//   - `func`                 — объявляем метод;
//   - `(s *Service)`         — получатель метода (наш сервис `s`);
//   - `Authenticate`         — имя метода;
//   - `(tokenString string)` — входной параметр: строка токена `tokenString` типа `string`;
//   - `(int64, error)`       — возвращает ДВА значения:
//                              1) `int64` — ID пользователя-владельца токена (или `0` при ошибке);
//                              2) `error` — ошибку (или `nil`);
//   - `{`                    — открываем тело метода.
func (s *Service) Authenticate(tokenString string) (int64, error) {
	// Создаём пустую структуру стандартных полей JWT (куда запишутся Subject, IssuedAt, ExpiresAt).
	// Разбор строки: `claims := &jwt.RegisteredClaims{}` — создаём структуру `RegisteredClaims` и берём её адрес `&`.
	// Разбор строки по каждому слову:
	//   - `claims`                  — имя новой переменной;
	//   - `:=`                      — объявить и присвоить;
	//   - `&jwt.RegisteredClaims{}` — создаём пустую структуру `RegisteredClaims` из пакета `jwt` и берём её адрес `&`.
	claims := &jwt.RegisteredClaims{}

	// Разбираем и проверяем токен через `jwt.ParseWithClaims`.
	// Третий аргумент `func(t *jwt.Token) (any, error)` — это АНОНИМНАЯ ФУНКЦИЯ (функция-колбэк без имени),
	// которую библиотека `jwt` вызывает внутри себя, чтобы спросить у нас:
	// "Эй, мне пришёл вот такой токен `t`, дай мне секретный ключ, чтобы я проверила его подпись!".
	//
	// Разбор строки по каждому слову:
	//   - `token, err`                       — создаём переменные `token` и `err`;
	//   - `:=`                               — объявляем и присваиваем;
	//   - `jwt.ParseWithClaims(`             — функция разбора и проверки токена;
	//   - `tokenString,`                     — 1-й аргумент: строка токена;
	//   - `claims,`                          — 2-й аргумент: куда записать прочитанные данные из токена;
	//   - `func(t *jwt.Token) (any, error) {` — 3-й аргумент: функция проверки алгоритма и возврата ключа.
	token, err := jwt.ParseWithClaims(tokenString, claims, func(t *jwt.Token) (any, error) {
		// ЧТО ПРОИСХОДИТ В СТРОКЕ `if _, ok := t.Method.(*jwt.SigningMethodHMAC); !ok`?
		// Поле `t.Method` имеет тип `jwt.SigningMethod` — это ИНТЕРФЕЙС (подробные примеры про интерфейсы есть в handler.go).
		// Внутри этого интерфейса может лежать любой алгоритм подписи: HMAC, RSA или даже "none" (без подписи).
		// Запись `t.Method.(*jwt.SigningMethodHMAC)` называется УТВЕРЖДЕНИЕМ ТИПА (Type Assertion).
		// Она спрашивает у интерфейса: "А внутри тебя точно лежит алгоритм семейства HMAC (наш HS256)?"
		//   - Если да → `ok` будет `true`.
		//   - Если хакер подсунул другой алгоритм → `ok` будет `false`, и мы сразу отвергаем токен!
		//
		// Разбор строки по каждому слову:
		//   - `if`                                    — если;
		//   - `_, ok := t.Method.(*jwt.SigningMethodHMAC);` — проверяем тип внутри интерфейса `t.Method` (само значение отбрасываем в `_`, а флаг успеха кладём в `ok`);
		//   - `!ok`                                   — если НЕ `ok` (`!` = НЕ);
		//   - `{ return nil, models.ErrInvalidToken }` — отвергаем токен с ошибкой `ErrInvalidToken`.
		if _, ok := t.Method.(*jwt.SigningMethodHMAC); !ok {
			// Разбор строки по каждому слову:
			//   - `return`                 — выйти из анонимной функции проверки ключа;
			//   - `nil,`                   — 1-й результат: `nil` вместо секретного ключа;
			//   - `models.ErrInvalidToken` — 2-й результат: ошибка "недействительный токен".
			return nil, models.ErrInvalidToken
		}
		// Алгоритм правильный — отдаём наш секретный ключ `s.jwtSecret` для проверки подписи.
		// Разбор строки: `return s.jwtSecret, nil` — возвращаем секретный ключ и `nil`.
		// Разбор строки по каждому слову:
		//   - `return`       — вернуть из анонимной функции;
		//   - `s.jwtSecret,` — 1-й результат: наш секретный ключ `[]byte`;
		//   - `nil`          — 2-й результат: ошибок нет.
		return s.jwtSecret, nil
	})

	// Если подпись не сошлась, срок действия токена (`ExpiresAt`) истёк или строка испорчена:
	// Разбор строки по каждому слову:
	//   - `if`           — если;
	//   - `err != nil`   — есть ошибка разбора/подписи/срока;
	//   - `||`           — ИЛИ;
	//   - `token == nil` — токен пустой;
	//   - `||`           — ИЛИ;
	//   - `!token.Valid` — токен недействителен;
	//   - `{ return 0, models.ErrInvalidToken }` — возвращаем `0` и ошибку `ErrInvalidToken`.
	if err != nil || token == nil || !token.Valid {
		// Разбор строки по каждому слову:
		//   - `return`                 — выйти из метода `Authenticate`;
		//   - `0,`                     — 1-й результат: `0` вместо ID пользователя;
		//   - `models.ErrInvalidToken` — 2-й результат: ошибка "недействительный токен".
		return 0, models.ErrInvalidToken
	}

	// Достаём `id` пользователя из поля `claims.Subject` (там оно хранится как строка, например `"5"`).
	// Превращаем строку `"5"` в 64-битное целое число `int64` в десятичной системе счисления (`10`).
	// Разбор строки по каждому слову:
	//   - `id, err`                                  — создаём переменные `id` (`int64`) и `err` (`error`);
	//   - `:=`                                       — объявляем и присваиваем;
	//   - `strconv.ParseInt(claims.Subject, 10, 64)` — переводим строку `claims.Subject` в десятичное (`10`) число `int64` (`64`).
	id, err := strconv.ParseInt(claims.Subject, 10, 64)
	// Разбор строки: `if err != nil || id <= 0` — если в `Subject` было не число или `id <= 0`:
	// Разбор строки по каждому слову:
	//   - `if`         — если;
	//   - `err != nil` — не удалось перевести строку в число;
	//   - `||`         — ИЛИ;
	//   - `id <= 0`    — полученный ID меньше или равен нулю;
	//   - `{`          — открываем блок ошибки.
	if err != nil || id <= 0 {
		// Разбор строки по каждому слову:
		//   - `return`                 — выйти из метода;
		//   - `0,`                     — 1-й результат: `0` вместо ID;
		//   - `models.ErrInvalidToken` — 2-й результат: ошибка `ErrInvalidToken`.
		return 0, models.ErrInvalidToken
	}

	// Возвращаем проверенный `id` пользователя!
	// Разбор строки: `return id, nil`.
	// Разбор строки по каждому слову:
	//   - `return` — завершаем метод и возвращаем результат;
	//   - `id,`    — 1-й результат: числовой ID пользователя (`int64`);
	//   - `nil`    — 2-й результат: ошибок нет.
	return id, nil
}

// createToken — приватный метод, который собирает и подписывает JWT-токен для пользователя `userID`.
// Разбор строки по каждому слову от начала до конца:
//   - `func`            — объявляем метод;
//   - `(s *Service)`    — получатель метода `s`;
//   - `createToken`     — имя метода (с маленькой буквы = приватный);
//   - `(userID int64)`  — входной параметр: ID пользователя типа `int64`;
//   - `(string, error)` — возвращает строку токена `string` и ошибку `error`;
//   - `{`               — открываем тело метода.
func (s *Service) createToken(userID int64) (string, error) {
	// Фиксируем текущее время.
	// Разбор строки: `now := time.Now()` — вызываем `time.Now()` и сохраняем текущий момент в `now`.
	// Разбор строки по каждому слову:
	//   - `now`        — имя новой переменной;
	//   - `:=`         — объявить и присвоить;
	//   - `time.Now()` — функция из пакета `time`, возвращающая текущие дату и время.
	now := time.Now()

	// Заполняем "начинку" токена (Claims):
	// Разбор строки: `claims := jwt.RegisteredClaims{` — создаём структуру стандартных полей JWT.
	// Разбор строки по каждому слову:
	//   - `claims`                — имя переменной для полей токена;
	//   - `:=`                    — объявить и присвоить;
	//   - `jwt.RegisteredClaims{` — создаём структуру `RegisteredClaims` из пакета `jwt`.
	claims := jwt.RegisteredClaims{
		// Subject ("субъект" — кому выдан пропуск): превращаем число userID (например, 5) в строку "5".
		// Разбор строки: `Subject:` (поле владельца) `strconv.FormatInt(userID, 10),` (перевод числа в строку).
		// Разбор строки по каждому слову:
		//   - `Subject:`                      — поле "субъект" (владелец токена);
		//   - `strconv.FormatInt(userID, 10)` — функция перевода числа `userID` в десятичную (`10`) строку;
		//   - `,`                             — запятая после поля структуры.
		Subject: strconv.FormatInt(userID, 10),
		// IssuedAt ("когда выдан"): текущий момент времени.
		// Разбор строки: `IssuedAt:` (поле времени выдачи) `jwt.NewNumericDate(now),` (упаковка времени `now` в формат JWT).
		// Разбор строки по каждому слову:
		//   - `IssuedAt:`               — поле "время выпуска токена";
		//   - `jwt.NewNumericDate(now)` — переводит `now` в числовой формат даты JWT;
		//   - `,`                       — запятая после поля структуры.
		IssuedAt: jwt.NewNumericDate(now),
		// ExpiresAt ("когда протухнет"): текущее время + наше время жизни токена (например, +24 часа).
		// Разбор строки: `ExpiresAt:` (поле истечения срока) `jwt.NewNumericDate(now.Add(s.jwtTTL)),` (`now` плюс `s.jwtTTL`).
		// Разбор строки по каждому слову:
		//   - `ExpiresAt:`                           — поле "срок окончания действия токена";
		//   - `jwt.NewNumericDate(now.Add(s.jwtTTL))` — прибавляем к `now` длительность `s.jwtTTL` и упаковываем в дату JWT;
		//   - `,`                                    — запятая после поля структуры.
		ExpiresAt: jwt.NewNumericDate(now.Add(s.jwtTTL)),
	}

	// Создаём заготовку токена с алгоритмом подписи HS256 (HMAC + SHA256) и нашей начинкой `claims`.
	// Разбор строки: `token := jwt.NewWithClaims(jwt.SigningMethodHS256, claims)`.
	// Разбор строки по каждому слову:
	//   - `token`                  — имя новой переменной заготовки токена;
	//   - `:=`                     — объявить и присвоить;
	//   - `jwt.NewWithClaims(`     — функция создания нового токена с полями `claims`;
	//   - `jwt.SigningMethodHS256,` — 1-й аргумент: алгоритм подписи HMAC-SHA256;
	//   - `claims)`                — 2-й аргумент: подготовленные поля токена.
	token := jwt.NewWithClaims(jwt.SigningMethodHS256, claims)

	// Подписываем токен нашим секретным ключом `s.jwtSecret` и возвращаем готовую строку "eyJhbG...".
	// Разбор строки: `return token.SignedString(s.jwtSecret)` — подписывает токен и возвращает `(string, error)`.
	// Разбор строки по каждому слову:
	//   - `return`             — вернуть результат из метода `createToken`;
	//   - `token.SignedString(` — метод, который вычисляет криптографическую подпись и склеивает токен в строку;
	//   - `s.jwtSecret)`       — аргумент: наш секретный ключ `[]byte`.
	return token.SignedString(s.jwtSecret)
}
