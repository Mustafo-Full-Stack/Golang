	"context"
	// "errors" — для проверки типа ошибки через errors.Is.
	"errors"
	// "time" — для расчёта времени выдачи и времени истечения access/refresh токенов.
	"time"

	// Библиотека для создания и проверки JWT-токенов.
	"github.com/golang-jwt/jwt/v5"
	// Библиотека с алгоритмом хеширования паролей bcrypt.
	"golang.org/x/crypto/bcrypt"

