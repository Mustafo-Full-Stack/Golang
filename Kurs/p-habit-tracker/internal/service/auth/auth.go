// ФАЙЛ: internal/service/auth/auth.go
// ЗАЧЕМ НУЖЕН: СЕРВИС авторизации — это "мозг", отвечающий за пользователей и безопасность:
//   1. `Register`     — регистрация (проверить поля, зашифровать пароль через bcrypt, сохранить в БД);
//   2. `Login`        — вход (найти пользователя по почте, сверить пароль, выдать JWT-токен);
//   3. `Authenticate` — проверка JWT-токена (настоящий ли пропуск и какому userID он принадлежит).
//
// Обрати внимание на чистоту архитектуры:
// Сервис НЕ знает ничего про HTTP-заголовки или JSON (это работа Handler)
// и НЕ пишет SQL-запросы (это работа Repository). Сервис принимает бизнес-решения!
//
// ============================================================================
// ШПАРГАЛКА: КАК УСТРОЕН JWT-ТОКЕН, BCRYPT, СРЕЗЫ БАЙТОВ ([]byte) И ИНТЕРФЕЙСЫ
// ============================================================================
//
// 1. КАК УСТРОЕН JWT-ТОКЕН ВНУТРИ?
//    JWT (JSON Web Token) — это строка из ТРЁХ частей, разделённых точками:
//      `AAAAA.BBBBB.CCCCC`
//
//    - Часть 1 (`AAAAA`) — HEADER (Заголовок): каким алгоритмом подписан токен (у нас `HS256`).
//    - Часть 2 (`BBBBB`) — PAYLOAD / CLAIMS (Начинка): данные внутри пропуска.
//      Например: `{"sub": "5", "iat": 1730000000, "exp": 1730086400}`
//      ("это пользователь №5, токен выдан сегодня, действует до завтра").
//      ВАЖНО: Начинка НЕ зашифрована! Любой человек может раскодировать её через Base64 и прочитать.
//      Поэтому внутрь токена НИКОГДА не кладут пароли или секретные данные!
//    - Часть 3 (`CCCCC`) — SIGNATURE (Подпись сервера):
//      Сервер берёт `Часть1 + Часть2 + свой секретный ключ jwtSecret` и пропускает через формулу HMAC-SHA256.
//      Если хакер поменяет в начинке `"sub": "5"` на `"sub": "1"` (чтобы притвориться админом),
//      подпись `CCCCC` перестанет сходиться, и сервер сразу отвергнет подделку!
//
// 2. КАК РАБОТАЕТ ХЕШИРОВАНИЕ ПАРОЛЕЙ `bcrypt`?
//    Хеширование — это "мясорубка в одну сторону":
//      Пароль `"12345678"` ──(bcrypt)──► `"$2a$10$X8f...9kL"` (Хеш)
//    Превратить фарш обратно в мясо (узнать пароль из хеша) математически НЕВОЗМОЖНО.
//    Причём `bcrypt` автоматически добавляет в каждый пароль случайную примесь ("соль" / salt),
//    поэтому даже если два пользователя введут одинаковый пароль `"12345678"`, их хеши в базе будут РАЗНЫМИ!
//    А при входе `bcrypt.CompareHashAndPassword` берёт введённый пароль, пропускает через ту же мясорубку
//    и проверяет, совпал ли результат.
//
// 3. ЧТО ТАКОЕ `[]byte` (Срез байтов) И ЗАЧЕМ ПЕРЕВОДИТЬ `string` ↔ `[]byte`?
//    Строка `string` в Go — это неизменяемый текст.
//    А криптографические библиотеки (`bcrypt`, `jwt`) работают не с буквами, а с сырыми байтами `[]byte`.
//    Перевод делается очень просто:
//      b := []byte("привет") // превратили строку в срез байтов
//      s := string(b)        // превратили срез байтов обратно в строку
//
// ============================================================================
// 🧒 ОБЪЯСНЕНИЕ ДЛЯ 10-ЛЕТНЕГО РЕБЁНКА (НА ПАЛЬЦАХ С ПРИМЕРАМИ):
// ============================================================================
//
// 1. ЧТО ТАКОЕ JWT-ТОКЕН НА ПРИМЕРЕ БРАСЛЕТА В АКВАПАРКЕ?
//    Представь, что ты пришёл в огромный аквапарк с 20 водными горками.
//      - На входе в кассе (`Login`) ты один раз показываешь кассиру своё свидетельство о рождении и билет (почту и пароль).
//      - Кассир проверяет их и надевает тебе на запястье **непромокаемый браслет с блестящей печатью директора** (`JWT-токен`).
//        На браслете написано: `"Мальчик №5. Действует до 20:00"` (`Claims`).
//      - Теперь, когда ты бегаешь от горки к горке (`POST /habits`, `GET /habits`), тебе НЕ НУЖНО
//        таскать с собой в плавках бумажные документы и пароль!
//      - Ты просто поднимаешь руку с браслетом (`Authorization: Bearer ...`), инструктор на горке
//        за секунду светит фонариком на печать директора (`Authenticate`), видит, что браслет настоящий
//        и время ещё не 20:00, и кричит: "Мальчик №5, катись с горки!".
//
// 2. КАК РАБОТАЕТ `bcrypt` НА ПРИМЕРЕ ФРУКТОВОГО СМУЗИ В БЛЕНДЕРЕ?
//    Почему мы не записываем в базу настоящий пароль `"12345678"`, а превращаем его в `PasswordHash`?
//    Представь блендер (`bcrypt`):
//      - Ты кидаешь в блендер клубнику, банан и пломбир (твой пароль) и нажимаешь кнопку (`GenerateFromPassword`).
//      - Получается розовый смузи (Хеш пароля `"$2a$10$..."`). Его мы и ставим в холодильник (в базу данных).
//      - Если злой вор залезет в холодильник и украдёт стакан со смузи, сможет ли он достать из жижи
//        обратно целую квадратную дольку банана? НИКОГДА В ЖИЗНИ! Блендер крутит только в одну сторону!
//      - "А как же мы сами проверим пароль при входе (`Login`), если смузи нельзя разобрать обратно?!"
//        Очень просто! Когда ты приходишь утром и приносишь свои фрукты (`in.Password`), мы кидаем их
//        в тот же блендер и сравниваем вкус нового смузи со старым (`CompareHashAndPassword`).
//        Вкус совпал — значит, ты принёс те самые секретные фрукты!
//
// ============================================================================
// 🍕 ПРИМЕРЫ НА РЕСТОРАНЕ (2 НАГЛЯДНЫХ ПРИМЕРА):
// ============================================================================
//
// ПРИМЕР 1: Секретный соус Шеф-повара вместо открытого пароля (`Register` и `bcrypt`)
//   Когда гость регистрируется в закрытом VIP-ресторане (`Register`), он называет своё секретное слово (пароль).
//   Если записать это слово на бумажке в книге гостей, любой уборщик прочитает его и притворится этим гостем!
//   Поэтому Шеф-повар безопасности пропускает пароль через кулинарный комбайн `bcrypt.GenerateFromPassword`
//   и получает уникальный "секретный соус" (`PasswordHash`).
//   Когда гость приходит в ресторан на следующий день (`Login`), повар берёт названный пароль,
//   делает соус и пробует его через `bcrypt.CompareHashAndPassword`: если вкус соуса совпал — добро пожаловать!
//
// ПРИМЕР 2: Клубная карта VIP-гостя с сургучной печатью ресторана (`createToken` и `Authenticate`)
//   Чтобы гостю не приходилось называть пароль при заказе каждого блюда:
//     1) В `createToken(userID)`: менеджер ресторана выписывает гостю карточку:
//        `"Гость №5, карта действует 24 часа"` и ставит на неё личную сургучную печать ресторана (`s.jwtSecret`).
//     2) В `Authenticate(tokenString)`: когда гость заказывает блюдо и показывает карточку,
//        менеджер сначала проверяет через `t.Method.(*jwt.SigningMethodHMAC)` — "А это точно наша сургучная печать,
//        а не нарисованная фломастером?", затем сверяет оттиск с `s.jwtSecret` и возвращает номер гостя `id = 5`!
// ============================================================================

