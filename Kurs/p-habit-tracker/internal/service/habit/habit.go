// Service — структура сервиса привычек.
// Разбор строки по каждому слову:
//   - `type`    — создаём новый тип данных;
//   - `Service` — имя структуры;
//   - `struct`  — это структура;
//   - `{`       — открываем список полей.
type Service struct {
	// habits — указатель на репозиторий привычек.
	// Разбор строки: `habits` (имя приватного поля) `*habitrepo.Repository` (тип: указатель на репозиторий привычек).
	// Разбор строки по каждому слову:
	//   - `habits`                — имя приватного поля структуры;
	//   - `*habitrepo.Repository` — тип поля: указатель (`*`) на структуру `Repository` из пакета `habitrepo`.
	habits *habitrepo.Repository
}

// NewService — конструктор сервиса привычек.
// Разбор строки по каждому слову от начала до конца:
//   - `func`                          — объявляем функцию;
//   - `NewService`                    — имя функции-конструктора;
//   - `(habits *habitrepo.Repository)` — входной параметр: указатель на репозиторий привычек;
//   - `*Service`                      — возвращает указатель (`*`) на созданную структуру `Service`;
//   - `{`                             — открываем тело функции.
func NewService(habits *habitrepo.Repository) *Service {
	// Разбор строки: `return &Service{habits: habits}` — создаём структуру `Service`, заполняем поле `habits` и возвращаем адрес `&`.
	// Разбор строки по каждому слову:
	//   - `return`           — вернуть результат из функции;
	//   - `&Service{`        — создаём структуру `Service` и оператором `&` берём её адрес в памяти;
	//   - `habits: habits}` — в поле `habits` записываем параметр `habits` и закрываем скобку `}`.
	return &Service{habits: habits}
}

// Create — проверяет данные и создаёт новую привычку для пользователя.
// Разбор строки по каждому слову от начала до конца:
//   - `func`                        — объявляем метод;
//   - `(s *Service)`                — получатель метода (наш сервис `s`);
//   - `Create`                      — имя метода;
//   - `(ctx context.Context,`       — 1-й входной параметр: контекст запроса `ctx`;
//   - `in models.CreateHabitInput)` — 2-й входной параметр: структура `CreateHabitInput` (`UserID` и `Name`);
//   - `(*models.Habit, error)`      — возвращает указатель на созданную привычку `*models.Habit` и ошибку `error`;
//   - `{`                           — открываем тело метода.
func (s *Service) Create(ctx context.Context, in models.CreateHabitInput) (*models.Habit, error) {
	// ШАГ 1. Проверяем название привычки (обрезаем пробелы, проверяем, что не пустое и <= 100 символов).
	// Разбор строки по каждому слову:
	//   - `if`                    — если;
	//   - `err := in.Validate();` — вызываем метод `Validate()` у входных данных `in`;
	//   - `err != nil`            — если вернулась ошибка;
	//   - `{ return nil, err }`   — возвращаем `nil` и ошибку.
	if err := in.Validate(); err != nil {
		// Разбор строки по каждому слову:
		//   - `return` — выйти из метода;
		//   - `nil,`   — 1-й результат: `nil` вместо `*models.Habit`;
		//   - `err`    — 2-й результат: ошибка валидации.
		return nil, err
	}

	// ШАГ 2. Создаём структуру привычки в памяти.
	// Разбор строки по каждому слову:
	//   - `habit`                                      — имя новой переменной;
	//   - `:=`                                         — создать и присвоить;
	//   - `&models.Habit{UserID: in.UserID, Name: in.Name}` — создаём структуру `models.Habit` и берём её адрес `&`.
	habit := &models.Habit{UserID: in.UserID, Name: in.Name}

	// ШАГ 3. Сохраняем привычку в БД через репозиторий (он заполнит поля ID и CreatedAt).
	// Разбор строки: `if err := s.habits.Create(ctx, habit); err != nil { return nil, err }`.
	// Разбор строки по каждому слову:
	//   - `if`                                  — если;
	//   - `err := s.habits.Create(ctx, habit);` — вызываем метод `Create` у репозитория `s.habits` и сохраняем ошибку в `err`;
	//   - `err != nil`                          — если ошибка не равна `nil` (произошёл сбой при записи в БД);
	//   - `{`                                   — открываем блок ошибки.
	if err := s.habits.Create(ctx, habit); err != nil {
		// Разбор строки по каждому слову:
		//   - `return` — выйти из метода;
		//   - `nil,`   — 1-й результат: `nil` вместо привычки;
		//   - `err`    — 2-й результат: ошибка базы данных.
		return nil, err
	}

	// Разбор строки: `return habit, nil` — возвращаем указатель на созданную привычку и `nil`.
	// Разбор строки по каждому слову:
	//   - `return` — завершаем метод и возвращаем значения;
	//   - `habit,` — 1-й результат: указатель `*models.Habit` на созданную привычку;
	//   - `nil`    — 2-й результат: ошибок нет.
	return habit, nil
}

