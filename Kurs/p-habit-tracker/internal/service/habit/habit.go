// ФАЙЛ: internal/service/habit/habit.go
// ЗАЧЕМ НУЖЕН: СЕРВИС привычек — бизнес-логика работы с привычками.
//
// Главные бизнес-правила, которые контролирует этот сервис:
//   1. Валидация: название привычки не может быть пустым или длиннее 100 символов.
//   2. Безопасность (Авторизация доступа): пользователь может отмечать и смотреть
//      историю ТОЛЬКО СВОИХ привычек (`checkOwner`).
//   3. Работа с датами: галочка выполнения ставится строго за сегодняшний день (по UTC)
//      и не более одного раза в сутки.
//
// ============================================================================
// ШПАРГАЛКА: БЕЗОПАСНОСТЬ (401 против 403), ВРЕМЯ В UTC И ПРИНЦИП DRY
// ============================================================================
//
// 1. ЗАЧЕМ НУЖНА ПРОВЕРКА ВЛАДЕЛЬЦА `checkOwner` (И ЧТО ТАКОЕ УЯЗВИМОСТЬ IDOR)?
//    Представь: Пользователь №1 вошёл в свой аккаунт (у него есть настоящий токен)
//    и отправляет запрос: `POST /habits/99/check` (отметить привычку №99).
//    Но привычка №99 принадлежит Пользователю №2!
//
//    Если мы не проверим, чей это `habitID`, Пользователь №1 сможет портить чужие привычки,
//    просто перебирая цифры в адресе (`/habits/1/check`, `/habits/2/check`...).
//    В кибербезопасности такая дыра называется IDOR (Insecure Direct Object Reference).
//
//    Поэтому:
//      - `authMiddleware` проверяет: "КТО ТЫ?" (Аутентификация — если нет токена, код 401).
//      - `checkOwner` в сервисе проверяет: "А ТВОЯ ЛИ ЭТО ВЕЩЬ?" (Авторизация — если чужая, код 403 Forbidden).
//
// 2. ПОЧЕМУ В БЭКЕНДЕ ВРЕМЯ ВСЕГДА БЕРУТ В `.UTC()`?
//    Сервер может стоять в Германии, база данных — в США, а пользователь сидеть в Душанбе или Ташкенте.
//    Если каждый компьютер будет считать время по своим местным часам, возникнет путаница.
//    Поэтому в профессиональной разработке на сервере всегда используют единое всемирное время UTC (`time.Now().UTC()`).
//
// 3. ЧТО ТАКОЕ ПРИНЦИП DRY (Don't Repeat Yourself — "Не повторяй себя")?
//    Проверка владельца привычки нужна нам в двух местах: в методе `Check` и в методе `Checks`.
//    Вместо того чтобы копировать одни и те же 10 строк кода дважды, мы вынесли их
//    в маленький приватный метод `checkOwner`. Если логика проверки изменится —
//    нам нужно будет поправить код только в одном месте!
//
// ============================================================================
// 🧒 ОБЪЯСНЕНИЕ ДЛЯ 10-ЛЕТНЕГО РЕБЁНКА (НА ПАЛЬЦАХ С ПРИМЕРАМИ):
// ============================================================================
//
// 1. В ЧЁМ РАЗНИЦА МЕЖДУ ОШИБКОЙ `401 Unauthorized` И `403 Forbidden` (`checkOwner`)?
//    Представь свою школу:
//      - На входе в здание школы стоит турникет (`authMiddleware`).
//        Если ты забыл дома школьную карточку-пропуск (нет JWT-токена), турникет пищит красным:
//        **"Ошибка 401 — Я тебя не знаю, вход в школу закрыт!"**.
//      - Но допустим, карточка у тебя с собой! Турникет пустил тебя внутрь школы (ты прошёл `authMiddleware`, ты ученик №5).
//        Ты идёшь по коридору, подходишь к чужому шкафчику №99 (который принадлежит отличнику Васе — ученику №2)
//        и пытаешься открыть его дверцу (`POST /habits/99/check`)!
//      - Тут тебя хватает за руку дежурный учитель (`checkOwner`), смотрит в журнал:
//        "Шкафчик №99 записан на Васю (`habit.UserID = 2`), а ты у нас кто? Ученик №5 (`userID = 5`)!
//        Я знаю, кто ты такой, но трогать ЧУЖОЙ шкафчик ЗАПРЕЩЕНО! **Ошибка 403 Forbidden!**".
//
// 2. ЗАЧЕМ В `Check` МЫ ОБНУЛЯЕМ ЧАСЫ, МИНУТЫ И СЕКУНДЫ (`0, 0, 0, 0`)?
//    Представь, что мама обещала давать тебе 1 конфету в день за чистку зубов.
//    Если записывать в блокнот точное время с секундами: `"5 ноября, 08:15:23"`,
//    то через две секунды в `"08:15:25"` ты скажешь: "Мама, время-то уже другое, давай вторую конфету!".
//    Поэтому мама хитрая: она отрезает часы, минуты и секунды ножницами (`0, 0, 0, 0`)
//    и записывает в блокнот просто `"5 ноября, 00:00:00"`.
//    Когда ты придёшь вечером второй раз, мама увидит, что запись `"5 ноября, 00:00:00"` уже есть,
//    и скажет: "На сегодня конфета уже выдана!" (`ErrAlreadyChecked`).
//
// ============================================================================
// 🍕 ПРИМЕРЫ НА РЕСТОРАНЕ (2 НАГЛЯДНЫХ ПРИМЕРА):
// ============================================================================
//
// ПРИМЕР 1: Чужой забронированный столик в ресторане (`checkOwner` — 401 против 403)
//   Представь 2 ситуации в нашем ресторане:
//     - Ситуация 1 (`401 Unauthorized`): человек с улицы без клубной карты ресторана пытается зайти в зал.
//       Охрана на входе (`authMiddleware`) останавливает его: "Мы не знаем, кто вы! Покажите карту!".
//     - Ситуация 2 (`403 Forbidden` в `checkOwner`): Гость №5 показал настоящую карту и вошёл в ресторан.
//       Но внутри зала он подходит к Столику №99, который забронирован на Гостя №2 (`habit.UserID = 2`),
//       и требует принести счёт или блюдо с чужого столика (`Check` / `Checks`)!
//       Шеф-менеджер зала вызывает `s.checkOwner(ctx, userID, habitID)`, видит, что `habit.UserID != userID` (`2 != 5`),
//       и говорит: "Уважаемый Гость №5, мы вас знаем, но Столик №99 — ЧУЖОЙ! Ошибка 403 Forbidden!".
//
// ПРИМЕР 2: Единые часы кухни ресторана (`.UTC()` и обнуление времени в `Check`)
//   У нашего ресторана могут быть гости из разных часовых поясов. Чтобы повара не путались,
//   на кухне висят одни главные мировые часы по Гринвичу: `now := time.Now().UTC()`.
//   А когда гость отмечает дневной абонемент на обед, мы записываем в журнал только год, месяц и день
//   (`today := time.Date(now.Year(), now.Month(), now.Day(), 0, 0, 0, 0, time.UTC)`),
//   чтобы ровно один день соответствовал ровно одному обеду!
// ============================================================================

