// Check — ставит отметку "выполнено сегодня" для привычки `habitID`.
// Разбор строки по каждому слову от начала до конца:
//   - `func`                   — объявляем метод;
//   - `(s *Service)`           — получатель метода `s`;
//   - `Check`                  — имя метода;
//   - `(ctx context.Context,`  — 1-й входной параметр: контекст `ctx`;
//   - `userID, habitID int64)` — 2-й и 3-й входные параметры: `userID` и `habitID`, оба типа `int64`;
//   - `error`                  — возвращает ошибку `error` (или `nil`);
//   - `{`                      — открываем тело метода.
func (s *Service) Check(ctx context.Context, userID, habitID int64) error {
	// ШАГ 1. Проверяем, существует ли привычка `habitID` и принадлежит ли она пользователю `userID`.
	// Разбор строки по каждому слову:
	//   - `if`                                         — если;
	//   - `err := s.checkOwner(ctx, userID, habitID);` — вызываем наш метод проверки владельца;
	//   - `err != nil`                                 — если привычка не найдена (404) или чужая (403);
	//   - `{ return err }`                             — возвращаем ошибку.
	if err := s.checkOwner(ctx, userID, habitID); err != nil {
		// Разбор строки по каждому слову:
		//   - `return` — выйти из метода;
		//   - `err`    — вернуть ошибку проверки владельца (`ErrNotFound` или `ErrForbidden`).
		return err
	}

	// ШАГ 2. Вычисляем "сегодняшний день" с обнулённым временем (00 часов, 00 минут, 00 секунд).
	// Например: если сейчас `2026-11-05 18:45:12 UTC`, то `today` станет `2026-11-05 00:00:00 UTC`.
	// Зачем мы обнуляем часы и секунды?
	// Чтобы в базе хранилась чистая дата дня, и уникальное ограничение `UNIQUE(habit_id, date)`
	// не давало поставить вторую галочку в этот же день через минуту!
	//
	// Разбор строки: `now := time.Now().UTC()` — берём текущее время и переводим в часовой пояс UTC.
	// Разбор строки по каждому слову:
	//   - `now`        — имя новой переменной;
	//   - `:=`         — объявить и присвоить;
	//   - `time.Now()` — получить текущее время;
	//   - `.UTC()`     — перевести время во всемирный часовой пояс UTC.
	now := time.Now().UTC()
	// Разбор строки: `today := time.Date(now.Year(), now.Month(), now.Day(), 0, 0, 0, 0, time.UTC)` —
	// собираем дату из текущего года, месяца и дня, а часы, минуты, секунды и наносекунды обнуляем (`0`).
	// Разбор строки по каждому слову:
	//   - `today`                                       — имя переменной для сегодняшней даты;
	//   - `:=`                                          — объявить и присвоить;
	//   - `time.Date(`                                  — функция сборки даты из пакета `time`;
	//   - `now.Year(), now.Month(), now.Day(),`         — текущий год, месяц и день;
	//   - `0, 0, 0, 0,`                                 — 0 часов, 0 минут, 0 секунд, 0 наносекунд;
	//   - `time.UTC)`                                   — часовой пояс UTC.
	today := time.Date(now.Year(), now.Month(), now.Day(), 0, 0, 0, 0, time.UTC)

	// ШАГ 3. Сохраняем галочку в базу данных.
	// Разбор строки: `return s.habits.CreateCheck(ctx, habitID, today)` — вызываем `CreateCheck` у репозитория.
	// Разбор строки по каждому слову:
	//   - `return`                     — вернуть результат из метода;
	//   - `s.habits.CreateCheck(`      — вызываем метод `CreateCheck` у репозитория `s.habits`;
	//   - `ctx, habitID, today)`       — передаём контекст `ctx`, ID привычки `habitID` и дату `today`.
	return s.habits.CreateCheck(ctx, habitID, today)
}

// Checks — возвращает список всех дат, когда привычка `habitID` была выполнена.
// Разбор строки по каждому слову от начала до конца:
//   - `func`                         — объявляем метод;
//   - `(s *Service)`                 — получатель метода `s`;
//   - `Checks`                       — имя метода;
//   - `(ctx context.Context,`        — 1-й входной параметр: контекст `ctx`;
//   - `userID, habitID int64)`       — 2-й и 3-й входные параметры: `userID` и `habitID` типа `int64`;
//   - `([]models.HabitCheck, error)` — возвращает слайс отметок `[]models.HabitCheck` и ошибку `error`;
//   - `{`                            — открываем тело метода.
func (s *Service) Checks(ctx context.Context, userID, habitID int64) ([]models.HabitCheck, error) {
	// ШАГ 1. Сначала убеждаемся, что привычка существует и принадлежит именно этому пользователю.
	// Разбор строки: `if err := s.checkOwner(ctx, userID, habitID); err != nil { return nil, err }`.
	// Разбор строки по каждому слову:
	//   - `if`                                         — если;
	//   - `err := s.checkOwner(ctx, userID, habitID);` — вызываем проверку владельца и сохраняем результат в `err`;
	//   - `err != nil`                                 — если ошибка не равна `nil`;
	//   - `{`                                          — открываем блок ошибки.
	if err := s.checkOwner(ctx, userID, habitID); err != nil {
		// Разбор строки по каждому слову:
		//   - `return` — выйти из метода;
		//   - `nil,`   — 1-й результат: пустой слайс `nil`;
		//   - `err`    — 2-й результат: ошибка доступа или 404.
		return nil, err
	}

	// ШАГ 2. Достаём из репозитория историю отметок.
	// Разбор строки: `return s.habits.ListChecks(ctx, habitID)`.
	// Разбор строки по каждому слову:
	//   - `return`                 — вернуть результат из метода;
	//   - `s.habits.ListChecks(`   — вызываем метод `ListChecks` у репозитория `s.habits`;
	//   - `ctx, habitID)`          — передаём контекст `ctx` и ID привычки `habitID`.
	return s.habits.ListChecks(ctx, habitID)
}

// checkOwner — приватный метод-помощник: проверяет, что привычка `habitID` принадлежит `userID`.
// Разбор строки по каждому слову от начала до конца:
//   - `func`                   — объявляем метод;
//   - `(s *Service)`           — получатель метода `s`;
//   - `checkOwner`             — имя метода (с маленькой буквы = приватный);
//   - `(ctx context.Context,`  — 1-й входной параметр: контекст `ctx`;
//   - `userID, habitID int64)` — 2-й и 3-й входные параметры: `userID` и `habitID` типа `int64`;
//   - `error`                  — возвращает ошибку `error` (или `nil`, если доступ разрешён);
//   - `{`                      — открываем тело метода.
func (s *Service) checkOwner(ctx context.Context, userID, habitID int64) error {
	// Ищем привычку в базе данных по её ID.
	// Если такой привычки вообще нет — репозиторий вернёт `models.ErrNotFound` (HTTP 404).
	// Разбор строки: `habit, err := s.habits.GetByID(ctx, habitID)` — получаем привычку по `habitID`.
	// Разбор строки по каждому слову:
	//   - `habit, err`                   — создаём переменные `habit` (`*models.Habit`) и `err` (`error`);
	//   - `:=`                           — объявить и присвоить;
	//   - `s.habits.GetByID(ctx, habitID)` — вызываем метод `GetByID` у репозитория `s.habits`.
	habit, err := s.habits.GetByID(ctx, habitID)
	// Разбор строки: `if err != nil { return err }` — если привычка не найдена или ошибка БД, возвращаем ошибку.
	// Разбор строки по каждому слову:
	//   - `if`         — если;
	//   - `err != nil` — переменная `err` не равна `nil` (привычка не найдена или ошибка БД);
	//   - `{`          — открываем блок ошибки.
	if err != nil {
		// Разбор строки по каждому слову:
		//   - `return` — выйти из метода;
		//   - `err`    — вернуть ошибку `err`.
		return err
	}

	// Сравниваем владельца привычки (`habit.UserID`) с тем, кто прислал запрос (`userID`).
	// Оператор `!=` означает "НЕ РАВНО".
	// Разбор строки по каждому слову:
	//   - `if`                     — если;
	//   - `habit.UserID != userID` — владелец привычки не равен текущему пользователю;
	//   - `{`                      — открываем блок ошибки.
	if habit.UserID != userID {
		// Чужая привычка! Возвращаем ошибку доступа `models.ErrForbidden` (HTTP 403).
		// Разбор строки: `return models.ErrForbidden`.
		// Разбор строки по каждому слову:
		//   - `return`              — выйти из метода;
		//   - `models.ErrForbidden` — вернуть ошибку "доступ запрещён" из пакета `models`.
		return models.ErrForbidden
	}

	// Владелец совпал — доступ разрешён!
	// Разбор строки: `return nil`.
	// Разбор строки по каждому слову:
	//   - `return` — завершить метод;
	//   - `nil`    — вернуть `nil` (ошибок нет, пользователь является владельцем).
	return nil
}
