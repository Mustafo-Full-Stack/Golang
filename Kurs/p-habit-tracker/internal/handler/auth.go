// signUp — HTTP-обработчик для регистрации нового пользователя (`POST /sign-up`).
//
// Вспомним параметры любого обработчика в стандартной библиотеке `net/http`:
//   - `w http.ResponseWriter` (ИНТЕРФЕЙС) — "лист бумаги", куда мы пишем ответ клиенту.
//   - `r *http.Request`       (УКАЗАТЕЛЬ НА СТРУКТУРУ) — пришедшее письмо от клиента (с заголовками, адресом и телом `r.Body`).
//
// Разбор строки по каждому слову от начала до конца:
//   - `func`                    — ключевое слово объявления метода;
//   - `(h *Handler)`            — получатель метода (наш `Handler`, внутри него лежит `h.auth`);
//   - `signUp`                  — имя метода-обработчика;
//   - `(w http.ResponseWriter,` — 1-й параметр: интерфейс `http.ResponseWriter` для записи ответа;
//   - `r *http.Request)`        — 2-й параметр: указатель `*http.Request` с данными входящего запроса;
//   - `{`                       — открываем тело метода.
func (h *Handler) signUp(w http.ResponseWriter, r *http.Request) {
	// ========================================================================
	// ШАГ 1. Читаем и разбираем JSON из тела запроса `r.Body`
	// ========================================================================
	// Разбор строки: `var req signUpRequest` — создаём пустую структуру `req` для данных запроса.
	// Разбор строки по каждому слову:
	//   - `var`           — объявляем переменную;
	//   - `req`           — имя переменной;
	//   - `signUpRequest` — тип переменной (наша структура с полями `Name`, `Email`, `Password`).
	var req signUpRequest

	// `json.NewDecoder(r.Body).Decode(&req)` читает поток байтов из тела запроса
	// и раскладывает JSON по полям структуры `req`.
	// Почему мы передаём `&req` (с амперсандом `&`)?
	// Потому что `Decode` должен ЗАПОЛНИТЬ нашу переменную `req`! Без `&` он получил бы пустую копию.
	//
	// Разбор строки по каждому слову:
	//   - `if`                                        — если;
	//   - `err := json.NewDecoder(r.Body).Decode(&req);` — создаём декодер для тела запроса `r.Body` и разбираем JSON по адресу `&req`;
	//   - `err != nil`                                — если JSON сломан и вернулась ошибка;
	//   - `{`                                         — открываем блок обработки ошибки.
	if err := json.NewDecoder(r.Body).Decode(&req); err != nil {
		// Если клиент прислал кривой JSON (например, забыл закрыть кавычку или скобку),
		// отвечаем статусом 400 Bad Request.
		// Разбор строки: `writeError(w, http.StatusBadRequest, "invalid request body")` — отправляем код 400 и текст ошибки.
		// Разбор строки по каждому слову:
		//   - `writeError(`            — вызываем функцию отправки JSON-ошибки;
		//   - `w,`                     — 1-й аргумент: интерфейс ответа;
		//   - `http.StatusBadRequest,`  — 2-й аргумент: код `400 Bad Request`;
		//   - `"invalid request body")` — 3-й аргумент: текст ошибки.
		writeError(w, http.StatusBadRequest, "некорректное тело запроса")
		// ОБЯЗАТЕЛЬНО пишем `return`, чтобы остановить выполнение функции!
		// Если забыть `return`, код пойдёт дальше на Шаг 2 с пустыми данными.
		// Разбор строки по каждому слову:
		//   - `return` — немедленно завершаем выполнение обработчика `signUp`.
		return
	}

	// ========================================================================
	// ШАГ 2. Вызываем бизнес-логику (Сервис авторизации)
	// ========================================================================
	// Перекладываем данные из HTTP-структуры `req` в структуру сервиса `models.RegisterInput`.
	// `r.Context()` — достаём контекст текущего HTTP-запроса и передаём его дальше в сервис и БД.
	//
	// Разбор строки по каждому слову:
	//   - `user, err`       — создаём переменные `user` (`*models.User`) и `err` (`error`);
	//   - `:=`              — объявляем и присваиваем;
	//   - `h.auth.Register(` — вызываем метод `Register` у сервиса авторизации `h.auth`;
	//   - `r.Context(),`    — 1-й аргумент: контекст HTTP-запроса;
	//   - `models.RegisterInput{...})` — 2-й аргумент: структура с именем, почтой и паролем из `req`.
	user, err := h.auth.Register(r.Context(), models.RegisterInput{
		// Разбор строки по каждому слову:
		//   - `Name:`     — поле `Name` структуры `models.RegisterInput`;
		//   - `req.Name,` — имя из прочитанного JSON-запроса `req`.
		Name: req.Name,
		// Разбор строки по каждому слову:
		//   - `Email:`     — поле `Email` структуры `models.RegisterInput`;
		//   - `req.Email,` — почта из прочитанного JSON-запроса `req`.
		Email: req.Email,
		// Разбор строки по каждому слову:
		//   - `Password:`     — поле `Password` структуры `models.RegisterInput`;
		//   - `req.Password,` — пароль из прочитанного JSON-запроса `req`.
		Password: req.Password,
	})
	// Разбор строки: `if err != nil {` — если сервис вернул ошибку:
	// Разбор строки по каждому слову:
	//   - `if`         — если;
	//   - `err != nil` — переменная `err` не равна `nil` (регистрация не прошла);
	//   - `{`          — открываем блок ошибки.
	if err != nil {
		// Если сервис вернул ошибку (короткий пароль, пустая почта, почта уже занята),
		// наша функция `writeErr` (из `handler.go`) сама выберет код 400, 409 или 500!
		// Разбор строки по каждому слову:
		//   - `writeErr(` — вызываем функцию перевода ошибки в HTTP-статус;
		//   - `w, err)`   — передаём интерфейс ответа `w` и ошибку `err`.
		writeErr(w, err)
		// Разбор строки по каждому слову:
		//   - `return` — выходим из обработчика `signUp`.
		return
	}

	// ========================================================================
	// ШАГ 3. Отправляем успешный ответ клиенту
	// ========================================================================
	// Статус `http.StatusCreated` (201) по стандарту HTTP означает "Успешно создана новая запись".
	// В теле ответа возвращаем словарь `map[string]int64{"id": user.ID}`,
	// который превратится в JSON: `{"id": 1}`.
	//
	// Разбор строки по каждому слову:
	//   - `writeJSON(`                  — вызываем функцию отправки JSON;
	//   - `w,`                          — 1-й аргумент: куда писать ответ;
	//   - `http.StatusCreated,`         — 2-й аргумент: статус 201 Created;
	//   - `map[string]int64{"id": user.ID})` — 3-й аргумент: словарь с ключом `"id"` и числом `user.ID`.
	writeJSON(w, http.StatusCreated, map[string]int64{"id": user.ID})
}

// login — HTTP-обработчик для входа в аккаунт (`POST /login`).
// Разбор строки по каждому слову от начала до конца:
//   - `func`                    — объявляем метод;
//   - `(h *Handler)`            — получатель метода `h`;
//   - `login`                   — имя метода;
//   - `(w http.ResponseWriter,` — 1-й параметр: интерфейс ответа `w`;
//   - `r *http.Request)`        — 2-й параметр: указатель на запрос `r`;
//   - `{`                       — открываем тело метода.
func (h *Handler) login(w http.ResponseWriter, r *http.Request) {
	// ========================================================================
	// ШАГ 1. Читаем JSON с почтой и паролем из тела запроса
	// ========================================================================
	// Разбор строки: `var req loginRequest` — создаём пустую структуру для чтения JSON.
	// Разбор строки по каждому слову:
	//   - `var`          — объявляем переменную;
	//   - `req`          — имя переменной;
	//   - `loginRequest` — тип структуры (с полями `Email` и `Password`).
	var req loginRequest
	// Разбор строки: разбираем JSON из `r.Body` по адресу `&req`; если ошибка — отвечаем 400 и выходим.
	// Разбор строки по каждому слову:
	//   - `if`                                        — если;
	//   - `err := json.NewDecoder(r.Body).Decode(&req);` — читаем JSON из тела запроса `r.Body` в структуру по адресу `&req`;
	//   - `err != nil`                                — если JSON некорректный;
	//   - `{`                                         — открываем блок ошибки.
	if err := json.NewDecoder(r.Body).Decode(&req); err != nil {
		// Разбор строки по каждому слову:
		//   - `writeError(`             — вызываем функцию отправки ошибки;
		//   - `w,`                      — 1-й аргумент: интерфейс ответа;
		//   - `http.StatusBadRequest,`  — 2-й аргумент: статус `400 Bad Request`;
		//   - `"invalid request body")` — 3-й аргумент: текст ошибки.
		writeError(w, http.StatusBadRequest, "некорректное тело запроса")
		// Разбор строки по каждому слову:
		//   - `return` — завершаем выполнение обработчика `login`.
		return
	}

	// ========================================================================
	// ШАГ 2. Просим сервис проверить почту/пароль и сгенерировать JWT-токен
	// ========================================================================
	// Разбор строки по каждому слову:
	//   - `token, err`    — создаём переменные `token` (строка JWT) и `err` (ошибка);
	//   - `:=`            — объявляем и присваиваем;
	//   - `h.auth.Login(` — вызываем метод `Login` у сервиса `h.auth`, передавая `r.Context()` и `models.LoginInput`.
	token, err := h.auth.Login(r.Context(), models.LoginInput{
		// Разбор строки по каждому слову:
		//   - `Email:`     — поле `Email` структуры `models.LoginInput`;
		//   - `req.Email,` — почта из прочитанного JSON-запроса `req`.
		Email: req.Email,
		// Разбор строки по каждому слову:
		//   - `Password:`     — поле `Password` структуры `models.LoginInput`;
		//   - `req.Password,` — пароль из прочитанного JSON-запроса `req`.
		Password: req.Password,
	})
	// Разбор строки по каждому слову:
	//   - `if`         — если;
	//   - `err != nil` — переменная `err` не равна `nil` (почта не найдена или пароль не подошёл);
	//   - `{`          — открываем блок ошибки.
	if err != nil {
		// Если почта не найдена или пароль не подошёл — `writeErr` отправит 401 Unauthorized.
		// Разбор строки по каждому слову:
		//   - `writeErr(` — вызываем переводчик ошибок в HTTP-ответ;
		//   - `w, err)`   — передаём `w` и ошибку `err`.
		writeErr(w, err)
		// Разбор строки по каждому слову:
		//   - `return` — выходим из обработчика `login`.
		return
	}

	// ========================================================================
	// ШАГ 3. Отправляем клиенту статус 200 OK и выданный токен: `{"token": "eyJhbG..."}`
	// ========================================================================
	// Разбор строки: `writeJSON(w, http.StatusOK, map[string]string{"token": token})`.
	// Разбор строки по каждому слову:
	//   - `writeJSON(`                        — вызываем функцию отправки JSON-ответа;
	//   - `w,`                                — 1-й аргумент: интерфейс ответа;
	//   - `http.StatusOK,`                    — 2-й аргумент: статус `200 OK`;
	//   - `map[string]string{"token": token})` — 3-й аргумент: словарь с ключом `"token"` и строкой JWT-токена.
	writeJSON(w, http.StatusOK, map[string]string{"token": token})
}
