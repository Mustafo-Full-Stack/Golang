// ============================================================================
// ФАЙЛ: internal/handler/auth.go
// ЗАЧЕМ НУЖЕН: HTTP-обработчики для регистрации (`POST /sign-up`) и входа (`POST /login`).
//
// ЗОЛОТОЕ ПРАВИЛО ЛЮБОГО ОБРАБОТЧИКА (HANDLER) В GO:
// Любой обработчик делает ровно 3 простых шага:
//   Шаг 1. Принять и распаковать входящие данные из HTTP-запроса (прочитать JSON).
//   Шаг 2. Передать эти данные в Сервис (`h.auth.Register` / `h.auth.Login`).
//   Шаг 3. Упаковать ответ сервиса в JSON и отправить клиенту (или отправить ошибку через `writeErr`).
//
// ============================================================================
// ШПАРГАЛКА ПО GO: СТРУКТУРНЫЕ ТЕГИ (`json:"..."`) И JSON В GO
// ============================================================================
//
// 1. ЧТО ТАКОЕ ТЕГИ СТРУКТУРЫ (`` `json:"name"` ``)?
//    В Go поля структур принято называть с Большой Буквы (`Name`, `Email`, `Password`),
//    а в мире веб-разработки (JSON) ключи принято писать маленькими буквами (`"name"`, `"email"`).
//
//    Тег `` `json:"name"` `` справа от поля — это подсказка для пакета `encoding/json`:
//      - При чтении запроса (Decode): "Возьми из JSON поле `"name"` и положи в Go-поле `Name`".
//      - При отправке ответа (Encode): "Возьми Go-поле `Name` и назови его в JSON `"name"`".
//
//    ОЧЕНЬ ВАЖНАЯ ЛОВУШКА ДЛЯ НОВИЧКОВ:
//    Поля структуры для JSON (`Name`, `Email`, `Password`) ОБЯЗАНЫ начинаться с БОЛЬШОЙ буквы!
//    Если написать `name string` с маленькой буквы, чужой пакет `encoding/json` просто НЕ УВИДИТ
//    приватное поле, и оно всегда будет оставаться пустым `""`, даже если тег написан правильно!
//
// 2. ЗАЧЕМ НУЖНЫ ОТДЕЛЬНЫЕ СТРУКТУРЫ `signUpRequest` И `loginRequest`,
//    ЕСЛИ У НАС УЖЕ ЕСТЬ `models.User` И `models.RegisterInput`?
//    Это разделение ответственности между слоями:
//      - `signUpRequest` — знает про HTTP и JSON-теги.
//      - `models.User` — знает про бизнес-модель и базу данных (там есть `PasswordHash` и `CreatedAt`).
//    Если мы завтра поменяем формат JSON, нам не придётся переделывать сервисы и базу данных!
//
// ============================================================================
// 🧒 ОБЪЯСНЕНИЕ ДЛЯ 10-ЛЕТНЕГО РЕБЁНКА (НА ПАЛЬЦАХ С ПРИМЕРАМИ):
// ============================================================================
//
// 1. ЧТО ТАКОЕ JSON И ТЕГИ `` `json:"name"` ``?
//    Представь, что мобильное приложение на телефоне — это иностранец, который пишет письма
//    только маленькими буквами в фигурных скобках: `{"name": "Али", "email": "ali@mail.com"}`.
//    Этот язык писем в интернете называется **JSON**.
//
//    Когда такое письмо прилетает к нам на сервер в `r.Body`, его встречает робот-почтальон `json.NewDecoder`.
//    Робот смотрит на нашу структуру `signUpRequest` и видит наклейки (теги) справа от полей:
//      `Name string` `` `json:"name"` ``
//    Наклейка `` `json:"name"` `` говорит роботу-почтальону:
//    "То, что в письме написано после слова `"name"`, переложи в ящик `Name`!".
//
// 2. ПОЧЕМУ ПОЛЕ `Name` ОБЯЗАТЕЛЬНО С БОЛЬШОЙ БУКВЫ, А НЕ `name` С МАЛЕНЬКОЙ?
//    Представь, что ящик с Большой буквы (`Name`) — это открытый почтовый ящик на двери,
//    куда почтальон из чужого пакета `encoding/json` спокойно может положить письмо.
//    А ящик с маленькой буквы (`name`) — это твой личный тайник под кроватью, закрытый на замок!
//    Чужой почтальон `encoding/json` просто не имеет права лазить в чужие тайники с маленькой буквы,
//    поэтому письмо туда никогда не попадёт!
//
// ============================================================================
// 🍕 ПРИМЕРЫ НА РЕСТОРАНЕ (2 НАГЛЯДНЫХ ПРИМЕРА):
// ============================================================================
//
// ПРИМЕР 1: Бланк анкеты гостя ресторана (`signUpRequest` и структурные теги `` `json:"..."` ``)
//   Когда новый гость приходит в ресторан (`POST /sign-up`), он заполняет бумажную карточку на стойке:
//     `{"name": "Мустафо", "email": "mustafo@mail.com", "password": "secretpassword"}`
//   Официант (`signUp`) берёт эту карточку из `r.Body` и с помощью сканера `json.NewDecoder(r.Body).Decode(&req)`
//   переносит данные в компьютерную анкету `signUpRequest`.
//   Наклейки `` `json:"name"` `` подсказывают сканеру, какую строчку с бумажки в какую графу анкеты переписать!
//
// ПРИМЕР 2: Три шага работы Официанта при выдаче Клубной Карты (`signUp` и `login`)
//   Посмотри на код методов `signUp` и `login` — официант в ресторане всегда работает строго в 3 шага:
//     - Шаг 1 (`Decode(&req)`): Официант читает бланк заказа от гостя. Если бланк залит кофе и ничего
//       не прочитать (`err != nil`) — официант даже не идёт на кухню, а сразу говорит гостю: `400 Bad Request`!
//     - Шаг 2 (`h.auth.Register` / `h.auth.Login`): Официант относит проверенный бланк управляющему (`h.auth`).
//       Управляющий проверяет гостя по базе и штампует клубную карту (`token`).
//     - Шаг 3 (`writeJSON`): Официант выносит гостю на подносе готовую клубную карту `{"token": "eyJ..."}` со статусом `200 OK`!
// ============================================================================

