// signUpRequest — описывает JSON, который мы ждём от клиента при регистрации (`POST /sign-up`):
//
//	{
//	    "name": "Mustafo",
//	    "email": "mustafo@example.com",
//	    "password": "secretpassword"
//	}
//
// Сама структура `signUpRequest` с маленькой буквы (нужна только внутри пакета `handler`),
// но поля внутри неё — с БОЛЬШОЙ буквы, чтобы пакет `encoding/json` имел к ним доступ!
//
// Разбор строки по каждому слову:
//   - `type`          — объявляем новый тип;
//   - `signUpRequest` — имя структуры (с маленькой буквы = приватная для пакета `handler`);
//   - `struct`        — это структура;
//   - `{`             — открываем поля.
type signUpRequest struct {
	// Разбор строки по каждому слову:
	//   - `Name`          — имя поля (с Большой буквы!);
	//   - `string`        — тип поля: строка;
	//   - `` `json:"name"` `` — структурный тег: связывает это поле с ключом `"name"` в JSON.
	Name string `json:"name"`
	// Разбор строки: поле `Email` типа `string`, связанное с ключом `"email"` в JSON.
	// Разбор строки по каждому слову:
	//   - `Email`          — имя поля (с Большой буквы);
	//   - `string`         — тип поля: строка;
	//   - `` `json:"email"` `` — структурный тег: связывает это поле с ключом `"email"` в JSON.
	Email string `json:"email"`
	// Разбор строки: поле `Password` типа `string`, связанное с ключом `"password"` в JSON.
	// Разбор строки по каждому слову:
	//   - `Password`          — имя поля (с Большой буквы);
	//   - `string`            — тип поля: строка;
	//   - `` `json:"password"` `` — структурный тег: связывает это поле с ключом `"password"` в JSON.
	Password string `json:"password"`
}

