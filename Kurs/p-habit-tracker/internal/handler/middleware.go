// ФАЙЛ: internal/handler/middleware.go
// ЗАЧЕМ НУЖЕН: здесь живёт `authMiddleware` — "фейс-контроль / охранник" нашего сервера.
//
// Как работает охранник `authMiddleware`:
// Когда клиент стучится на закрытый адрес (например, `POST /habits`),
// запрос СНАЧАЛА попадает в `authMiddleware`:
//   1. Охранник смотрит: есть ли заголовок `Authorization: Bearer <токен>`?
//   2. Если токена нет или он фальшивый → охранник сразу разворачивает клиента с ошибкой `401 Unauthorized`.
//      Настоящий обработчик `createHabit` даже не узнает, что кто-то приходил!
//   3. Если токен настоящий → охранник прикрепляет бейджик с `userID` к запросу (в `context`)
//      и открывает дверь в `createHabit` (`next(w, r.WithContext(ctx))`).
//
// ============================================================================
// ШПАРГАЛКА ПО GO: ФУНКЦИИ ВНУТРИ ФУНКЦИЙ (ЗАМЫКАНИЯ) И УТВЕРЖДЕНИЕ ТИПА (.(int64))
// ============================================================================
//
// 1. КАК ФУНКЦИЯ МОЖЕТ ПРИНИМАТЬ ФУНКЦИЮ И ВОЗВРАЩАТЬ ФУНКЦИЮ? (Замыкание / Closure)
//    В Go функции — это такие же значения, как числа или строки!
//    Функцию можно передать в качестве параметра в другую функцию и можно вернуть через `return`.
//
//    Простой пример на пальцах:
//      // Функция makeGreeter создаёт и возвращает новую функцию:
//      func makeGreeter(prefix string) func(name string) {
//          return func(name string) {
//              // Внутренняя функция "помнит" переменную prefix снаружи! Это и есть ЗАМЫКАНИЕ (Closure).
//              fmt.Println(prefix + ", " + name + "!")
//          }
//      }
//      sayHello := makeGreeter("Привет")
//      sayHello("Мустафо") // Выведет: Привет, Мустафо!
//
//    Точно так же работает `authMiddleware(next http.HandlerFunc) http.HandlerFunc`:
//      - Она принимает функцию-обработчик `next` (например, `createHabit`).
//      - И возвращает НОВУЮ функцию-обёртку, которая сначала проверяет токен, а в конце вызывает `next`!
//
// 2. ЧТО ТАКОЕ ТИП `http.HandlerFunc` (И КАК ФУНКЦИЯ РЕАЛИЗУЕТ ИНТЕРФЕЙС)?
//    В стандартном пакете `net/http` написано:
//      type HandlerFunc func(w ResponseWriter, r *Request)
//    То есть `http.HandlerFunc` — это просто короткое имя для типа `func(w http.ResponseWriter, r *http.Request)`.
//    Мало того: в Go даже к типу функции можно прикрепить метод! У `http.HandlerFunc` есть метод `ServeHTTP`,
//    поэтому любая функция типа `http.HandlerFunc` автоматически реализует интерфейс `http.Handler`!
//
// 3. ЧТО ТАКОЕ УТВЕРЖДЕНИЕ ТИПА (Type Assertion) `value.(int64)`?
//    Когда мы кладём что-то в контекст (`context.WithValue`), контекст принимает значение как тип `any`
//    (пустой интерфейс `interface{}` — коробка без надписи).
//    Когда мы достаём значение обратно через `r.Context().Value(userIDKey)`, Go возвращает эту коробку `any`
//    и говорит: "Я не знаю, что лежит внутри коробки — строка, число или структура".
//
//    Чтобы открыть коробку и достать оттуда `int64`, мы пишем `.(int64)`:
//      id, ok := box.(int64)
//    Это возвращает два значения:
//      - `id` — само число `int64` (если внутри действительно лежало `int64`, иначе `0`);
//      - `ok` — `true` (если угадали тип) или `false` (если в коробке лежало что-то другое).
//    Важно: всегда используй безопасную форму с двумя переменными `id, ok := ...` (или `id, _ := ...`).
//    Если написать просто `id := box.(int64)` без второй переменной, и внутри окажется не `int64`,
//    программа упадёт с паникой (panic)!
//
// ============================================================================
// 🧒 ОБЪЯСНЕНИЕ ДЛЯ 10-ЛЕТНЕГО РЕБЁНКА (НА ПАЛЬЦАХ С ПРИМЕРАМИ):
// ============================================================================
//
// 1. КТО ТАКОЙ `authMiddleware` И КАК ОН РАБОТАЕТ?
//    Представь секретную комнату с игровой приставкой PlayStation (`createHabit`).
//    Чтобы туда не пробрались посторонние, мы ставим перед дверью строгого Робота-Охранника (`authMiddleware`).
//
//    Когда к двери подходит мальчик с запросом `r`:
//      - Шаг 1: Охранник говорит: "Покажи руку с браслетом!" (`r.Header.Get("Authorization")`).
//        Если на руке нет надписи `"Bearer ..."` — охранник кричит: "Стой! Без браслета нельзя! Ошибка 401!" и закрывает дверь (`return`).
//      - Шаг 2: Если браслет есть, охранник звонит по рации в Сервис (`h.auth.Authenticate(token)`):
//        "Проверьте браслет!". Сервис отвечает: "Браслет настоящий, это мальчик под номером `userID = 5`!".
//      - Шаг 3 (`context.WithValue`): Чтобы внутри игровой комнаты не спрашивать браслет заново,
//        охранник берёт наклейку-бейджик `userIDKey`, пишет на ней фломастером цифру `5`,
//        приклеивает мальчику на рюкзак (`r.WithContext(ctx)`) и открывает дверь в комнату (`next(...)`)!
//
// 2. КАК ПОНЯТЬ `id, _ := r.Context().Value(userIDKey).(int64)`?
//    Внутри игровой комнаты ведущий (`currentUserID`) хочет узнать номер мальчика на бейджике.
//    Но карман рюкзака (`Context().Value(...)`) возвращает загадочный чёрный мешочек `any` ("неизвестный предмет").
//    Тогда ведущий пишет заклинание `.(int64)` — "Достань мне из мешочка число `int64`!".
//    И получает номер мальчика `5`!
//
// ============================================================================
// 🍕 ПРИМЕРЫ НА РЕСТОРАНЕ (2 НАГЛЯДНЫХ ПРИМЕРА):
// ============================================================================
//
// ПРИМЕР 1: Хостес на входе в VIP-зал ресторана (`authMiddleware`)
//   В нашем ресторане есть общий вход (стойка регистрации `/sign-up` и `/login`), куда пускают всех с улицы,
//   и есть закрытый VIP-зал с заказами блюд (`/habits`), перед дверью которого стоит Хостес (`authMiddleware`):
//     1) Гость подходит к VIP-залу. Хостес смотрит на его клубную карту в заголовке `Authorization: Bearer <токен>`.
//        Если карты нет — Хостес не зовёт официанта (`next`), а сразу вежливо разворачивает гостя (`401 Unauthorized`).
//     2) Если карта настоящая (`h.auth.Authenticate(token)` вернул `userID = 5`), Хостес прикрепляет к папке меню гостя
//        золотую клипсу `userIDKey` с номером `5` (`ctx := context.WithValue(...)`) и передаёт папку официанту:
//        `next(w, r.WithContext(ctx))`!
//
// ПРИМЕР 2: Замыкание (Closure) и чтение клипсы официантом (`currentUserID`) в ресторане (С КОДОМ!)
//   Как работает обёртка `h.authMiddleware(h.createHabit)`?
//   Представь, что у нас есть обычный официант `createHabit`. Мы приставляем к нему личного телохранителя:
//
//     // Функция приставляет охрану к любому официанту next:
//     func (h *Handler) authMiddleware(next http.HandlerFunc) http.HandlerFunc {
//         return func(w http.ResponseWriter, r *http.Request) {
//             // 1. Сначала работает охрана (проверяет карту и цепляет клипсу с userID в ctx)
//             // ...
//             // 2. И только потом охрана зовёт официанта next, которого она "запомнила" (Замыкание!):
//             next(w, r.WithContext(ctx))
//         }
//     }
//
//   А когда официант `createHabit` принимает заказ, он вызывает `currentUserID(r)`:
//   смотрит на золотую клипсу `r.Context().Value(userIDKey).(int64)` и сразу видит: "Это заказ от Гостя №5!".
// ============================================================================

// package handler — часть пакета `handler`.
// Разбор строки: `package` (ключевое слово пакета) `handler` (имя пакета).
package handler

// Разбор строки: `import (` — открываем список подключаемых пакетов.
import (
	// "context" — чтобы положить ID авторизованного пользователя внутрь контекста запроса.
	"context"
	// "net/http" — для чтения заголовка Authorization и отправки ответа 401.
	"net/http"
	// "strings" — для проверки префикса "Bearer " и его отрезания.
	"strings"
)

// ctxKey — создаём свой собственный приватный тип ключа для контекста на основе `string`.
// Зачем создавать новый тип `type ctxKey string`, почему нельзя использовать просто строку `"userID"`?
// Потому что в большом проекте к запросу могут подключаться десятки чужих библиотек (логгеры, трейсеры).
// Если какая-то чужая библиотека тоже запишет в контекст что-то по строковому ключу `"userID"`,
// она случайно перезапишет нашего пользователя!
// А тип `ctxKey` приватный и принадлежит только нашему пакету `handler` — совпадение ключей невозможно на 100%.
//
// Разбор строки по каждому слову:
//   - `type`   — создаём новый тип данных;
//   - `ctxKey` — имя нашего типа (с маленькой буквы = виден только внутри пакета `handler`);
//   - `string` — базовый тип, на основе которого создан `ctxKey`.
type ctxKey string

// userIDKey — конкретный ключ нашего типа `ctxKey`, под которым мы прячем и достаём ID пользователя.
// Разбор строки по каждому слову:
//   - `const`     — объявляем константу;
//   - `userIDKey` — имя константы;
//   - `ctxKey`    — тип константы (наш уникальный тип `ctxKey`);
//   - `=`         — равно;
//   - `"userID"`  — значение ключа.
const userIDKey ctxKey = "userID"

// authMiddleware — оборачивает защищённый обработчик `next` проверкой JWT-токена.
// Разбор строки по каждому слову от начала до конца:
//   - `func`                     — объявляем метод;
//   - `(h *Handler)`             — получатель метода (наш `Handler`, чтобы иметь доступ к `h.auth`);
//   - `authMiddleware`           — имя метода;
//   - `(next http.HandlerFunc)`  — входной параметр `next` типа `http.HandlerFunc` (следующий обработчик, который нужно защитить);
//   - `http.HandlerFunc`         — возвращает новую функцию типа `http.HandlerFunc` (обёртку с проверкой токена);
//   - `{`                        — открываем тело метода.
func (h *Handler) authMiddleware(next http.HandlerFunc) http.HandlerFunc {
	// Возвращаем функцию-обёртку (замыкание), которая будет срабатывать на каждый HTTP-запрос.
	// Разбор строки по каждому слову:
	//   - `return`                                     — вернуть функцию;
	//   - `func(w http.ResponseWriter, r *http.Request)` — анонимная функция-обработчик HTTP-запроса;
	//   - `{`                                          — открываем тело этой функции-обёртки.
	return func(w http.ResponseWriter, r *http.Request) {
		// ====================================================================
		// ШАГ 1. Читаем заголовок `Authorization` из HTTP-запроса
		// ====================================================================
		// По мировому стандарту клиент присылает токен в заголовке такого вида:
		//   Authorization: Bearer eyJhbGciOiJIUzI1NiIs...
		// Разбор строки по каждому слову:
		//   - `header`                          — имя переменной;
		//   - `:=`                              — создать и присвоить;
		//   - `r.Header.Get("Authorization")`   — достать из заголовков запроса `r.Header` значение `"Authorization"`.
		header := r.Header.Get("Authorization")

		// Проверяем: начинается ли заголовок со слова `"Bearer "` (с пробелом)?
		// Восклицательный знак `!` означает отрицание ("НЕ"): "если НЕ начинается с Bearer ".
		// Разбор строки по каждому слову:
		//   - `if`                                    — если;
		//   - `!`                                     — НЕ;
		//   - `strings.HasPrefix(header, "Bearer ")`  — строка `header` начинается с префикса `"Bearer "`;
		//   - `{`                                     — открываем блок ошибки.
		if !strings.HasPrefix(header, "Bearer ") {
			// Разбор строки: отправляем статус 401 Unauthorized и сообщение `"missing bearer token"`.
			// Разбор строки по каждому слову:
			//   - `writeError(`             — вызываем функцию отправки JSON-ошибки;
			//   - `w,`                      — 1-й аргумент: интерфейс ответа;
			//   - `http.StatusUnauthorized,` — 2-й аргумент: статус `401 Unauthorized`;
			//   - `"missing bearer token")` — 3-й аргумент: текст ошибки.
			writeError(w, http.StatusUnauthorized, "отсутствует токен авторизации (Bearer)")
			// `return` — выходим и НЕ пускаем запрос дальше в `next`!
			// Разбор строки по каждому слову:
			//   - `return` — завершаем работу функции-обёртки (запрос дальше не идёт).
			return
		}

		// ====================================================================
		// ШАГ 2. Вырезаем сам токен из строки заголовка
		// ====================================================================
		// `strings.TrimPrefix(header, "Bearer ")` отрезает слово `"Bearer "` спереди.
		// `strings.TrimSpace(...)` убирает случайные лишние пробелы по краям.
		// Разбор строки по каждому слову:
		//   - `token`                                — имя переменной для чистого токена;
		//   - `:=`                                   — создать и присвоить;
		//   - `strings.TrimSpace(`                   — убрать пробелы по краям;
		//   - `strings.TrimPrefix(header, "Bearer "))` — отрезать `"Bearer "` из начала строки `header`.
		token := strings.TrimSpace(strings.TrimPrefix(header, "Bearer "))
		// Разбор строки: `if token == ""` — если после `"Bearer "` ничего не было написано:
		// Разбор строки по каждому слову:
		//   - `if`          — если;
		//   - `token == ""` — строка `token` оказалась пустой;
		//   - `{`           — открываем блок ошибки.
		if token == "" {
			// Разбор строки по каждому слову:
			//   - `writeError(`             — вызываем функцию отправки JSON-ошибки;
			//   - `w,`                      — 1-й аргумент: интерфейс ответа;
			//   - `http.StatusUnauthorized,` — 2-й аргумент: статус `401 Unauthorized`;
			//   - `"missing bearer token")` — 3-й аргумент: текст ошибки.
			writeError(w, http.StatusUnauthorized, "отсутствует токен авторизации (Bearer)")
			// Разбор строки по каждому слову:
			//   - `return` — выходим из функции-обёртки.
			return
		}

		// ====================================================================
		// ШАГ 3. Проверяем подпись и срок годности токена через Сервис
		// ====================================================================
		// Разбор строки по каждому слову:
		//   - `userID, err`                — создаём переменные `userID` (`int64`) и `err` (`error`);
		//   - `:=`                         — создать и присвоить;
		//   - `h.auth.Authenticate(token)` — вызываем метод `Authenticate` у сервиса авторизации `h.auth`.
		userID, err := h.auth.Authenticate(token)
		// Разбор строки по каждому слову:
		//   - `if`         — если;
		//   - `err != nil` — токен оказался поддельным или просроченным;
		//   - `{`          — открываем блок ошибки.
		if err != nil {
			// Если токен просрочен или подделан — `writeErr` вернёт 401 Unauthorized.
			// Разбор строки по каждому слову:
			//   - `writeErr(` — вызываем функцию перевода ошибки в HTTP-статус;
			//   - `w, err)`   — передаём `w` и `err`.
			writeErr(w, err)
			// Разбор строки по каждому слову:
			//   - `return` — выходим из функции-обёртки.
			return
		}

		// ====================================================================
		// ШАГ 4. Кладём `userID` в контекст запроса и пропускаем запрос дальше!
		// ====================================================================
		// Контекст в Go неизменяемый (immutable). Поэтому `context.WithValue` берёт старый контекст
		// `r.Context()` и создаёт его новую копию `ctx`, в которой лежит пара `userIDKey -> userID`.
		// Разбор строки по каждому слову:
		//   - `ctx`                                            — новая переменная контекста;
		//   - `:=`                                             — создать и присвоить;
		//   - `context.WithValue(r.Context(), userIDKey, userID)` — создать копию контекста `r.Context()`
		//                                                        с добавленным значением `userID` по ключу `userIDKey`.
		ctx := context.WithValue(r.Context(), userIDKey, userID)

		// `r.WithContext(ctx)` прикрепляет обновлённый контекст к запросу `r`,
		// а `next(...)` вызывает целевой обработчик (например, `createHabit` или `listHabits`).
		// Разбор строки по каждому слову:
		//   - `next(`              — вызываем настоящий обработчик `next`;
		//   - `w,`                 — 1-й аргумент: интерфейс записи ответа `w`;
		//   - `r.WithContext(ctx))` — 2-й аргумент: запрос `r` с вложенным в него новым контекстом `ctx`.
		next(w, r.WithContext(ctx))
	}
}

// currentUserID — достаёт `userID` текущего пользователя из контекста запроса `r`.
// Эту функцию вызывают обработчики привычек (`createHabit`, `listHabits`, `checkHabit`, `listChecks`).
//
// Разбор строки по каждому слову от начала до конца:
//   - `func`              — объявляем функцию;
//   - `currentUserID`     — имя функции;
//   - `(r *http.Request)` — входной параметр: указатель на запрос `r`;
//   - `int64`             — возвращает ID пользователя типа `int64`;
//   - `{`                 — открываем тело функции.
func currentUserID(r *http.Request) int64 {
	// Достаём коробку `any` по ключу `userIDKey` и через утверждение типа `.(int64)`
	// безопасно извлекаем из неё число `int64`.
	// Разбор строки по каждому слову:
	//   - `id, _`                        — в `id` кладём число, а второй результат (`ok`) игнорируем через `_`;
	//   - `:=`                           — объявляем и присваиваем;
	//   - `r.Context().Value(userIDKey)` — достаём из контекста запроса значение по ключу `userIDKey` (возвращает тип `any`);
	//   - `.(int64)`                     — утверждение типа (Type Assertion): достаём из коробки `any` число типа `int64`.
	id, _ := r.Context().Value(userIDKey).(int64)
	// Разбор строки: `return id` — возвращаем полученный ID пользователя.
	// Разбор строки по каждому слову:
	//   - `return` — завершаем функцию и возвращаем значение;
	//   - `id`     — числовой ID текущего пользователя (`int64`).
	return id
}
