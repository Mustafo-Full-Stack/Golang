// ЗАЧЕМ НУЖЕН: это "ресепшен" (входная стойка) нашего веб-сервера.
// Здесь находятся:
//   - `Routes()`   — карта всех HTTP-адресов (эндпоинтов) нашего API;
//   - `writeErr`   — переводчик ошибок с языка Go на язык HTTP-кодов (400, 401, 403, 404, 409, 500);
//   - `writeJSON`  — упаковщик любого ответа в формат JSON для отправки клиенту;
//   - `writeError` — отправка текста ошибки в красивом JSON-конверте `{"error": "..."}`.
//
// ============================================================================
// ГЛАВНАЯ ШПАРГАЛКА ПО GO: ЧТО ТАКОЕ ИНТЕРФЕЙС (`interface`) И ЗАЧЕМ ОН НУЖЕН?
// ============================================================================
//
// В этом файле ты постоянно видишь типы `http.Handler`, `http.ResponseWriter`, `error`, `any`.
// Все они — это ИНТЕРФЕЙСЫ! Давай разберём раз и навсегда, что это такое, простыми словами.
//
// 1. АНАЛОГИЯ ИЗ ЖИЗНИ: ЭЛЕКТРИЧЕСКАЯ РОЗЕТКА
//    Представь розетку в стене. Розетке всё равно, ЧТО ты в неё включишь:
//    чайник, утюг, зарядку от Айфона или гирлянду.
//    У розетки есть только ОДНО ТРЕБОВАНИЕ (контракт): "У прибора должна быть вилка с двумя штырьками".
//
//    В Go:
//      - СТРУКТУРА (`struct`) — это конкретный прибор (Чайник, Утюг) со своими деталями внутри.
//      - ИНТЕРФЕЙС (`interface`) — это требование: СПИСОК МЕТОДОВ, которые объект обязан уметь делать!
//
// 2. ПРОСТОЙ ПРИМЕР КОДА С ИНТЕРФЕЙСОМ:
//
//      // Шаг 1. Создаём интерфейс Speaker ("Говорящий").
//      // Требование одно: у объекта должен быть метод Speak(), возвращающий строку.
//      type Speaker interface {
//          Speak() string
//      }
//
//      // Шаг 2. Создаём две совершенно разные структуры: Собаку и Робота.
//      type Dog struct { Name string }
//      func (d Dog) Speak() string { return "Гав!" }
//
//      type Robot struct { Model int }
//      func (r Robot) Speak() string { return "Бип-буп!" }
//
//      // Шаг 3. Функция принимает ИНТЕРФЕЙС Speaker!
//      // Ей всё равно, кто придёт — Dog или Robot, главное, что оба умеют метод Speak()!
//      func MakeSound(s Speaker) {
//          fmt.Println(s.Speak())
//      }
//
//    ОСОБЕННОСТЬ GO (УТИНАЯ ТИПИЗАЦИЯ / Неявная реализация):
//    В Java или C# нужно специально писать `class Dog implements Speaker`.
//    В Go писать `implements` НЕ НУЖНО! Go действует по правилу:
//    "Если оно крякает как утка — значит, это утка".
//    Раз у `Dog` есть метод `Speak() string`, Go автоматически разрешает передавать `Dog` туда, где ждут `Speaker`!
//
// 3. ГДЕ ИНТЕРФЕЙСЫ ИСПОЛЬЗУЮТСЯ ПРЯМО В НАШЕМ ПРОЕКТЕ?
//
//    а) `http.Handler` (в методе `Routes() http.Handler` ниже):
//       Внутри стандартной библиотеки Go он объявлен всего в 3 строчки:
//         type Handler interface {
//             ServeHTTP(w ResponseWriter, r *Request)
//         }
//       Наш маршрутизатор `mux := http.NewServeMux()` имеет метод `ServeHTTP`, поэтому
//       мы можем вернуть его как `http.Handler`. Если завтра мы захотим заменить `ServeMux`
//       на роутер `Gin` или `Chi`, в `app.go` не придётся менять ни строчки!
//
//    б) `http.ResponseWriter` (первый параметр любого обработчика `w http.ResponseWriter`):
//       Это тоже интерфейс (умеет методы `Write()`, `WriteHeader()`, `Header()`).
//       Почему в `func(w http.ResponseWriter, r *http.Request)` у `r` есть звёздочка `*`, а у `w` НЕТ звёздочки?
//       Потому что `http.Request` — это структура (передаём по указателю `*`),
//       а `http.ResponseWriter` — это ИНТЕРФЕЙС (интерфейсы в Go всегда передаются без `*`, они уже внутри хранят адрес!).
//
//    в) Пустой интерфейс `any` (раньше в Go писали `interface{}`):
//       Посмотри на функцию внизу файла: `func writeJSON(w http.ResponseWriter, status int, body any)`.
//       Что такое `any`? Это интерфейс, у которого НЕТ НИ ОДНОГО ТРЕБОВАНИЯ (`interface{}`).
//       Какой тип в Go умеет хотя бы 0 методов? ЛЮБОЙ!
//       Поэтому в параметр `body any` можно передать и число, и строку, и структуру `habitResponse`, и слайс, и `map`!
//
//    г) Зачем в проекте учителя были интерфейсы для сервисов и репозиториев?
//       Когда пишут юнит-тесты (как в `auth_test.go` у учителя), не хотят запускать настоящий PostgreSQL.
//       Если Сервис принимает интерфейс `UserRepository`, то в реальной работе ему дают настоящий Postgres,
//       а в тесте — маленькую поддельную структуру в памяти (Mock).
//
// 4. ЧТО ТАКОЕ СЛОВАРЬ (`map[Ключ]Значение`)?
//    Внизу в `writeError` ты увидишь запись: `map[string]string{"error": message}`.
//    `map` (карта / словарь / хеш-таблица) хранит пары "Ключ → Значение".
//      - В квадратных скобках `[string]` — тип КЛЮЧА.
//      - После скобок `string` — тип ЗНАЧЕНИЯ.
//    Примеры:
//      ages := map[string]int{"Али": 20, "Вали": 25} // ключ — строка (имя), значение — число (возраст)
//      fmt.Println(ages["Али"])                      // выведет 20
//
// ============================================================================
// 🧒 ОБЪЯСНЕНИЕ ИНТЕРФЕЙСОВ ДЛЯ 10-ЛЕТНЕГО РЕБЁНКА (НА ПАЛЬЦАХ С ПРИМЕРАМИ):
// ============================================================================
//
// 1. ЧТО ТАКОЕ `interface` НА ПРИМЕРЕ ДЖОЙСТИКА ОТ ИГРОВОЙ ПРИСТАВКИ?
//    Представь, что ты делаешь компьютерную игру, и у тебя на джойстике есть кнопка "ПРЫЖОК" (`Jump()`).
//    В игре могут быть совершенно разные персонажи:
//      - водопроводчик Марио (`type Mario struct`),
//      - синий ёжик Соник (`type Sonic struct`),
//      - лягушонок (`type Frog struct`).
//
//    Если бы в Go НЕ БЫЛО интерфейсов, тебе пришлось бы писать три отдельные кнопки на джойстике:
//    `PressJumpForMario(m Mario)`, `PressJumpForSonic(s Sonic)`, `PressJumpForFrog(f Frog)`. Какой ужас!
//
//    Поэтому в Go придумали ИНТЕРФЕЙС — это "клуб по умению":
//      type Jumper interface {
//          Jump() // Правило входа в клуб: нужно уметь метод Jump()!
//      }
//    Джойстику вообще всё равно, кто перед ним — человек, ёжик или лягушка!
//    Джойстик просто говорит: `func PressButton(hero Jumper) { hero.Jump() }`.
//    Если у персонажа есть способность `Jump()`, он автоматически принят в клуб `Jumper`!
//
// 2. ЧТО ТАКОЕ ПУСТОЙ ИНТЕРФЕЙС `any` (`interface{}`)?
//    Если обычный интерфейс `Jumper` — это клуб со строгим правилом "вход только тем, кто умеет прыгать",
//    то пустой интерфейс `any` — это детская площадка с табличкой **"ПРАВИЛ НЕТ, ВХОД РАЗРЕШЁН ВСЕМ!"**.
//    Туда пускают и число `5`, и строку `"Привет"`, и структуру `habitResponse`, и словарь `map`!
//    Именно поэтому наша функция `writeJSON(w, status, body any)` умеет упаковывать в JSON вообще что угодно!
//
// 3. ЧТО ТАКОЕ `map[string]string` НА ПРИМЕРЕ ТЕЛЕФОННОЙ КНИЖКИ?
//    В обычном списке (слайсе `[]string`) всё лежит под номерами: `0`, `1`, `2`...
//    Но искать телефон друга по номеру `47` неудобно! Хочется искать по ИМЕНИ: `"Мама" → "+992..."`.
//    Вот `map[string]string` — это и есть записная книжка, где слева написано слово-ключ (`"error"`),
//    а справа — слово-ответ (`"invalid habit id"`).
//
// ============================================================================
// 🍕 ПРИМЕРЫ НА РЕСТОРАНЕ (2 НАГЛЯДНЫХ ПРИМЕРА ПРО ИНТЕРФЕЙСЫ И HANDLER):
// ============================================================================
//
// ПРИМЕР 1: Что такое ИНТЕРФЕЙС (`interface`) на примере должности "Повар ресторана" (С КОДОМ!)
//   Представь, что директор ресторана вешает объявление: "Требуется Повар (`interface Chef`)".
//   Директору не важно, откуда приехал повар и как его зовут. Главное требование одно:
//   он обязан уметь готовить блюдо — метод `CookOrder(dish string) string`!
//
//     // 1. Объявляем ИНТЕРФЕЙС (должностную инструкцию повара в ресторане):
//     type Chef interface {
//         CookOrder(dish string) string
//     }
//
//     // 2. Создаём двух разных поваров (две разные структуры struct):
//     type PizzaMaster struct { OvenTemp int }
//     func (p PizzaMaster) CookOrder(dish string) string {
//         return "Испёк в печи пиццу: " + dish
//     }
//
//     type SushiMaster struct { KnifeName string }
//     func (s SushiMaster) CookOrder(dish string) string {
//         return "Скрутил роллы: " + dish
//     }
//
//     // 3. Официант принимает ЛЮБОГО повара через интерфейс Chef!
//     func ServeGuest(c Chef, order string) {
//         result := c.CookOrder(order)
//         fmt.Println("Официант несёт гостю:", result)
//     }
//
//   Точно так же в `Routes() http.Handler` серверу Go не важно, какой у нас роутер внутри —
//   главное, что он выполняет роль "Метрдотеля зала" (интерфейс `http.Handler` с методом `ServeHTTP`)!
//
// ПРИМЕР 2: Официант, Поднос `any` (`writeJSON`) и Таблица кодов ресторана (`writeErr`)
//   1) `writeJSON(w http.ResponseWriter, status int, body any)`:
//      - `w http.ResponseWriter` — это столик гостя, куда официант ставит заказ.
//      - `body any` (пустой интерфейс) — это универсальный серебряный поднос официанта:
//        потому что у `any` нет ограничений, на этот поднос можно поставить и тарелку с пиццей (`habitResponse`),
//        и целую стойку с закусками (`[]habitResponse`), и папку со счётом (`map[string]string`)!
//   2) `writeErr(w, err)`:
//      Это памятка официанта, как вежливо отвечать гостю в любой ситуации:
//        - `400 Bad Request` — "Извините, вы не разборчиво заполнили бланк заказа";
//        - `401 Unauthorized` — "Пожалуйста, предъявите клубную карту ресторана";
//        - `403 Forbidden` — "Извините, но этот столик забронирован другим гостем";
//        - `404 Not Found` — "Такого блюда или столика в нашем ресторане нет";
//        - `409 Conflict` — "Этот столик уже занят / сегодняшняя отметка уже стоит";
//        - `500 Internal Server Error` — "На кухне временная заминка, мы уже чиним!".
// ============================================================================

// package handler — объединяет 4 файла в папке `internal/handler`:
// `handler.go`, `auth.go`, `habit.go`, `middleware.go`.
// Так как у всех четырёх файлов написано `package handler`, они видят все функции друг друга без `import`!
//
// Разбор строки по каждому слову:
//   - `package` — ключевое слово объявления пакета;
//   - `handler` — имя пакета (совпадает с папкой `internal/handler`).
package handler

// Разбор строки: `import (` — открываем список подключаемых пакетов.
import (
	// "encoding/json" — стандартный пакет для превращения структур Go в текст JSON и обратно.
	"encoding/json"
	// "errors" — для функции errors.Is (проверяем, какая именно ошибка вернулась из сервиса).
	"errors"
	// "net/http" — всё для работы с протоколом HTTP (сервер, роутер, коды ответов 200, 400, 404...).
	"net/http"

	// Наши модели и сервисы.
	"habit-tracker/internal/models"
	"habit-tracker/internal/service/auth"
	"habit-tracker/internal/service/habit"
)

// Handler — главная структура HTTP-слоя.
// Она держит в себе указатели на оба наших сервиса (`auth` и `habit`),
// чтобы любой HTTP-обработчик мог обратиться к бизнес-логике.
//
// Разбор строки по каждому слову:
//   - `type`    — создаём новый тип данных;
//   - `Handler` — имя структуры (с Большой буквы);
//   - `struct`  — это структура;
//   - `{`       — открываем список полей.
type Handler struct {
	// Разбор строки: `auth` (имя приватного поля) `*auth.Service` (тип: указатель на сервис авторизации).
	// Разбор строки по каждому слову:
	//   - `auth`          — имя приватного поля структуры `Handler`;
	//   - `*auth.Service` — тип поля: указатель (`*`) на структуру `Service` из пакета `auth`.
	auth *auth.Service
	// Разбор строки: `habit` (имя приватного поля) `*habit.Service` (тип: указатель на сервис привычек).
	// Разбор строки по каждому слову:
	//   - `habit`          — имя приватного поля структуры `Handler`;
	//   - `*habit.Service` — тип поля: указатель (`*`) на структуру `Service` из пакета `habit`.
	habit *habit.Service
}

// New — конструктор структуры Handler.
// Разбор строки по каждому слову от начала до конца:
//   - `func`                        — объявляем функцию;
//   - `New`                         — имя конструктора (вызывается как `handler.New(...)`);
//   - `(authService *auth.Service,` — 1-й входной параметр: указатель на сервис авторизации;
//   - `habitService *habit.Service)` — 2-й входной параметр: указатель на сервис привычек;
//   - `*Handler`                    — возвращает указатель (`*`) на созданную структуру `Handler`;
//   - `{`                           — открываем тело функции.
func New(authService *auth.Service, habitService *habit.Service) *Handler {
	// Разбор строки: `return &Handler{auth: authService, habit: habitService}` —
	// создаём структуру `Handler`, заполняем оба поля и значком `&` возвращаем её адрес.
	// Разбор строки по каждому слову:
	//   - `return`               — вернуть результат из функции;
	//   - `&Handler{`            — создаём структуру `Handler` и берём её адрес в памяти (`&`);
	//   - `auth: authService,`   — в поле `auth` записываем `authService`;
	//   - `habit: habitService}` — в поле `habit` записываем `habitService` и закрываем скобку `}`.
	return &Handler{auth: authService, habit: habitService}
}

// Routes — создаёт маршрутизатор (роутер) и привязывает каждый HTTP-адрес к своей функции.
// Возвращает интерфейс `http.Handler`, который мы передаём в `http.ListenAndServe` в `app.go`.
//
// Разбор строки по каждому слову от начала до конца:
//   - `func`         — объявляем метод;
//   - `(h *Handler)` — получатель метода (наш обработчик `h`);
//   - `Routes`       — имя метода (с Большой буквы, вызывается в `app.go` как `h.Routes()`);
//   - `()`           — без входных параметров;
//   - `http.Handler` — возвращает объект, реализующий интерфейс `http.Handler`;
//   - `{`            — открываем тело метода.
func (h *Handler) Routes() http.Handler {
	// `http.NewServeMux()` — стандартный маршрутизатор Go (начиная с Go 1.22 он стал очень мощным:
	// умеет проверять HTTP-методы POST/GET и вытаскивать переменные `{id}` прямо из адреса!).
	// Разбор строки по каждому слову:
	//   - `mux`                — имя переменной роутера;
	//   - `:=`                 — создать и присвоить;
	//   - `http.NewServeMux()` — вызвать конструктор роутера из пакета `net/http`.
	mux := http.NewServeMux()

	// ========================================================================
	// 1. ОТКРЫТЫЕ МАРШРУТЫ (Доступны всем без токена)
	// ========================================================================
	// Почему мы пишем `h.signUp` БЕЗ круглых скобок `()`?
	// Потому что мы НЕ вызываем функцию прямо сейчас! Мы передаём её роутеру как инструкцию:
	// "Когда кто-нибудь пришлёт запрос `POST /sign-up`, вот тогда и вызови функцию `h.signUp`".
	//
	// Разбор строки по каждому слову:
	//   - `mux.HandleFunc(` — регистрируем маршрут в роутере `mux`;
	//   - `"POST /sign-up",` — 1-й аргумент: HTTP-метод `POST` и путь `/sign-up`;
	//   - `h.signUp)`        — 2-й аргумент: метод-обработчик `signUp` (из файла `auth.go`).
	mux.HandleFunc("POST /sign-up", h.signUp)
	// Разбор строки: регистрируем маршрут `"POST /login"` и привязываем к нему метод `h.login`.
	// Разбор строки по каждому слову:
	//   - `mux.HandleFunc(` — регистрируем маршрут в роутере `mux`;
	//   - `"POST /login",`  — 1-й аргумент: HTTP-метод `POST` и путь `/login`;
	//   - `h.login)`        — 2-й аргумент: метод-обработчик `login` (из файла `auth.go`).
	mux.HandleFunc("POST /login", h.login)

	// ========================================================================
	// 2. ЗАЩИЩЁННЫЕ МАРШРУТЫ (Требуют заголовок `Authorization: Bearer <токен>`)
	// ========================================================================
	// Обрати внимание: мы оборачиваем каждый обработчик в `h.authMiddleware(...)`, как подарок в обёртку!
	// Сначала запрос попадёт к охраннику `authMiddleware` (файл `middleware.go`),
	// и только если токен верный — управление перейдёт внутрь `h.createHabit` и остальных.
	//
	// Разбор строки по каждому слову:
	//   - `mux.HandleFunc(`                — регистрируем маршрут;
	//   - `"POST /habits",`                — 1-й аргумент: метод `POST` и путь `/habits`;
	//   - `h.authMiddleware(h.createHabit))` — 2-й аргумент: оборачиваем обработчик `h.createHabit` в проверку токена `h.authMiddleware`.
	mux.HandleFunc("POST /habits", h.authMiddleware(h.createHabit))
	// Разбор строки: маршрут `"GET /habits"` → проверка токена `h.authMiddleware` → обработчик `h.listHabits`.
	// Разбор строки по каждому слову:
	//   - `mux.HandleFunc(`               — регистрируем маршрут в роутере `mux`;
	//   - `"GET /habits",`                — 1-й аргумент: HTTP-метод `GET` и путь `/habits`;
	//   - `h.authMiddleware(h.listHabits))` — 2-й аргумент: защищаем обработчик `h.listHabits` охранником `h.authMiddleware`.
	mux.HandleFunc("GET /habits", h.authMiddleware(h.listHabits))

	// `{id}` в адресе — это динамический параметр пути (например, `/habits/42/check`).
	// Внутри обработчика мы сможем достать это число "42" с помощью `r.PathValue("id")`.
	// Разбор строки: маршрут `"POST /habits/{id}/check"` → `h.authMiddleware(h.checkHabit)`.
	// Разбор строки по каждому слову:
	//   - `mux.HandleFunc(`                 — регистрируем маршрут в роутере `mux`;
	//   - `"POST /habits/{id}/check",`      — 1-й аргумент: метод `POST` и путь с параметром `{id}`;
	//   - `h.authMiddleware(h.checkHabit))` — 2-й аргумент: защищаем обработчик `h.checkHabit` охранником `h.authMiddleware`.
	mux.HandleFunc("POST /habits/{id}/check", h.authMiddleware(h.checkHabit))
	// Разбор строки: маршрут `"GET /habits/{id}/checks"` → `h.authMiddleware(h.listChecks)`.
	// Разбор строки по каждому слову:
	//   - `mux.HandleFunc(`                 — регистрируем маршрут в роутере `mux`;
	//   - `"GET /habits/{id}/checks",`      — 1-й аргумент: метод `GET` и путь с параметром `{id}`;
	//   - `h.authMiddleware(h.listChecks))` — 2-й аргумент: защищаем обработчик `h.listChecks` охранником `h.authMiddleware`.
	mux.HandleFunc("GET /habits/{id}/checks", h.authMiddleware(h.listChecks))

	// Возвращаем настроенный роутер `mux`. Так как у `*http.ServeMux` есть метод
	// `ServeHTTP(w http.ResponseWriter, r *http.Request)`, он реализует интерфейс `http.Handler`!
	// Разбор строки: `return mux` — возвращаем роутер `mux`.
	// Разбор строки по каждому слову:
	//   - `return` — завершаем метод и возвращаем результат;
	//   - `mux`    — наш настроенный маршрутизатор (реализующий интерфейс `http.Handler`).
	return mux
}

// writeErr — умный переводчик ошибок из сервисов в HTTP-ответы.
// Почему это вынесено в одну функцию?
// Чтобы в каждом обработчике просто писать `writeErr(w, err)` и не дублировать длинные `if / else`.
//
// Разбор строки по каждому слову от начала до конца:
//   - `func`                    — объявляем функцию;
//   - `writeErr`                — имя функции (с маленькой буквы = видна во всех файлах пакета `handler`);
//   - `(w http.ResponseWriter,` — 1-й параметр: интерфейс `http.ResponseWriter` (куда пишем ответ клиенту);
//   - `err error)`              — 2-й параметр: интерфейс `error` (ошибка, вернувшаяся из сервиса);
//   - (ничего не возвращает)    — функция просто записывает ответ в `w`;
//   - `{`                       — открываем тело функции.
func writeErr(w http.ResponseWriter, err error) {
	// Конструкция `switch` без переменной после слова `switch` — это красивая замена длинной цепочки `if ... else if ... else`.
	// Go проверяет условия `case` сверху вниз и выполняет ПЕРВОЕ совпавшее:
	// Разбор строки: `switch {` — открываем переключатель условий.
	// Разбор строки по каждому слову:
	//   - `switch` — ключевое слово переключателя условий;
	//   - `{`      — открываем список веток `case`.
	switch {
	// Запятая в `case` работает как "ИЛИ": если ошибка равна ErrInvalidInput ИЛИ ErrPasswordTooShort ИЛИ ErrPasswordTooLong:
	// Разбор строки по каждому слову:
	//   - `case`                                   — ветка условия;
	//   - `errors.Is(err, models.ErrInvalidInput),` — ошибка равна `ErrInvalidInput` ИЛИ (запятая `,`);
	//   - `errors.Is(err, models.ErrPasswordTooShort),` — ошибка равна `ErrPasswordTooShort` ИЛИ;
	//   - `errors.Is(err, models.ErrPasswordTooLong):`  — ошибка равна `ErrPasswordTooLong`.
	case errors.Is(err, models.ErrInvalidInput),
		errors.Is(err, models.ErrPasswordTooShort),
		errors.Is(err, models.ErrPasswordTooLong):
		// HTTP 400 Bad Request — клиент прислал некорректные данные.
		// Метод `err.Error()` достаёт текст из интерфейса `error`.
		// Разбор строки по каждому слову:
		//   - `writeError(`           — вызываем нашу функцию отправки JSON-ошибки;
		//   - `w,`                    — 1-й аргумент: куда писать ответ;
		//   - `http.StatusBadRequest,` — 2-й аргумент: константа кода `400`;
		//   - `err.Error())`          — 3-й аргумент: текст ошибки в виде строки.
		writeError(w, http.StatusBadRequest, err.Error())

	// Разбор строки по каждому слову:
	//   - `case`                                        — ветка условия;
	//   - `errors.Is(err, models.ErrInvalidToken),`     — ошибка равна `ErrInvalidToken` ИЛИ;
	//   - `errors.Is(err, models.ErrInvalidCredentials):` — ошибка равна `ErrInvalidCredentials`.
	case errors.Is(err, models.ErrInvalidToken), errors.Is(err, models.ErrInvalidCredentials):
		// HTTP 401 Unauthorized — неверный логин/пароль или плохой токен ("Мы не знаем, кто ты").
		// Разбор строки: отправляем в `w` статус `http.StatusUnauthorized` (401) и текст `err.Error()`.
		// Разбор строки по каждому слову:
		//   - `writeError(`             — вызываем функцию отправки JSON-ошибки;
		//   - `w,`                      — 1-й аргумент: интерфейс ответа;
		//   - `http.StatusUnauthorized,` — 2-й аргумент: код `401 Unauthorized`;
		//   - `err.Error())`            — 3-й аргумент: строка с текстом ошибки.
		writeError(w, http.StatusUnauthorized, err.Error())

	// Разбор строки по каждому слову:
	//   - `case`                                 — ветка условия;
	//   - `errors.Is(err, models.ErrForbidden):` — если ошибка равна `models.ErrForbidden`.
	case errors.Is(err, models.ErrForbidden):
		// HTTP 403 Forbidden — токен верный, но привычка чужая ("Мы знаем, кто ты, но тебе туда нельзя").
		// Разбор строки: отправляем в `w` статус `http.StatusForbidden` (403) и текст `err.Error()`.
		// Разбор строки по каждому слову:
		//   - `writeError(`          — вызываем функцию отправки JSON-ошибки;
		//   - `w,`                   — 1-й аргумент: интерфейс ответа;
		//   - `http.StatusForbidden,` — 2-й аргумент: код `403 Forbidden`;
		//   - `err.Error())`         — 3-й аргумент: строка с текстом ошибки.
		writeError(w, http.StatusForbidden, err.Error())

	// Разбор строки по каждому слову:
	//   - `case`                                — ветка условия;
	//   - `errors.Is(err, models.ErrNotFound):` — если ошибка равна `models.ErrNotFound`.
	case errors.Is(err, models.ErrNotFound):
		// HTTP 404 Not Found — запись с таким ID не существует в базе.
		// Разбор строки: отправляем в `w` статус `http.StatusNotFound` (404) и текст `err.Error()`.
		// Разбор строки по каждому слову:
		//   - `writeError(`         — вызываем функцию отправки JSON-ошибки;
		//   - `w,`                  — 1-й аргумент: интерфейс ответа;
		//   - `http.StatusNotFound,` — 2-й аргумент: код `404 Not Found`;
		//   - `err.Error())`        — 3-й аргумент: строка с текстом ошибки.
		writeError(w, http.StatusNotFound, err.Error())

	// Разбор строки по каждому слову:
	//   - `case`                                      — ветка условия;
	//   - `errors.Is(err, models.ErrUserExists),`     — ошибка равна `ErrUserExists` ИЛИ;
	//   - `errors.Is(err, models.ErrAlreadyChecked):` — ошибка равна `ErrAlreadyChecked`.
	case errors.Is(err, models.ErrUserExists), errors.Is(err, models.ErrAlreadyChecked):
		// HTTP 409 Conflict — конфликт дубликата (почта уже занята или привычка уже отмечена сегодня).
		// Разбор строки: отправляем в `w` статус `http.StatusConflict` (409) и текст `err.Error()`.
		// Разбор строки по каждому слову:
		//   - `writeError(`         — вызываем функцию отправки JSON-ошибки;
		//   - `w,`                  — 1-й аргумент: интерфейс ответа;
		//   - `http.StatusConflict,` — 2-й аргумент: код `409 Conflict`;
		//   - `err.Error())`        — 3-й аргумент: строка с текстом ошибки.
		writeError(w, http.StatusConflict, err.Error())

	// Разбор строки по каждому слову:
	//   - `default:` — ветка "по умолчанию" (выполняется, если ни один `case` выше не подошёл).
	default:
		// HTTP 500 Internal Server Error — непредвиденная поломка на сервере (например, отключилась БД).
		// В целях безопасности никогда не отправляем клиенту внутренний текст системной ошибки (`err.Error()`),
		// а пишем нейтральное `"internal server error"`.
		// Разбор строки: отправляем в `w` статус `http.StatusInternalServerError` (500) и строку `"internal server error"`.
		// Разбор строки по каждому слову:
		//   - `writeError(`                    — вызываем функцию отправки JSON-ошибки;
		//   - `w,`                             — 1-й аргумент: интерфейс ответа;
		//   - `http.StatusInternalServerError,` — 2-й аргумент: код `500 Internal Server Error`;
		//   - `"internal server error")`       — 3-й аргумент: безопасный текст ошибки для клиента.
		writeError(w, http.StatusInternalServerError, "внутренняя ошибка сервера")
	}
}

// writeJSON — превращает любое значение `body` (тип `any`, то есть пустой интерфейс `interface{}`)
// в JSON-строку и отправляет её клиенту со статусом `status`.
//
// Разбор строки по каждому слову от начала до конца:
//   - `func`                    — объявляем функцию;
//   - `writeJSON`               — имя функции;
//   - `(w http.ResponseWriter,` — 1-й параметр: интерфейс записи HTTP-ответа `w`;
//   - `status int,`             — 2-й параметр: числовой HTTP-код ответа `status` (например, 200, 201, 400);
//   - `body any)`               — 3-й параметр: данные для отправки `body` с типом `any` (пустой интерфейс — принимает любой тип!);
//   - `{`                       — открываем тело функции.
func writeJSON(w http.ResponseWriter, status int, body any) {
	// 1. Ставим заголовок `Content-Type: application/json`, чтобы браузер или мобильное приложение
	//    поняли, что в ответе пришёл именно JSON, а не обычный текст или картинка.
	//    ВАЖНО: заголовки (`w.Header().Set(...)`) всегда нужно задавать ДО вызова `w.WriteHeader(status)`!
	// Разбор строки по каждому слову:
	//   - `w.Header()`                           — получаем заголовки ответа;
	//   - `.Set("Content-Type", "application/json")` — устанавливаем заголовок `"Content-Type"` равным `"application/json"`.
	w.Header().Set("Content-Type", "application/json")

	// 2. Отправляем клиенту HTTP-код статуса (например, 200 OK или 201 Created).
	// Разбор строки: `w.WriteHeader(status)` — записываем числовой код статуса в ответ `w`.
	// Разбор строки по каждому слову:
	//   - `w`            — интерфейс записи HTTP-ответа;
	//   - `.WriteHeader(` — метод отправки HTTP-статуса клиенту;
	//   - `status)`      — числовой код статуса (например, `200`, `201`, `400`).
	w.WriteHeader(status)

	// 3. Превращаем `body` в JSON и записываем прямо в поток ответа `w`.
	//    Символ `_` (пустой идентификатор) говорит Go: "Мы знаем, что Encode возвращает ошибку,
	//    но намеренно её игнорируем, так как заголовок ответа уже ушёл клиенту".
	// Разбор строки по каждому слову:
	//   - `_ =`                 — игнорируем возвращаемую ошибку;
	//   - `json.NewEncoder(w)`  — создаём JSON-кодировщик, подключённый к потоку ответа `w`;
	//   - `.Encode(body)`       — превращаем переменную `body` в JSON и отправляем клиенту.
	_ = json.NewEncoder(w).Encode(body)
}

// writeError — упаковывает сообщение об ошибке в стандартный JSON-объект `{"error": "..."}`.
// Например: `writeError(w, 400, "invalid habit id")` отправит клиенту `{"error": "invalid habit id"}`.
//
// Разбор строки по каждому слову от начала до конца:
//   - `func`                    — объявляем функцию;
//   - `writeError`              — имя функции;
//   - `(w http.ResponseWriter,` — 1-й параметр: интерфейс ответа `w`;
//   - `status int,`             — 2-й параметр: HTTP-код `status` типа `int`;
//   - `message string)`         — 3-й параметр: текст ошибки `message` типа `string`;
//   - `{`                       — открываем тело функции.
func writeError(w http.ResponseWriter, status int, message string) {
	// Разбор строки по каждому слову:
	//   - `writeJSON(w, status,`             — вызываем `writeJSON`, передавая `w` и `status`;
	//   - `map[string]string{"error": message})` — создаём словарь `map` (ключ `string` → значение `string`)
	//                                              с одной парой `"error": message`.
	writeJSON(w, status, map[string]string{"error": message})
}
