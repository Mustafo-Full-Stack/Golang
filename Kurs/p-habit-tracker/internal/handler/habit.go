// habitResponse — то, как одна привычка выглядит в JSON-ответе клиенту:
//
//	{"id": 1, "name": "Пить 2 литра воды", "created_at": "2026-11-05T16:00:00Z"}
//
// Обрати внимание: мы специально не включили сюда поле `UserID`, потому что клиенту
// незачем каждый раз видеть свой собственный ID в каждой привычке.
//
// Разбор строки: `type habitResponse struct {` — объявляем структуру ответа для привычки.
// Разбор строки по каждому слову:
//   - `type`          — объявляем новый тип данных;
//   - `habitResponse` — имя структуры ответа;
//   - `struct`        — это структура;
//   - `{`             — открываем список полей.
type habitResponse struct {
	// Разбор строки: поле `ID` типа `int64`, в JSON будет ключом `"id"`.
	// Разбор строки по каждому слову:
	//   - `ID`          — имя поля (с Большой буквы);
	//   - `int64`       — тип поля: 64-битное целое число;
	//   - `` `json:"id"` `` — структурный тег: в JSON превратится в ключ `"id"`.
	ID int64 `json:"id"`
	// Разбор строки: поле `Name` типа `string`, в JSON будет ключом `"name"`.
	// Разбор строки по каждому слову:
	//   - `Name`          — имя поля (с Большой буквы);
	//   - `string`        — тип поля: строка;
	//   - `` `json:"name"` `` — структурный тег: в JSON превратится в ключ `"name"`.
	Name string `json:"name"`
	// Разбор строки: поле `CreatedAt` типа `time.Time`, в JSON будет ключом `"created_at"`.
	// Разбор строки по каждому слову:
	//   - `CreatedAt`           — имя поля (с Большой буквы);
	//   - `time.Time`           — тип поля: дата и время из пакета `time`;
	//   - `` `json:"created_at"` `` — структурный тег: в JSON превратится в ключ `"created_at"`.
	CreatedAt time.Time `json:"created_at"`
}

