// ============================================================================
// ФАЙЛ: internal/handler/habit.go
// ЗАЧЕМ НУЖЕН: HTTP-обработчики для управления привычками:
//   1. `createHabit` — `POST /habits`             (создать новую привычку);
//   2. `listHabits`  — `GET  /habits`             (получить список своих привычек);
//   3. `checkHabit`  — `POST /habits/{id}/check`  (поставить галочку за сегодня);
//   4. `listChecks`  — `GET  /habits/{id}/checks` (посмотреть историю выполнения привычки).
//
// Все 4 обработчика стоят ЗА спиной охранника `authMiddleware` (см. `handler.go` и `middleware.go`),
// поэтому к моменту входа в эти функции токен УЖЕ проверен, а `id` пользователя
// лежит в контексте запроса и достаётся вызовом `currentUserID(r)`.
//
// ============================================================================
// ШПАРГАЛКА ПО GO: `make()` ДЛЯ СЛАЙСОВ, ЦИКЛ `for range` И МАГИЧЕСКАЯ ДАТА `2006-01-02`
// ============================================================================
//
// 1. В ЧЁМ РАЗНИЦА МЕЖДУ `var resp []habitResponse` И `resp := make([]habitResponse, 0)`?
//    Это тонкость, на которой часто спотыкаются при работе с JSON!
//
//    Вариант А:
//      var resp []habitResponse
//      Если у пользователя пока 0 привычек, слайс `resp` равен `nil` (не инициализирован).
//      При переводе в JSON `nil`-слайс превращается в слово `null`!
//      Фронтендеры очень не любят получать `null` вместо пустого массива `[]`.
//
//    Вариант Б (как сделано у нас):
//      resp := make([]habitResponse, 0, len(habits))
//      Функция `make(тип, длина, ёмкость)` создаёт настоящий (не `nil`) пустой слайс.
//      Даже если привычек 0, в JSON он превратится в красивые пустые скобки `[]`!
//      А третий аргумент `len(habits)` заранее бронирует в памяти место ровно под нужное
//      количество элементов, чтобы компьютеру не приходилось расширять память на каждом шаге цикла.
//
// 2. КАК РАБОТАЕТ ЦИКЛ `for _, habit := range habits`?
//    Слово `range` проходит по очереди по каждому элементу слайса `habits`.
//    На каждом шаге `range` отдаёт ДВА значения:
//      1-е значение: порядковый номер элемента (индекс: 0, 1, 2...).
//      2-е значение: копия самого элемента (`habit`).
//
//    Но нам внутри цикла индекс (0, 1, 2) не нужен!
//    Если в Go объявить переменную `i` и не использовать её — программа не скомпилируется.
//    Поэтому вместо имени переменной пишут нижнее подчёркивание `_` ("пустой идентификатор" / мусорная корзина):
//      `for _, habit := range habits` — "индекс выброси в корзину `_`, а сам элемент положи в `habit`".
//
// 3. ПОЧЕМУ В `check.Date.Format("2006-01-02")` НАПИСАНЫ ИМЕННО ЦИФРЫ `2006-01-02`?!
//    В других языках пишут буквы `"YYYY-MM-DD"`. Но создатели Go придумали необычную систему:
//    вместо букв ты пишешь в качестве шаблона ОДНУ КОНКРЕТНУЮ ЭТАЛОННУЮ ДАТУ:
//      2 января 2006 года, 15 часов 04 минуты 05 секунд (Mon Jan 2 15:04:05 MST 2006).
//    Как легко запомнить эти цифры? По порядку: 1, 2, 3, 4, 5, 6!
//      - `01` — месяц (январь)
//      - `02` — день (2-е число)
//      - `03` (или `15` в 24-часовом формате) — час
//      - `04` — минуты
//      - `05` — секунды
//      - `2006` — год
//    Поэтому строка `"2006-01-02"` говорит Go: "Напечатай год-месяц-день через дефис"!
//
// ============================================================================
// 🧒 ОБЪЯСНЕНИЕ ДЛЯ 10-ЛЕТНЕГО РЕБЁНКА (НА ПАЛЬЦАХ С ПРИМЕРАМИ):
// ============================================================================
//
// 1. В ЧЁМ РАЗНИЦА МЕЖДУ ПУСТОЙ КОРЗИНОЙ `[]` (`make`) И ОТСУТСТВИЕМ КОРЗИНЫ `null` (`var`)?
//    Представь, что мама просит тебя: "Сходи в сад и принеси корзинку с яблоками!".
//    Ты приходишь в сад, а яблок на дереве сегодня нет (0 штук).
//      - Если ты использовал `var resp []habitResponse` — ты возвращаешься к маме вообще с пустыми руками,
//        даже без корзинки (`null`). Мама пугается: "А где же корзинка?!".
//      - А если ты использовал `resp := make([]habitResponse, 0, len(habits))` — ты приносишь маме
//        аккуратную чистую корзинку `[]`, просто внутри неё пока 0 яблок! Мама довольна.
//
// 2. ЗАЧЕМ В ЦИКЛЕ `for _, habit := range habits` НУЖЕН ЗНАЧОК `_`?
//    Когда робот `range` достаёт игрушки из коробки одну за другой, он каждый раз громко кричит две вещи:
//    "Игрушка номер Ноль — вот Мишка! Игрушка номер Один — вот Машинка!".
//    Но нам не важен порядковый номер (Ноль, Один), нам нужна только сама игрушка (`habit`)!
//    А в Go строгое правило: если ты взял что-то в руки, ты обязан этим воспользоваться.
//    Поэтому под номер мы подставляем мусорное ведёрко `_`: номер сразу летит в ведёрко `_`,
//    а саму игрушку `habit` мы берём в руки!
//
// ============================================================================
// 🍕 ПРИМЕРЫ НА РЕСТОРАНЕ (2 НАГЛЯДНЫХ ПРИМЕРА):
// ============================================================================
//
// ПРИМЕР 1: Пустой поднос `[]` (`make`) против отсутствия подноса `null` (`var`) в `listHabits`
//   Гость садится за столик в ресторане и просит официанта (`GET /habits`):
//   "Покажите список блюд, которые я уже заказал!".
//   Допустим, гость только что пришёл и ещё ничего не заказывал (в базе 0 записей):
//     - Если написать `var resp []habitResponse`: официант принесёт `null` ("У нас вообще нет подносов!").
//       Мобильное приложение гостя от такого ответа может сломаться.
//     - Поэтому мы пишем `resp := make([]habitResponse, 0, len(habits))`: официант выносит
//       красивый чистый поднос `[]` (внутри 0 блюд). Гость видит пустой поднос и спокойно делает первый заказ!
//
// ПРИМЕР 2: Номер столика на двери (`parseID` и `r.PathValue("id")`) и штамп даты (`"2006-01-02"`)
//   1) `parseID(r)`:
//      Гость стучится в дверь кабинки с табличкой `POST /habits/15/check` ("Обслужить кабинку №15").
//      Вызов `r.PathValue("id")` снимает с двери текстовую табличку `"15"`, а `strconv.ParseInt(..., 10, 64)`
//      превращает текст `"15"` в настоящее число `15`, чтобы повар нашёл заказ №15 в базе.
//   2) `check.Date.Format("2006-01-02")`:
//      Когда гость просит распечатку всех своих посещений ресторана (`listChecks`),
//      кассовый аппарат отрезает лишние нули времени и печатает в чеке только аккуратную дату: `"2026-11-05"`.
// ============================================================================

