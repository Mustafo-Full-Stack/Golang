// ФАЙЛ: internal/models/models.go
// ЗАЧЕМ НУЖЕН: это "общий словарь" всего приложения.
// Здесь нет ни HTTP, ни SQL-запросов. Здесь описаны только структуры данных и ошибки,
// которыми обмениваются между собой Handler, Service и Repository:
//
//   1. СУЩНОСТИ БАЗЫ ДАННЫХ (Entities):
//      User, Habit, HabitCheck — то, как данные хранятся в таблицах PostgreSQL.
//
//   2. ВХОДНЫЕ ДАННЫЕ (DTO — Data Transfer Objects):
//      RegisterInput, LoginInput, CreateHabitInput — сырые данные, пришедшие от пользователя,
//      которые умеют сами себя проверять через метод `.Validate()`.
//
//   3. ОШИБКИ ПРИЛОЖЕНИЯ (Sentinel Errors):
//      ErrNotFound, ErrUserExists и др. — сигнальные ошибки для понимания, что пошло не так.
//
// ============================================================================
// ШПАРГАЛКА ПО GO: ПОЛУЧАТЕЛЬ-УКАЗАТЕЛЬ В МЕТОДАХ И БАЙТЫ ПРОТИВ РУН (UTF-8)
// ============================================================================
//
// 1. ПОЧЕМУ В МЕТОДЕ `func (in *RegisterInput) Validate()` СТОИТ ЗВЁЗДОЧКА `*`?
//    Вспомним: метод можно объявить двумя способами:
//
//    Способ А — БЕЗ звёздочки (получатель-значение / Value Receiver):
//      func (in RegisterInput) Validate() {
//          in.Name = "Али" // МЕНЯЕТ ТОЛЬКО ВРЕМЕННУЮ КОПИЮ!
//      }
//      Когда метод закончится, копия выбросится, а в оригинальной структуре `in.Name`
//      останется старым (с пробелами по краям)!
//
//    Способ Б — СО звёздочкой (получатель-указатель / Pointer Receiver):
//      func (in *RegisterInput) Validate() {
//          in.Name = strings.TrimSpace(in.Name) // МЕНЯЕТ САМ ОРИГИНАЛ ПО АДРЕСУ!
//      }
//      Так как `Validate()` не просто проверяет поля, но и ЧИСТИТ их (убирает пробелы,
//      переводит email в маленькие буквы), нам ОБЯЗАТЕЛЬНО нужна звёздочка `*RegisterInput`,
//      чтобы эти изменения сохранились в оригинальной структуре!
//
// 2. В ЧЁМ РАЗНИЦА МЕЖДУ `len(str)` И `utf8.RuneCountInString(str)`?
//    В компьютере любой текст хранится в виде байтов (чисел от 0 до 255) в кодировке UTF-8:
//      - Английские буквы и цифры (`a`, `b`, `1`) занимают 1 байт.
//      - Русские буквы (`а`, `б`, `я`) занимают 2 байта!
//      - Смайлики (`🔥`, `😀`) занимают 4 байта!
//
//    Функция `len(s)` считает БАЙТЫ, а не буквы!
//    А одна буква (символ любого языка) в Go называется РУНОЙ (`rune`).
//
//    Пример:
//      word := "Привет"
//      fmt.Println(len(word))                    // Выведет 12! (6 русских букв * 2 байта)
//      fmt.Println(utf8.RuneCountInString(word)) // Выведет 6!  (настоящее количество букв)
//
// ============================================================================
// 🧒 ОБЪЯСНЕНИЕ ДЛЯ 10-ЛЕТНЕГО РЕБЁНКА (НА ПАЛЬЦАХ С ПРИМЕРАМИ):
// ============================================================================
//
// 1. ЗАЧЕМ НУЖЕН ФАЙЛ `models.go`?
//    Вспомни нашу пиццерию из `app.go`: есть Официант (`Handler`), Повар (`Service`) и Кладовщик (`Repository`).
//    Если Официант скажет "круглая штука с колбасой", а Повар понимает только слово "Пепперони",
//    они переругаются и перепутают заказ!
//    Файл `models.go` — это общее меню с картинками, которое выучили все трое.
//    Здесь нарисовано: вот так выглядит Человек (`User`), вот так — Привычка (`Habit`), а вот так — Галочка (`HabitCheck`).
//
// 2. ПОЧЕМУ В `func (in *RegisterInput) Validate()` НУЖНА ЗВЁЗДОЧКА `*`?
//    Представь, что ты написал диктант в тетрадке (`RegisterInput`) и случайно посадил кляксу (лишние пробелы).
//    Ты даёшь тетрадку учителю (`Validate`), чтобы он стёр кляксу ластиком:
//      - Если дать учителю ФОТОГРАФИЮ тетрадки (без `*`), учитель сотрёт кляксу на фотке,
//        а в твоей настоящей тетрадке на парте клякса так и останется!
//      - А если дать учителю САМУ ТЕТРАДКУ (со звёздочкой `*RegisterInput`), учитель сотрёт
//        пробелы прямо в ней (`in.Name = strings.TrimSpace(in.Name)`), и тетрадка станет чистой!
//
// 3. ПОЧЕМУ `len("Привет")` ДАЁТ 12, А НЕ 6?
//    Представь поезд с маленькими сиденьями (байтами):
//      - Английские буквы (`A`, `B`, `C`) — худенькие малыши, каждый садится на 1 сиденье (1 байт).
//      - Русские буквы (`П`, `р`, `и`, `в`, `е`, `т`) — пухлые богатыри, каждому нужно сразу 2 сиденья (2 байта)!
//      - Смайлики (`😀`) — вообще великаны, каждый занимает 4 сиденья (4 байта)!
//    Команда `len()` считает, сколько СИДЕНИЙ занято в вагоне (6 богатырей * 2 = 12 сидений).
//    А команда `utf8.RuneCountInString()` считает по головам, сколько ПАССАЖИРОВ (букв) едет в вагоне (6)!
//
// ============================================================================
// 🍕 ПРИМЕРЫ НА РЕСТОРАНЕ (2 НАГЛЯДНЫХ ПРИМЕРА):
// ============================================================================
//
// ПРИМЕР 1: Черновик заказа официанта (`RegisterInput` / `CreateHabitInput`) против Книги Учёта (`User` / `Habit`)
//   В ресторане есть два вида карточек:
//     1) Черновик заказа от гостя (`CreateHabitInput{UserID: 5, Name: "  Пицца Маргарита  "}`):
//        Гость написал заказ от руки и оставил по краям лишние пробелы.
//        Официант вызывает метод `(in *CreateHabitInput) Validate()` со звёздочкой `*`:
//        он берёт НАСТОЯЩИЙ листок гостя, стирает пробелы по краям (`"Пицца Маргарита"`)
//        и проверяет, что листок не пустой.
//     2) Готовая запись в кассовой книге ресторана (`Habit{ID: 10, UserID: 5, Name: "Пицца Маргарита", CreatedAt: ...}`):
//        Когда заказ прошёл проверку и попал на склад (в БД), касса присвоила ему чек `ID: 10` и время `CreatedAt`.
//
// ПРИМЕР 2: Табличка с названием блюда в меню (`len` против `utf8.RuneCountInString`)
//   На деревянной табличке меню ресторана помещается максимум 10 букв (`maxRunes = 10`):
//     - Блюдо №1: `"Steak"` (5 английских букв) → занимает 5 байт (`len` = 5) и 5 букв (`RuneCount` = 5).
//     - Блюдо №2: `"Хачапури"` (8 русских букв) → каждая русская буква занимает 2 байта!
//       Если проверять через `len("Хачапури")`, получится `16 > 10`, и глупая программа скажет:
//       "Слово Хачапури слишком длинное, в нём 16 букв!".
//       А `utf8.RuneCountInString("Хачапури")` честно посчитает буквы: `8 <= 10` — блюдо отлично помещается в меню!
// ============================================================================

