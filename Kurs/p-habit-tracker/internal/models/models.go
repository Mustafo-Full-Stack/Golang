// Validate — очищает почту и проверяет, что почта и пароль не пустые.
// Разбор строки по каждому слову от начала до конца:
//   - `func`             — объявляем метод;
//   - `(in *LoginInput)` — получатель-указатель на структуру `LoginInput`;
//   - `Validate`         — имя метода;
//   - `()`               — без входных параметров;
//   - `error`            — возвращает ошибку `error` (или `nil`);
//   - `{`                — открываем тело метода.
func (in *LoginInput) Validate() error {
	// Приводим почту к тому же виду, в каком сохраняли при регистрации (маленькие буквы без пробелов).
	// Разбор строки: `in.Email = strings.ToLower(strings.TrimSpace(in.Email))` — чистим пробелы и регистр букв.
	// Разбор строки по каждому слову:
	//   - `in.Email`                    — обращаемся к полю `Email` структуры `in`;
	//   - `=`                           — присваиваем новое значение;
	//   - `strings.ToLower(`            — переводим все буквы в нижний регистр;
	//   - `strings.TrimSpace(in.Email))` — предварительно обрезаем пробелы по краям.
	in.Email = strings.ToLower(strings.TrimSpace(in.Email))

	// Разбор строки: `if in.Email == "" || in.Password == "" {` — если почта пустая ИЛИ пароль пустой:
	// Разбор строки по каждому слову:
	//   - `if`                — если;
	//   - `in.Email == ""`    — поле `Email` пустое;
	//   - `||`                — ИЛИ;
	//   - `in.Password == ""` — поле `Password` пустое;
	//   - `{`                 — открываем блок ошибки.
	if in.Email == "" || in.Password == "" {
		// `return ErrInvalidInput` — возвращаем ошибку пустых полей.
		// Разбор строки по каждому слову:
		//   - `return`          — выйти из метода;
		//   - `ErrInvalidInput` — вернуть ошибку `ErrInvalidInput`.
		return ErrInvalidInput
	}
	// `return nil` — ошибок нет.
	// Разбор строки по каждому слову:
	//   - `return` — завершить метод;
	//   - `nil`    — ошибок нет.
	return nil
}

