// Validate — очищает название привычки и проверяет его длину.
// Разбор строки по каждому слову от начала до конца:
//   - `func`                   — объявляем метод;
//   - `(in *CreateHabitInput)` — получатель-указатель на структуру `CreateHabitInput`;
//   - `Validate`               — имя метода;
//   - `()`                     — без дополнительных параметров;
//   - `error`                  — возвращает `error` (или `nil`);
//   - `{`                      — открываем тело метода.
func (in *CreateHabitInput) Validate() error {
	// Отрезаем пробелы по краям (чтобы строка из одних пробелов "    " стала пустой "").
	// Разбор строки: `in.Name = strings.TrimSpace(in.Name)` — записываем в `in.Name` очищенную от пробелов строку.
	// Разбор строки по каждому слову:
	//   - `in.Name`                   — поле названия привычки;
	//   - `=`                         — присвоить обновлённое значение;
	//   - `strings.TrimSpace(in.Name)` — убрать пробелы по краям строки `in.Name`.
	in.Name = strings.TrimSpace(in.Name)

	// Если название пустое ИЛИ в нём больше 100 букв — возвращаем ошибку.
	// Разбор строки по каждому слову:
	//   - `if`                                — если;
	//   - `in.Name == ""`                     — название пустое;
	//   - `||`                                — ИЛИ;
	//   - `utf8.RuneCountInString(in.Name)`   — количество букв (рун) в названии;
	//   - `>`                                 — больше чем;
	//   - `maxHabitNameRunes`                 — константа `100`;
	//   - `{`                                 — открываем блок ошибки.
	if in.Name == "" || utf8.RuneCountInString(in.Name) > maxHabitNameRunes {
		// `return ErrInvalidInput` — возвращаем ошибку некорректных данных.
		// Разбор строки по каждому слову:
		//   - `return`          — выйти из метода;
		//   - `ErrInvalidInput` — вернуть ошибку `ErrInvalidInput`.
		return ErrInvalidInput
	}
	// `return nil` — всё отлично, ошибок нет.
	// Разбор строки по каждому слову:
	//   - `return` — завершить метод;
	//   - `nil`    — ошибок нет.
	return nil
}

