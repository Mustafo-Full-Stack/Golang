// Repository — структура репозитория пользователей.
// Разбор строки по каждому слову:
//   - `type`       — создаём новый тип данных;
//   - `Repository` — имя структуры (с Большой буквы = публичная);
//   - `struct`     — это структура;
//   - `{`          — открываем список полей.
type Repository struct {
	// db — указатель на пул подключений к базе.
	// Почему `db` написано с маленькой буквы?
	// Это ИНКАПСУЛЯЦИЯ: поле приватное, чтобы никто снаружи пакета `user` не мог
	// залезть напрямую в `repo.db` и написать кривой SQL-запрос в обход наших методов.
	// Разбор строки по каждому слову:
	//   - `db`            — имя приватного поля;
	//   - `*pgxpool.Pool` — тип поля: указатель (`*`) на структуру `Pool` из пакета `pgxpool`.
	db *pgxpool.Pool
}

// NewRepository — функция-конструктор.
// Принимает пул соединений `db` и возвращает готовый к работе `*Repository`.
// Разбор строки по каждому слову от начала до конца:
//   - `func`               — объявляем функцию;
//   - `NewRepository`      — имя конструктора (вызывается как `userrepo.NewRepository(pool)`);
//   - `(db *pgxpool.Pool)` — входной параметр `db` с типом `*pgxpool.Pool`;
//   - `*Repository`        — функция возвращает указатель (`*`) на структуру `Repository`;
//   - `{`                  — открываем тело функции.
func NewRepository(db *pgxpool.Pool) *Repository {
	// Разбор строки по каждому слову:
	//   - `return`      — вернуть результат из функции;
	//   - `&Repository` — создаём структуру `Repository` и значком `&` берём её адрес в памяти;
	//   - `{db: db}`    — в поле структуры `db:` кладём переданный параметр `db`.
	return &Repository{db: db}
}

// Create — добавляет нового пользователя в таблицу `users`.
// Принимает указатель `u *models.User`. До вызова у `u` заполнены только Name, Email и PasswordHash,
// а после успешного выполнения метода `Create` внутри `u` появятся ещё `ID` и `CreatedAt` из базы!
//
// Разбор строки по каждому слову от начала до конца:
//   - `func`                  — объявляем метод;
//   - `(r *Repository)`       — получатель (receiver): привязывает метод к структуре `Repository` (внутри `r` — наш репозиторий);
//   - `Create`                — имя метода;
//   - `(ctx context.Context,` — 1-й входной параметр: контекст запроса `ctx` (интерфейс `context.Context`);
//   - `u *models.User)`       — 2-й входной параметр: переменная `u` — указатель (`*`) на структуру `models.User`;
//   - `error`                 — метод возвращает ошибку `error` (или `nil`);
//   - `{`                     — открываем тело метода.
func (r *Repository) Create(ctx context.Context, u *models.User) error {
	// `QueryRow` выполняет SQL-запрос, который возвращает ровно ОДНУ строку.
	// Почему INSERT возвращает строку? Потому что в конце мы дописали `RETURNING id, created_at`!
	// Это супер-удобная фишка PostgreSQL: база сама генерирует следующий по счёту `id`
	// и текущее время `created_at` и сразу отдаёт их нам обратно.
	//
	// Разбор строки по каждому слову:
	//   - `err :=`                        — создаём переменную `err` для сохранения возможной ошибки;
	//   - `r.db.QueryRow(ctx,`            — у пула `r.db` вызываем метод `QueryRow`, передавая контекст `ctx`;
	//   - `` `INSERT INTO users ...` ``   — текст SQL-запроса с местами под параметры `$1, $2, $3`;
	//   - `u.Name, u.Email, u.PasswordHash,` — значения, которые безопасно подставятся вместо `$1, $2, $3`;
	//   - `).Scan(&u.ID, &u.CreatedAt)`   — метод `.Scan(...)` читает вернувшиеся из базы `id` и `created_at`
	//                                       и записывает их прямо по адресам полей `&u.ID` и `&u.CreatedAt`.
	err := r.db.QueryRow(ctx,
		`INSERT INTO users (name, email, password_hash) VALUES ($1, $2, $3)
		 RETURNING id, created_at`,
		u.Name, u.Email, u.PasswordHash,
	).Scan(&u.ID, &u.CreatedAt)

	// Если при вставке в базу произошла ошибка:
	// Разбор строки по каждому слову:
	//   - `if`         — ключевое слово "если";
	//   - `err != nil` — переменная `err` не равна (`!=`) пустоте `nil` (то есть база вернула ошибку);
	//   - `{`          — открываем блок обработки ошибки.
	if err != nil {
		// Проверяем: а вдруг ошибка случилась потому, что такой email уже есть в таблице?
		// В PostgreSQL у каждой ошибки есть 5-значный код. Код `"23505"` означает `unique_violation`
		// (нарушение уникальности — сработал уникальный индекс по email из миграции 001).
		//
		// Разбор строки по каждому слову:
		//   - `var`             — ключевое слово объявления переменной;
		//   - `pgErr`           — имя переменной для хранения ошибки PostgreSQL;
		//   - `*pgconn.PgError` — тип: указатель (`*`) на структуру ошибки `PgError` из пакета `pgconn`.
		var pgErr *pgconn.PgError

		// Разбор строки по каждому слову:
		//   - `if`                     — если;
		//   - `errors.As(err, &pgErr)` — ошибка `err` внутри является типом `*pgconn.PgError` (копируем её по адресу `&pgErr`);
		//   - `&&`                     — логическое "И" (оба условия должны быть истинны);
		//   - `pgErr.Code == "23505"`  — И код ошибки равен `"23505"` (дубликат email);
		//   - `{`                      — открываем блок.
		if errors.As(err, &pgErr) && pgErr.Code == "23505" {
			// Переводим техническую ошибку базы на язык нашего приложения:
			// Разбор строки по каждому слову:
			//   - `return`               — выйти из метода `Create`;
			//   - `models.ErrUserExists` — вернуть нашу сигнальную ошибку "пользователь уже существует" (HTTP 409).
			return models.ErrUserExists
		}
		// Если это какая-то другая ошибка (например, оборвалась связь с БД), возвращаем как есть.
		// Разбор строки по каждому слову:
		//   - `return` — выйти из метода `Create`;
		//   - `err`    — вернуть исходную ошибку базы данных `err`.
		return err
	}

	// Ошибок нет — возвращаем `nil`.
	// Разбор строки по каждому слову:
	//   - `return` — выйти из метода `Create`;
	//   - `nil`    — вернуть `nil` (вставка прошла без ошибок!).
	return nil
}

// GetByEmail — ищет пользователя в таблице `users` по его электронной почте.
// Возвращает `*models.User` (найденного пользователя) или ошибку `models.ErrNotFound`.
//
// Разбор строки по каждому слову от начала до конца:
//   - `func`                  — объявляем метод;
//   - `(r *Repository)`       — получатель метода (наш репозиторий `r`);
//   - `GetByEmail`            — имя метода;
//   - `(ctx context.Context,` — 1-й входной параметр: контекст запроса `ctx`;
//   - `email string)`         — 2-й входной параметр: строка почты `email` типа `string`;
//   - `(*models.User, error)` — метод возвращает ДВА значения:
//                               1) `*models.User` — указатель на найденного пользователя (или `nil`);
//                               2) `error`        — ошибку (или `nil`);
//   - `{`                     — открываем тело метода.
func (r *Repository) GetByEmail(ctx context.Context, email string) (*models.User, error) {
	// Создаём пустую структуру `u`, в которую `Scan` перепишет данные из найденной строки таблицы.
	// Разбор строки по каждому слову:
	//   - `var`         — объявляем переменную;
	//   - `u`           — имя переменной;
	//   - `models.User` — тип структуры `User` из пакета `models`.
	var u models.User

	// Выполняем SELECT-запрос.
	// `WHERE lower(email) = lower($1)` сравнивает почты без учёта регистра букв.
	// Важно: порядок переменных в `Scan(...)` должен строго совпадать с порядком колонок после слова `SELECT`!
	//
	// Разбор строки по каждому слову:
	//   - `err :=`                    — создаём переменную `err` для результата запроса;
	//   - `r.db.QueryRow(ctx,`        — вызываем метод запроса одной строки `QueryRow` у пула `r.db`;
	//   - `` `SELECT id, name...` ``  — SQL-запрос выбора 5 колонок из таблицы `users`, где `lower(email) = lower($1)`;
	//   - `email,`                    — значение `email`, которое подставится вместо `$1`;
	//   - `).Scan(`                   — вызываем метод `.Scan(...)` для записи найденных колонок в структуру `u`;
	//   - `&u.ID, &u.Name, &u.Email, &u.PasswordHash, &u.CreatedAt)` — адреса 5 полей структуры `u`.
	err := r.db.QueryRow(ctx,
		`SELECT id, name, email, password_hash, created_at
		 FROM users WHERE lower(email) = lower($1)`,
		email,
	).Scan(&u.ID, &u.Name, &u.Email, &u.PasswordHash, &u.CreatedAt)

	// Если база данных ответила `pgx.ErrNoRows` ("в таблице нет ни одной такой строки"):
	// Разбор строки по каждому слову:
	//   - `if`                           — если;
	//   - `errors.Is(err, pgx.ErrNoRows)` — ошибка `err` совпадает с `pgx.ErrNoRows` ("строка не найдена");
	//   - `{`                            — открываем блок.
	if errors.Is(err, pgx.ErrNoRows) {
		// Возвращаем `nil` вместо пользователя и нашу стандартную ошибку `models.ErrNotFound`.
		// Разбор строки по каждому слову:
		//   - `return`             — выйти из метода `GetByEmail`;
		//   - `nil,`               — 1-й результат: `nil` (пользователя нет);
		//   - `models.ErrNotFound` — 2-й результат: наша сигнальная ошибка "не найдено".
		return nil, models.ErrNotFound
	}
	// Если случилась любая другая ошибка (например, проблема с сетью):
	// Разбор строки по каждому слову:
	//   - `if`         — если;
	//   - `err != nil` — переменная `err` не равна `nil` (есть техническая ошибка БД);
	//   - `{`          — открываем блок ошибки.
	if err != nil {
		// Разбор строки по каждому слову:
		//   - `return` — выйти из метода;
		//   - `nil,`   — 1-й результат: `nil` вместо пользователя;
		//   - `err`    — 2-й результат: сама ошибка `err`.
		return nil, err
	}

	// Пользователь найден! Возвращаем указатель на него (`&u`) и `nil` вместо ошибки.
	// Разбор строки по каждому слову:
	//   - `return` — вернуть из метода;
	//   - `&u,`    — 1-й результат: адрес `&` структуры `u` (тип `*models.User`);
	//   - `nil`    — 2-й результат: ошибок нет (`nil`).
	return &u, nil
}
