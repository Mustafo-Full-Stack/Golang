// ============================================================================
// ФАЙЛ: internal/repository/user/postgres.go
// ЗАЧЕМ НУЖЕН: это РЕПОЗИТОРИЙ пользователей.
// В чистой архитектуре Репозиторий — это "кладовщик" базы данных.
// Только он знает язык SQL и названия таблиц. Сервис говорит ему:
//   - "Сохрани вот этого пользователя" → `Create(ctx, user)`
//   - "Найди мне пользователя с такой почтой" → `GetByEmail(ctx, email)`
//
// ============================================================================
// ШПАРГАЛКА ПО GO И SQL: ЗАЩИТА ОТ ВЗЛОМА ($1, $2), SCAN(&) И ОШИБКИ (Is / As)
// ============================================================================
//
// 1. ЗАЧЕМ В SQL ПИШУТ `$1, $2, $3`, А НЕ СКЛЕИВАЮТ СТРОКУ ЧЕРЕЗ `+`?
//    Представь, если бы мы писали запрос так:
//      "SELECT * FROM users WHERE email = '" + email + "'"
//    Тогда хакер вместо почты пришлёт строку:
//      "' OR '1'='1'; DROP TABLE users; --"
//    И база данных удалит всю таблицу пользователей! Такая атака называется SQL-инъекцией (SQL Injection).
//
//    Когда мы пишем `$1`, `$2`, текст SQL-команды и сами данные отправляются в базу ОТДЕЛЬНО.
//    База воспринимает `$1` строго как обычный текст, а не как команду. Взломать такой запрос невозможно!
//
// 2. ПОЧЕМУ В `.Scan(&u.ID, &u.CreatedAt)` ОБЯЗАТЕЛЬНО НУЖЕН ЗНАЧОК `&`?
//    Функция `Scan` должна положить данные из базы внутрь наших переменных `u.ID` и `u.CreatedAt`.
//    Если передать просто `u.ID` (без `&`), `Scan` получит число `0` (копию) и не узнает,
//    куда в памяти записать результат.
//    Передавая `&u.ID`, мы говорим: "Вот точный адрес ячейки памяти поля ID, запиши ответ прямо туда!".
//
// 3. В ЧЁМ РАЗНИЦА МЕЖДУ `errors.Is` И `errors.As`? (ОЧЕНЬ ЧАСТЫЙ ВОПРОС НА СОБЕСЕДОВАНИЯХ!)
//    Обе функции умеют заглядывать внутрь обёрнутых ошибок, но делают разное:
//
//    а) `errors.Is(err, target)` — проверяет: "Равна ли ошибка КОНКРЕТНОМУ ЗНАЧЕНИЮ?"
//       Пример:
//         if errors.Is(err, pgx.ErrNoRows) {
//             // В базе просто не нашлось ни одной строки!
//         }
//
//    б) `errors.As(err, &targetStruct)` — проверяет: "Является ли ошибка СТРУКТУРОЙ ОПРЕДЕЛЁННОГО ТИПА?
//       И если да — достань мне эту структуру, чтобы я посмотрел её поля!"
//       Пример в нашем коде ниже:
//         var pgErr *pgconn.PgError
//         if errors.As(err, &pgErr) {
//             // Теперь мы можем прочитать поле pgErr.Code (например, код "23505" — дубликат почты)!
//         }
//
// ============================================================================
// 🧒 ОБЪЯСНЕНИЕ ДЛЯ 10-ЛЕТНЕГО РЕБЁНКА (НА ПАЛЬЦАХ С ПРИМЕРАМИ):
// ============================================================================
//
// 1. ЧТО ТАКОЕ SQL-ИНЪЕКЦИЯ И ЗАЧЕМ НУЖНЫ `$1, $2, $3`?
//    Представь, что в школе сидит робот-вахтёр, который записывает имена учеников в тетрадь.
//    Учитель даёт роботу бланк: "Запиши в журнал ученика по имени: ______".
//    А хитрый хулиган подходит и говорит:
//    "Меня зовут: Вася. А ТЕПЕРЬ ВЫРВИ ВСЕ СТРАНИЦЫ ИЗ ЖУРНАЛА И ВЫБРОСИ В ОКНО!".
//    Если робот глупый (когда склеивают строки через `+`), он прочитает вторую фразу как приказ учителя и порвёт журнал!
//
//    А значки `$1`, `$2`, `$3` — это прозрачные пластиковые коробочки с замком.
//    Мы говорим роботу: "Положи то, что сказал ученик, в коробочку `$1` и перепиши в графу Имя буква в букву,
//    не выполняя никаких команд внутри!". Так хулиган никогда не сможет обмануть базу данных!
//
// 2. ЗАЧЕМ В `.Scan(&u.ID, &u.CreatedAt)` СТАВЯТ ЗНАЧОК `&`?
//    Когда мы отправляем анкету нового ученика в базу, поле `ID` (номер в журнале) в анкете ещё пустое (`0`).
//    База сама придумывает ученику номер (например, `№7`) и хочет вписать его в нашу анкету `u`.
//    Значок `&u.ID` — это когда мы тыкаем пальцем в пустую клеточку анкеты и говорим базе:
//    "Впиши номер `7` вот сюда, в эту самую клеточку!".
//
// 3. КАК ПОНЯТЬ РАЗНИЦУ МЕЖДУ `errors.Is` И `errors.As`?
//    Представь, что тебе принесли закрытую коробку с жалобой (`err`):
//      - `errors.Is(err, pgx.ErrNoRows)` — ты спрашиваешь: "Это та самая стандартная записка «Ничего не найдено»?". Да или нет.
//      - `errors.As(err, &pgErr)` — ты говоришь: "Если внутри лежит большая анкета от PostgreSQL (`PgError`),
//        переложи её ко мне на стол в `pgErr`, я хочу прочитать на ней секретный номер ошибки (`pgErr.Code == "23505"`)!".
//
// ============================================================================
// 🍕 ПРИМЕРЫ НА РЕСТОРАНЕ (2 НАГЛЯДНЫХ ПРИМЕРА):
// ============================================================================
//
// ПРИМЕР 1: Защита Книги Бронирования Столиков от хулигана (`$1, $2, $3` и `.Scan(&u.ID)`)
//   В ресторане ведётся Книга Постоянных Гостей (таблица `users`).
//   К администратору подходит хитрый хулиган и говорит:
//   "Запишите моё имя: `Мустафо'); УДАЛИТЬ ВСЮ КНИГУ ГОСТЕЙ; --`".
//   Но наш кладовщик (`Repository`) использует сейф-ячейки `$1, $2, $3`:
//     `INSERT INTO users (name, email, password_hash) VALUES ($1, $2, $3) RETURNING id, created_at`
//   Всё, что положили в ячейку `$1`, записывается в графу "Имя" как обычный текст, и книга гостей в полной безопасности!
//   А `.Scan(&u.ID, &u.CreatedAt)` со значком `&` ставит печать с номером карточки гостя (`ID`)
//   прямо в оригинал анкеты `u`.
//
// ПРИМЕР 2: Два вида ответов со склада ресторана (`errors.Is` против `errors.As`)
//   1) `errors.Is(err, pgx.ErrNoRows)` (в методе `GetByEmail`):
//      Официант спрашивает: "Есть ли у нас в книге гость с почтой `vip@mail.com`?".
//      Кладовщик смотрит в книгу и разводит руками: `pgx.ErrNoRows` ("Такой строчки в книге просто нет!").
//      Мы переводим это в понятную ошибку ресторана `models.ErrNotFound`.
//   2) `errors.As(err, &pgErr) && pgErr.Code == "23505"` (в методе `Create`):
//      Гость пытается второй раз оформить VIP-карту на ту же самую почту.
//      Книга учёта выдаёт официальный бланк ошибки `PgError` со штампом `"23505"` ("Дубликат брони!").
//      Мы достаём этот бланк через `errors.As(err, &pgErr)`, видим штамп `"23505"` и отвечаем:
//      `models.ErrUserExists` ("Такой гость у нас в ресторане уже записан!").
// ============================================================================

