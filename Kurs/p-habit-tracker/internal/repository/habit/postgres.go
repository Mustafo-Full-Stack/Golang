// Repository — структура репозитория привычек.
// Разбор строки по каждому слову:
//   - `type`       — создаём новый тип данных;
//   - `Repository` — имя структуры;
//   - `struct`     — структура;
//   - `{`          — открываем список полей.
type Repository struct {
	// db — приватное поле с пулом соединений к PostgreSQL.
	// Разбор строки: `db` (имя приватного поля) `*pgxpool.Pool` (тип: указатель на пул соединений).
	db *pgxpool.Pool
}

// NewRepository — конструктор репозитория привычек.
// Разбор строки по каждому слову от начала до конца:
//   - `func`               — объявляем функцию;
//   - `NewRepository`      — имя конструктора;
//   - `(db *pgxpool.Pool)` — входной параметр `db` с типом `*pgxpool.Pool`;
//   - `*Repository`        — возвращает указатель (`*`) на созданный `Repository`;
//   - `{`                  — открываем тело функции.
func NewRepository(db *pgxpool.Pool) *Repository {
	// Разбор строки: `return &Repository{db: db}` — создаём структуру `Repository`, кладём `db` и возвращаем её адрес `&`.
	return &Repository{db: db}
}

// Create — сохраняет новую привычку в таблицу `habits`.
// Записывает сгенерированные базой `id` и `created_at` прямо в переданную по указателю структуру `h`.
//
// Разбор строки по каждому слову от начала до конца:
//   - `func`                  — объявляем метод;
//   - `(r *Repository)`       — получатель метода (наш репозиторий `r`);
//   - `Create`                — имя метода;
//   - `(ctx context.Context,` — 1-й входной параметр: контекст запроса `ctx`;
//   - `h *models.Habit)`      — 2-й входной параметр: указатель (`*`) на структуру `models.Habit`;
//   - `error`                 — возвращает ошибку `error` (или `nil`);
//   - `{`                     — открываем тело метода.
func (r *Repository) Create(ctx context.Context, h *models.Habit) error {
	// Используем `QueryRow`, так как `RETURNING id, created_at` вернёт ровно одну строку.
	// Обрати внимание на лаконичность: `Scan(...)` сам возвращает `error` (или `nil`),
	// поэтому мы можем написать `return r.db.QueryRow(...).Scan(...)` сразу в одну конструкцию!
	//
	// Разбор строки по каждому слову:
	//   - `return`                     — вернуть результат вызова `.Scan(...)`;
	//   - `r.db.QueryRow(ctx, ...)`    — отправить INSERT-запрос с возвратом одной строки (`RETURNING id, created_at`);
	//   - `h.UserID, h.Name,`          — значения для `$1` (владелец) и `$2` (название привычки);
	//   - `).Scan(&h.ID, &h.CreatedAt)` — записать вернувшиеся `id` и `created_at` по адресам полей `&h.ID` и `&h.CreatedAt`.
	return r.db.QueryRow(ctx,
		`INSERT INTO habits (user_id, name) VALUES ($1, $2)
		 RETURNING id, created_at`,
		h.UserID, h.Name,
	).Scan(&h.ID, &h.CreatedAt)
}

// ListByUser — достаёт из базы ВСЕ привычки конкретного пользователя `userID`.
// Возвращает слайс `[]models.Habit` и ошибку `error`.
//
// Разбор строки по каждому слову от начала до конца:
//   - `func`                    — объявляем метод;
//   - `(r *Repository)`         — получатель метода `r`;
//   - `ListByUser`              — имя метода;
//   - `(ctx context.Context,`   — 1-й входной параметр: контекст `ctx`;
//   - `userID int64)`           — 2-й входной параметр: ID пользователя типа `int64`;
//   - `([]models.Habit, error)` — метод возвращает ДВА значения:
//                                 1) `[]models.Habit` — слайс (список) привычек `models.Habit`;
//                                 2) `error`          — ошибку (или `nil`);
//   - `{`                       — открываем тело метода.
func (r *Repository) ListByUser(ctx context.Context, userID int64) ([]models.Habit, error) {
	// ШАГ 1. Отправляем запрос через `.Query(...)`, потому что у пользователя может быть много привычек.
	// `ORDER BY id` сортирует привычки по порядку их создания (от старых к новым).
	//
	// Разбор строки по каждому слову:
	//   - `rows, err`              — создаём переменные `rows` (курсор строк ответа) и `err` (ошибка);
	//   - `:=`                     — объявляем и присваиваем;
	//   - `r.db.Query(ctx, ..., userID)` — выполняем SELECT-запрос нескольких строк для `user_id = $1`.
	rows, err := r.db.Query(ctx,
		`SELECT id, user_id, name, created_at FROM habits
		 WHERE user_id = $1 ORDER BY id`,
		userID,
	)
	// Разбор строки по каждому слову:
	//   - `if`         — ключевое слово "если";
	//   - `err != nil` — переменная ошибки `err` не равна (`!=`) пустоте `nil` (то есть запрос в БД не удался);
	//   - `{`          — открываем блок обработки ошибки.
	if err != nil {
		// Разбор строки по каждому слову:
		//   - `return` — немедленно выйти из метода `ListByUser`;
		//   - `nil,`   — 1-е возвращаемое значение: пустой слайс `nil` (списка привычек нет);
		//   - `err`    — 2-е возвращаемое значение: сама ошибка `err`, которую вернула база данных.
		return nil, err
	}
	// ОЧЕНЬ ВАЖНО: пока `rows` не закрыт, соединение с базой занято и не может вернуться в пул!
	// Если забыть `defer rows.Close()`, через 10-20 запросов все соединения в пуле закончатся,
	// и сервер намертво зависнет (это называется утечкой соединений — Connection Leak).
	// Разбор строки по каждому слову:
	//   - `defer`        — ключевое слово "выполни эту команду автоматически при выходе из функции";
	//   - `rows`         — наш курсор со строками ответа из базы;
	//   - `.Close()`     — вызываем метод закрытия курсора, чтобы вернуть соединение в пул.
	defer rows.Close()

	// ШАГ 2. Создаём пустой слайс `list`, куда будем складывать прочитанные привычки.
	// Разбор строки по каждому слову:
	//   - `var`            — ключевое слово объявления переменной;
	//   - `list`           — имя нашего слайса (подноса для привычек);
	//   - `[]models.Habit` — тип: слайс (`[]`), внутри которого лежат структуры `models.Habit`.
	var list []models.Habit

	// ШАГ 3. Бежим по строкам ответа в цикле `for rows.Next()`.
	// Как работает `rows.Next()`?
	// Перед первой строкой курсор стоит "на старте". Каждый вызов `rows.Next()` двигает его
	// на одну строку вперёд и возвращает `true`. Когда строки кончатся — вернёт `false`, и цикл завершится.
	// Разбор строки по каждому слову:
	//   - `for`         — ключевое слово цикла ("повторяй, пока условие истинно");
	//   - `rows.Next()` — метод курсора `rows`: шагает на следующую строку и возвращает `true` (есть строка) или `false` (конец);
	//   - `{`           — открываем тело цикла.
	for rows.Next() {
		// Создаём переменную `h` под одну привычку.
		// Разбор строки по каждому слову:
		//   - `var`          — объявляем новую переменную;
		//   - `h`            — имя переменной для одной привычки;
		//   - `models.Habit` — тип структуры `Habit` из пакета `models`.
		var h models.Habit
		// Перекладываем 4 колонки из текущей строки БД в поля структуры `h`.
		// Разбор строки по каждому слову:
		//   - `if`            — если;
		//   - `err :=`        — создаём переменную `err` и записываем в неё результат вызова `Scan`;
		//   - `rows.Scan(`    — вызываем метод `Scan` у курсора `rows` (читает колонки текущей строки БД);
		//   - `&h.ID,`        — 1-я колонка (`id`) записывается по адресу `&` поля `h.ID`;
		//   - `&h.UserID,`    — 2-я колонка (`user_id`) записывается по адресу `&` поля `h.UserID`;
		//   - `&h.Name,`      — 3-я колонка (`name`) записывается по адресу `&` поля `h.Name`;
		//   - `&h.CreatedAt)` — 4-я колонка (`created_at`) записывается по адресу `&` поля `h.CreatedAt`;
		//   - `;`             — точка с запятой отделяет вызов `Scan` от проверки условия;
		//   - `err != nil`    — условие: если при чтении строки случилась ошибка (`err` не равна `nil`);
		//   - `{`             — открываем блок ошибки.
		if err := rows.Scan(&h.ID, &h.UserID, &h.Name, &h.CreatedAt); err != nil {
			// Разбор строки по каждому слову:
			//   - `return` — прерываем цикл и выходим из метода;
			//   - `nil,`   — 1-й результат: `nil` вместо списка привычек;
			//   - `err`    — 2-й результат: возникшая ошибка чтения `err`.
			return nil, err
		}
		// Добавляем прочитанную привычку в конец нашего слайса `list`.
		// Разбор строки по каждому слову:
		//   - `list`            — переменная нашего списка привычек;
		//   - `=`               — записываем обновлённый список обратно в `list`;
		//   - `append(`         — встроенная функция Go для добавления элемента в конец слайса;
		//   - `list,`           — 1-й аргумент: в какой слайс добавляем;
		//   - `h)`              — 2-й аргумент: какую привычку (`h`) кладём в конец слайса.
		list = append(list, h)
	}

	// ШАГ 4. Почему в конце мы возвращаем `rows.Err()`, а не просто `nil`?
	// Потому что цикл `for rows.Next()` мог остановиться не только из-за конца таблицы,
	// но и если прямо посередине чтения оборвался интернет до базы!
	// `rows.Err()` проверит это: если всё прошло штатно, он вернёт `nil`.
	// Разбор строки по каждому слову:
	//   - `return`     — выйти из метода и вернуть результаты;
	//   - `list,`      — 1-й результат: собранный слайс привычек `list`;
	//   - `rows.Err()` — 2-й результат: вызываем метод `Err()` у `rows` (вернёт `nil`, если чтение прошло без сбоев).
	return list, rows.Err()
}

// GetByID — находит одну привычку по её уникальному номеру `id`.
// Нужен сервису, чтобы проверить, существует ли привычка и кто её владелец (`UserID`).
//
// Разбор строки по каждому слову от начала до конца:
//   - `func`                   — объявляем метод;
//   - `(r *Repository)`        — получатель метода `r`;
//   - `GetByID`                — имя метода;
//   - `(ctx context.Context,`  — 1-й входной параметр: контекст `ctx`;
//   - `id int64)`              — 2-й входной параметр: ID привычки типа `int64`;
//   - `(*models.Habit, error)` — возвращает указатель на привычку `*models.Habit` и ошибку `error`;
//   - `{`                      — открываем тело метода.
func (r *Repository) GetByID(ctx context.Context, id int64) (*models.Habit, error) {
	// Разбор строки по каждому слову:
	//   - `var`          — ключевое слово объявления переменной;
	//   - `h`            — имя переменной для привычки;
	//   - `models.Habit` — тип структуры `Habit` из пакета `models`.
	var h models.Habit

	// Запрашиваем одну строку через `QueryRow`.
	// Разбор строки по каждому слову:
	//   - `err :=`            — создаём переменную `err` для результата выполнения запроса;
	//   - `r.db.QueryRow(`    — вызываем метод запроса одной строки у пула БД `r.db`;
	//   - `ctx,`              — 1-й аргумент: контекст запроса;
	//   - `` `SELECT ...` ``  — 2-й аргумент: SQL-запрос выбора 4 колонок из таблицы `habits`, где `id = $1`;
	//   - `id,`               — 3-й аргумент: значение `id`, которое подставится вместо `$1`;
	//   - `).Scan(`           — вызываем `.Scan(...)`, чтобы переложить найденную строку в поля `h`;
	//   - `&h.ID, &h.UserID, &h.Name, &h.CreatedAt)` — адреса 4 полей структуры `h`, куда запишутся данные.
	err := r.db.QueryRow(ctx,
		`SELECT id, user_id, name, created_at FROM habits WHERE id = $1`,
		id,
	).Scan(&h.ID, &h.UserID, &h.Name, &h.CreatedAt)

	// Если привычки с таким `id` нет в базе — превращаем `pgx.ErrNoRows` в нашу `models.ErrNotFound`.
	// Разбор строки по каждому слову:
	//   - `if`                           — если;
	//   - `errors.Is(err, pgx.ErrNoRows)` — функция `errors.Is` проверяет, равна ли ошибка `err` ошибке `pgx.ErrNoRows` ("строка не найдена");
	//   - `{`                            — открываем блок.
	if errors.Is(err, pgx.ErrNoRows) {
		// Разбор строки по каждому слову:
		//   - `return`             — выходим из метода;
		//   - `nil,`               — 1-й результат: `nil` (привычка не найдена);
		//   - `models.ErrNotFound` — 2-й результат: наша сигнальная ошибка "не найдено" (для кода 404).
		return nil, models.ErrNotFound
	}
	// Разбор строки по каждому слову:
	//   - `if`         — если;
	//   - `err != nil` — произошла любая другая ошибка базы данных;
	//   - `{`          — открываем блок ошибки.
	if err != nil {
		// Разбор строки по каждому слову:
		//   - `return` — выходим из метода;
		//   - `nil,`   — 1-й результат: `nil` вместо привычки;
		//   - `err`    — 2-й результат: сама техническая ошибка `err`.
		return nil, err
	}
	// Разбор строки по каждому слову:
	//   - `return` — выходим из метода;
	//   - `&h,`    — 1-й результат: берём адрес `&` заполненной структуры `h` (тип `*models.Habit`);
	//   - `nil`    — 2-й результат: `nil` (ошибок нет!).
	return &h, nil
}

// CreateCheck — ставит отметку о выполнении привычки `habitID` за дату `date`.
// Разбор строки по каждому слову от начала до конца:
//   - `func`                  — объявляем метод;
//   - `(r *Repository)`       — получатель метода `r`;
//   - `CreateCheck`           — имя метода;
//   - `(ctx context.Context,` — 1-й входной параметр: контекст `ctx`;
//   - `habitID int64,`        — 2-й входной параметр: ID привычки типа `int64`;
//   - `date time.Time)`       — 3-й входной параметр: дата выполнения типа `time.Time`;
//   - `error`                 — возвращает ошибку `error` (или `nil`);
//   - `{`                     — открываем тело метода.
func (r *Repository) CreateCheck(ctx context.Context, habitID int64, date time.Time) error {
	// Здесь нам не нужно возвращать никаких колонок из базы, поэтому используем `Exec`.
	//
	// Как работает `ON CONFLICT (habit_id, date) DO NOTHING`?
	// В таблице `habit_checks` стоит ограничение `UNIQUE (habit_id, date)` — нельзя дважды
	// отметить одну и ту же привычку в один и тот же день.
	// Если пользователь нажмёт кнопку второй раз за день, возникнет конфликт уникальности.
	// Фраза `DO NOTHING` говорит базе: "Не падай с ошибкой, просто проигнорируй вставку (вставь 0 строк)".
	//
	// Разбор строки по каждому слову:
	//   - `tag, err`            — создаём переменные `tag` (отчёт базы о выполненных изменениях) и `err` (ошибка);
	//   - `:=`                  — объявляем и присваиваем;
	//   - `r.db.Exec(`          — вызываем метод `Exec` у пула БД (выполняет SQL без возврата строк);
	//   - `ctx,`                — 1-й аргумент: контекст запроса;
	//   - `` `INSERT INTO...` `` — 2-й аргумент: текст SQL-команды вставки отметки;
	//   - `habitID, date)`      — 3-й и 4-й аргументы: значения для `$1` (ID привычки) и `$2` (дата).
	tag, err := r.db.Exec(ctx,
		`INSERT INTO habit_checks (habit_id, date) VALUES ($1, $2)
		 ON CONFLICT (habit_id, date) DO NOTHING`,
		habitID, date,
	)
	// Разбор строки по каждому слову:
	//   - `if`         — если;
	//   - `err != nil` — запрос в БД завершился с технической ошибкой;
	//   - `{`          — открываем блок ошибки.
	if err != nil {
		// Разбор строки по каждому слову:
		//   - `return` — выходим из метода;
		//   - `err`    — возвращаем ошибку `err`.
		return err
	}

	// Спрашиваем у `tag`: сколько строк реально добавилось в таблицу?
	// Если `0` — значит сработал `ON CONFLICT DO NOTHING`, то есть галочка за сегодня УЖЕ стояла!
	// Разбор строки по каждому слову:
	//   - `if`                 — если;
	//   - `tag.RowsAffected()` — вызываем метод `RowsAffected()` у `tag` (сколько строк было вставлено);
	//   - `== 0`               — равно нулю (ни одной новой строки не добавилось);
	//   - `{`                  — открываем блок ошибки.
	if tag.RowsAffected() == 0 {
		// Возвращаем понятную ошибку (Handler превратит её в HTTP 409 Conflict).
		// Разбор строки по каждому слову:
		//   - `return`                   — выходим из метода;
		//   - `models.ErrAlreadyChecked` — возвращаем ошибку "привычка уже отмечена сегодня".
		return models.ErrAlreadyChecked
	}

	// Если `RowsAffected() == 1`, значит галочка успешно поставлена!
	// Разбор строки по каждому слову:
	//   - `return` — выходим из метода;
	//   - `nil`    — возвращаем `nil` (ошибок нет!).
	return nil
}

// ListChecks — возвращает всю историю выполнения привычки `habitID` (список дат по возрастанию).
// Разбор строки по каждому слову от начала до конца:
//   - `func`                         — объявляем метод;
//   - `(r *Repository)`              — получатель метода `r`;
//   - `ListChecks`                   — имя метода;
//   - `(ctx context.Context,`        — 1-й входной параметр: контекст `ctx`;
//   - `habitID int64)`               — 2-й входной параметр: ID привычки типа `int64`;
//   - `([]models.HabitCheck, error)` — возвращает слайс отметок `[]models.HabitCheck` и ошибку `error`;
//   - `{`                            — открываем тело метода.
func (r *Repository) ListChecks(ctx context.Context, habitID int64) ([]models.HabitCheck, error) {
	// Запрашиваем все отметки для данной привычки, отсортированные от старых дат к новым (`ORDER BY date`).
	// Разбор строки по каждому слову:
	//   - `rows, err`          — создаём переменные `rows` (курсор строк ответа) и `err` (ошибка);
	//   - `:=`                 — объявляем и присваиваем;
	//   - `r.db.Query(`        — вызываем метод `Query` для получения нескольких строк из БД;
	//   - `ctx,`               — 1-й аргумент: контекст запроса;
	//   - `` `SELECT ...` ``   — 2-й аргумент: SQL-запрос выбора `id, habit_id, date` из `habit_checks`;
	//   - `habitID)`           — 3-й аргумент: значение `habitID` вместо `$1`.
	rows, err := r.db.Query(ctx,
		`SELECT id, habit_id, date FROM habit_checks
		 WHERE habit_id = $1 ORDER BY date`,
		habitID,
	)
	// Разбор строки по каждому слову:
	//   - `if`         — если;
	//   - `err != nil` — при отправке SQL-запроса произошла ошибка;
	//   - `{`          — открываем блок ошибки.
	if err != nil {
		// Разбор строки по каждому слову:
		//   - `return` — выходим из метода;
		//   - `nil,`   — 1-й результат: пустой список `nil`;
		//   - `err`    — 2-й результат: ошибка `err`.
		return nil, err
	}
	// Обязательно закрываем `rows` при выходе из функции.
	// Разбор строки по каждому слову:
	//   - `defer`        — отложить выполнение до момента выхода из функции `ListChecks`;
	//   - `rows.Close()` — закрыть курсор `rows` и освободить соединение с базой данных.
	defer rows.Close()

	// Собираем все строки в слайс `list`.
	// Разбор строки по каждому слову:
	//   - `var`                 — ключевое слово объявления переменной;
	//   - `list`                — имя слайса для хранения отметок;
	//   - `[]models.HabitCheck` — тип: слайс (`[]`) элементов `models.HabitCheck`.
	var list []models.HabitCheck

	// Разбор строки по каждому слову:
	//   - `for`         — ключевое слово цикла ("повторяй, пока есть строки");
	//   - `rows.Next()` — переключает курсор на следующую строку ответа БД (возвращает `true`, пока строки не кончились);
	//   - `{`           — открываем тело цикла.
	for rows.Next() {
		// Разбор строки по каждому слову:
		//   - `var`               — объявляем переменную;
		//   - `check`             — имя переменной для одной отметки;
		//   - `models.HabitCheck` — тип структуры `HabitCheck` из пакета `models`.
		var check models.HabitCheck

		// Читаем 3 поля из текущей строки БД в структуру `check` и проверяем ошибку.
		// Разбор строки по каждому слову от начала до конца:
		//   - `if`             — ключевое слово "если";
		//   - `err :=`         — создаём переменную `err` и кладём в неё результат вызова `rows.Scan`;
		//   - `rows.Scan(`     — метод чтения колонок текущей строки БД;
		//   - `&check.ID,`     — 1-я колонка (`id`) записывается по адресу `&` в поле `check.ID`;
		//   - `&check.HabitID,` — 2-я колонка (`habit_id`) записывается по адресу `&` в поле `check.HabitID`;
		//   - `&check.Date)`   — 3-я колонка (`date`) записывается по адресу `&` в поле `check.Date`;
		//   - `;`              — разделитель между действием `Scan` и проверкой условия;
		//   - `err != nil`     — условие: если `err` не равна `nil` (не удалось прочитать строку);
		//   - `{`              — открываем блок обработки ошибки.
		if err := rows.Scan(&check.ID, &check.HabitID, &check.Date); err != nil {
			// Разбор строки по каждому слову:
			//   - `return` — прерываем цикл и выходим из функции;
			//   - `nil,`   — 1-й результат: `nil` вместо списка отметок;
			//   - `err`    — 2-й результат: ошибка чтения `err`.
			return nil, err
		}

		// Добавляем прочитанную отметку в конец списка `list`.
		// Разбор строки по каждому слову:
		//   - `list`               — наш слайс отметок;
		//   - `=`                  — сохраняем новый расширенный слайс обратно в `list`;
		//   - `append(list, check)` — встроенная функция `append` добавляет структуру `check` в конец слайса `list`.
		list = append(list, check)
	}

	// Возвращаем собранный список `list` и проверяем `rows.Err()`.
	// Разбор строки по каждому слову:
	//   - `return`     — выйти из метода и вернуть результаты;
	//   - `list,`      — 1-й результат: готовый слайс всех отметок `list`;
	//   - `rows.Err()` — 2-й результат: проверяет, не было ли обрыва связи во время цикла (вернёт `nil`, если всё хорошо).
	return list, rows.Err()
}
