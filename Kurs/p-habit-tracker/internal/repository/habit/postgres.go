// 1. ЧТО ТАКОЕ СЛАЙС (Slice, или Срез) `[]models.Habit`?
//    В Go есть массивы фиксированной длины, например `[3]int` (строго 3 числа, добавить 4-е нельзя).
//    Но на практике никто не знает заранее, сколько привычек у пользователя — 0, 2 или 100.
//    Поэтому в 99% случаев в Go используют СЛАЙСЫ (пишутся с пустыми скобками: `[]int`, `[]models.Habit`).
//
//    Слайс — это резиновый (динамический) список, который умеет расти!
//    Как с ним работать (пример):
//      var nums []int           // Создали пустой слайс чисел (сейчас в нём 0 элементов)
//      nums = append(nums, 10)  // Добавили число 10 → [10]
//      nums = append(nums, 20)  // Добавили число 20 → [10, 20]
//      fmt.Println(len(nums))   // Выведет 2 (количество элементов в слайсе)
//
//    Почему результат `append` снова присваивают в `nums = append(nums, ...)`?
//    Потому что когда место в старом списке заканчивается, `append` выделяет в памяти
//    новый, более просторный участок, перекладывает элементы туда и возвращает новый слайс!
//
// 2. ТРИ ГЛАВНЫХ МЕТОДА РАБОТЫ С БАЗОЙ В БИБЛИОТЕКЕ `pgx`:
//    В этом файле ты увидишь все три метода — запомни, когда какой нужен:
//
//    а) `r.db.QueryRow(ctx, sql, args...).Scan(...)`
//       Когда нужен: когда запрос возвращает РОВНО ОДНУ строку
//       (например, найти одну привычку по `id` или вставить строку с `RETURNING id`).
//
//    б) `rows, err := r.db.Query(ctx, sql, args...)`
//       Когда нужен: когда запрос возвращает МНОГО строк (список привычек, список отметок).
//       Он возвращает "курсор" `rows`, по которому мы шагаем в цикле `for rows.Next()`,
//       и его ОБЯЗАТЕЛЬНО нужно закрывать через `defer rows.Close()`.
//
//    в) `tag, err := r.db.Exec(ctx, sql, args...)`
//       Когда нужен: когда нам НЕ нужны данные из базы, нужно только выполнить команду
//       (`INSERT`, `UPDATE`, `DELETE` без `RETURNING`).
//       В ответе приходит `tag`, у которого можно спросить `tag.RowsAffected()` —
//       "сколько строк реально изменилось?".
//
// ============================================================================
// 🧒 ОБЪЯСНЕНИЕ ДЛЯ 10-ЛЕТНЕГО РЕБЁНКА (НА ПАЛЬЦАХ С ПРИМЕРАМИ):
// ============================================================================
//
// 1. ЧТО ТАКОЕ СЛАЙС (`[]models.Habit`) И `append`?
//    Представь игрушечный паровозик:
//      - Обычный массив (`[3]Habit`) — это литая машинка ровно на 3 места. Четвёртого пассажира посадить нельзя!
//      - А СЛАЙС (`[]Habit`) — это паровозик на магнитах!
//        Сначала мы пишем `var list []models.Habit` — у нас вообще 0 вагончиков.
//        Затем в цикле мы пишем `list = append(list, h)` — и к нашему паровозику сзади "щёлк!" и
//        примагничивается новый вагончик с привычкой `h`. И так можно прицеплять хоть миллион вагончиков!
//
// 2. КАК ПОНЯТЬ `rows`, `for rows.Next()` И `defer rows.Close()`?
//    Представь аппарат с газировкой в кафе:
//      - `rows, err := r.db.Query(...)` — мы нажали рычаг, и из крана потекла струя с привычками (`rows`).
//      - `for rows.Next()` — мы подставляем стаканчики один за другим, пока из крана течёт газировка.
//      - `defer rows.Close()` — САМОЕ ГЛАВНОЕ ПРАВИЛО: когда набрали все стаканчики, обязательно
//        отпусти рычаг и закрой кран! Если забыть `defer rows.Close()`, кран останется открытым,
//        вся база данных зальётся водой и никому больше газировки не достанется!
//
// 3. ЧТО ТАКОЕ `ON CONFLICT (habit_id, date) DO NOTHING` В `CreateCheck`?
//    Представь, что ты собираешь наклейки в альбом. На странице "Сегодня" есть место только для ОДНОЙ наклейки.
//    Если ты пытаешься наклеить туда вторую наклейку за сегодня, возникает КОНФЛИКТ (`ON CONFLICT`).
//    Команда `DO NOTHING` ("ничего не делай") говорит: "Не рви альбом и не кричи, просто не клей вторую наклейку!".
//    А потом мы смотрим на `tag.RowsAffected()` (сколько наклеек приклеилось): если `0` — значит, место уже было занято!
//
// ============================================================================
// 🍕 ПРИМЕРЫ НА РЕСТОРАНЕ (2 НАГЛЯДНЫХ ПРИМЕРА):
// ============================================================================
//
// ПРИМЕР 1: Три способа попросить что-то у кладовщика ресторана (`QueryRow`, `Query`, `Exec`)
//   1) `QueryRow` (в `Create` и `GetByID` — ровно 1 тарелка):
//      Повар говорит кладовщику: "Дай мне ОДНО конкретное блюдо под номером №5 (`WHERE id = $1`)".
//      Кладовщик выносит ровно одну тарелку, и мы сразу перекладываем её в `&h`.
//   2) `Query` (в `ListByUser` и `ListChecks` — тележка с тарелками):
//      Повар говорит: "Вывези мне тележку (`rows`) со ВСЕМИ любимыми блюдами гостя №5!".
//      Мы берём поднос (`var list []models.Habit`), в цикле `for rows.Next()` перекладываем тарелки
//      с тележки на поднос через `list = append(list, h)`, а пустую тележку ОБЯЗАТЕЛЬНО откатываем
//      обратно на склад через `defer rows.Close()`!
//   3) `Exec` (в `CreateCheck` — просто поставить печать без выноса тарелок):
//      Повар говорит: "Поставь штамп в карточку постоянного гостя за сегодняшний обед!".
//      Никаких тарелок выносить не надо, нужно только узнать через `tag.RowsAffected()`,
//      поставился ли штамп (`1`) или он уже стоял сегодня (`0`).
//
// ПРИМЕР 2: Карточка бесплатного десерта раз в день (`ON CONFLICT (habit_id, date) DO NOTHING`)
//   В ресторане акция: по карточке `habit_id` можно получить 1 бесплатный десерт в день (`date`).
//   Если гость уже получил десерт утром и подходит за вторым вечером:
//     - База данных видит конфликт `(habit_id, date)` (сегодняшняя дата уже записана!).
//     - Благодаря `ON CONFLICT ... DO NOTHING`, касса не ломается, а просто выдаёт `0` новых чеков (`tag.RowsAffected() == 0`).
//     - Мы видим этот `0` и вежливо говорим гостю: `models.ErrAlreadyChecked` ("Сегодня десерт уже выдан!").
// ============================================================================

