// ============================================================================
// ФАЙЛ: internal/config/config.go
// ЗАЧЕМ НУЖЕН: читает настройки приложения из ПЕРЕМЕННЫХ ОКРУЖЕНИЯ (Environment Variables)
// и складывает их в удобную структуру Config.
//
// ЧТО ТАКОЕ ПЕРЕМЕННЫЕ ОКРУЖЕНИЯ (ПРОСТЫМИ СЛОВАМИ)?
// Когда программа запускается на компьютере или сервере, операционная система
// передаёт ей набор пар "ИМЯ=ЗНАЧЕНИЕ". Например:
//   HTTP_PORT=8080
//   JWT_SECRET=my-super-secret-key
//   POSTGRES_PASSWORD=12345
//
// Зачем это нужно? Почему нельзя написать пароль прямо в коде?
//   1) Безопасность: код выкладывают на GitHub. Если написать пароль в коде, его увидят все!
//   2) Гибкость: у тебя на ноутбуке база данных на "localhost", а на боевом сервере — на другом адресе.
//      Код программы остаётся один и тот же, меняются только переменные окружения снаружи.
//
// ============================================================================
// ШПАРГАЛКА ПО GO: СТРУКТУРЫ (struct) И УКАЗАТЕЛИ (* и &)
// ============================================================================
//
// 1. ЧТО ТАКОЕ СТРУКТУРА (struct)?
//    В Go нет классов (class), как в Java или Python. Вместо них — СТРУКТУРЫ.
//    Структура — это коробка (или анкета), в которой лежат несколько переменных разных типов.
//
//    Пример:
//      type Car struct {
//          Brand string // марка машины (строка)
//          Year  int    // год выпуска (число)
//      }
//      myCar := Car{Brand: "Toyota", Year: 2020}
//      fmt.Println(myCar.Brand) // напечатает "Toyota"
//
// 2. ЧТО ТАКОЕ УКАЗАТЕЛЬ (`*`) И ВЗЯТИЕ АДРЕСА (`&`)? (ОЧЕНЬ ВАЖНО!)
//    Представь большой бумажный учебник.
//    Когда ты передаёшь переменную в функцию ОБЫЧНЫМ способом (без `*` и `&`),
//    Go делает КСЕРОКОПИЮ всего учебника и отдаёт копию.
//    Если функция нарисует что-то на странице копии — твой оригинальный учебник НЕ изменится!
//
//    А УКАЗАТЕЛЬ — это маленькая бумажка, на которой написан АДРЕС:
//    "Учебник лежит в комнате 5, на полке 2" (в памяти компьютера это адрес вида 0xc0000140a0).
//
//    Два главных значка, которые нужно выучить наизусть:
//      `&` (амперсанд) — читается как "АДРЕС ПЕРЕМЕННОЙ" (сделать бумажку с адресом).
//      `*` (звёздочка) — имеет два значения:
//          а) Перед ТИПОМ (`*Config`, `*int`) — читается как "УКАЗАТЕЛЬ НА тип Config".
//          б) Перед ПЕРЕМЕННОЙ (`*p`) — "пройти по адресу на бумажке и взять сам предмет".
//
//    Наглядный пример в коде:
//      x := 10       // Обычная переменная x, в ней лежит число 10.
//      p := &x       // В p лежит АДРЕС переменной x (тип p — это *int, "указатель на int").
//      *p = 99       // Идём по адресу p и меняем значение внутри на 99.
//      // Теперь x тоже равен 99! Потому что p указывал прямо на x.
//
//    Зачем мы возвращаем `*Config` (указатель), а не просто `Config`?
//    Чтобы не ксерокопировать всю структуру настроек каждый раз, когда мы передаём её дальше,
//    и чтобы в случае ошибки можно было вернуть `nil` ("пустой адрес, настроек нет").
//
// ============================================================================
// 🧒 ОБЪЯСНЕНИЕ ДЛЯ 10-ЛЕТНЕГО РЕБЁНКА (НА ПАЛЬЦАХ С ПРИМЕРАМИ):
// ============================================================================
//
// 1. ЧТО ТАКОЕ `Config` И ПЕРЕМЕННЫЕ ОКРУЖЕНИЯ (`os.Getenv`)?
//    Представь игру Minecraft. Сама игра — это наша программа.
//    Но перед тем как войти в мир, ты заходишь в меню настроек и выбираешь:
//    сложность игры, имя мира, пароль от сервера.
//    Ты же не переписываешь программный код Minecraft каждый раз, когда хочешь поменять пароль!
//    Ты просто меняешь табличку с настройками снаружи игры.
//    Вот эта табличка снаружи и называется "переменными окружения", а `config.Load()` — это
//    робот, который перед стартом игры читает табличку и складывает все настройки в рюкзак `Config`.
//
// 2. КАК ПОНЯТЬ УКАЗАТЕЛИ (`*` и `&`) НА ПРИМЕРЕ ЗАМКА ИЗ LEGO?
//    Представь, что ты построил у себя в комнате огромный замок из LEGO (структуру `Config`).
//    В школе друг говорит тебе: "Покажи свой замок!".
//      - Способ БЕЗ указателя (`Config`): тебе придётся купить ещё одну коробку LEGO, собрать
//        ТОЧНО ТАКУЮ ЖЕ КОПИЮ замка и тащить её в школу в руках. Тяжело и долго!
//        А если друг приклеит на копию флажок, на твоём замке дома флажка НЕ появится.
//      - Способ С УКАЗАТЕЛЕМ (`*Config` и `&Config`): ты берёшь маленький бумажный стикер (`&Config`)
//        и пишешь на нём адрес: "Улица Ленина, дом 5, моя комната".
//        В школе ты просто отдаёшь другу этот лёгкий стикер с адресом (`*Config`)!
//        Друг приходит по адресу и видит твой НАСТОЯЩИЙ замок.
//
//    Запомни правило стикера:
//      `&` (амперсанд) = написать адрес замка на стикере (`&Config{...}`).
//      `*` (звёздочка) = сам стикер с адресом (`*Config`).
//
// ============================================================================
// 🍕 ПРИМЕРЫ НА РЕСТОРАНЕ (2 НАГЛЯДНЫХ ПРИМЕРА):
// ============================================================================
//
// ПРИМЕР 1: Табличка с правилами ресторана (`Config` и `os.Getenv`)
//   Представь сеть ресторанов в разных городах. Меню и правила готовки везде одинаковые (один код Go),
//   но у каждого филиала свои настройки снаружи (`переменные окружения`):
//     - Ресторан №1: окошко выдачи №8080 (`HTTP_PORT=8080`), секретная печать шефа `"secret1"` (`JWT_SECRET`).
//     - Ресторан №2: окошко выдачи №9000 (`HTTP_PORT=9000`), секретная печать шефа `"secret2"` (`JWT_SECRET`).
//   Функция `Load()` — это утренний менеджер, который читает табличку на двери филиала (`os.Getenv`)
//   и заполняет папку с правилами ресторана `Config`. А если на двери забыли написать секретную печать
//   (`jwtSecret == ""`), менеджер не разрешает открывать ресторан!
//
// ПРИМЕР 2: Указатель (`*Config`) и Адрес (`&Config`) на примере Главной Книги Рецептов ресторана
//   Представь, что `Config` — это толстая Главная Книга Рецептов ресторана в 500 страниц.
//     - Вариант БЕЗ указателя (`func Load() Config`):
//       Каждому официанту и повару делают полную бумажную КСЕРОКОПИЮ всех 500 страниц.
//       Это долго и занимает кучу места на кухне!
//     - Вариант С УКАЗАТЕЛЕМ (`func Load() *Config` и `return &Config{...}`):
//       Книга лежит в одном экземпляре на главном столе кухни, а `&Config` — это визитка с надписью:
//       "Книга лежит на Столе №1". Мы раздаём всем работникам эту лёгкую визитку (`*Config`),
//       и все смотрят в одну и ту же настоящую книгу!
// ============================================================================

// package config — имя пакета совпадает с названием папки `internal/config`.
// Разбор строки по каждому слову:
//   - `package` — ключевое слово объявления пакета;
//   - `config`  — имя этого пакета.
package config

// Подключаем нужные пакеты из стандартной библиотеки и нашего проекта.
// Разбор строки:
//   - `import (` — начинаем список подключаемых пакетов.
import (
	// "fmt" — пакет для форматирования текста. Мы используем `fmt.Errorf` для создания понятных ошибок.
	"fmt"
	// "os" — пакет для общения с операционной системой (чтение переменных окружения, файлов и т.д.).
	"os"
	// "time" — пакет для работы со временем и длительностью (секунды, минуты, часы).
	"time"

	// Подключаем наш пакет postgres, чтобы использовать его структуру `postgres.Config`.
	"habit-tracker/pkg/db/postgres"
)

// Config — главная структура настроек всего приложения.
// Обрати внимание: и само слово `Config`, и все поля внутри (`HTTPPort`, `JWTSecret`...)
// начинаются с БОЛЬШОЙ (заглавной) буквы.
// В Go заглавная буква означает `public` (публичное): эти поля видны из других пакетов (например, из `app`).
// Если бы написали с маленькой буквы (`httpPort`), другие пакеты не смогли бы их прочитать!
//
// Разбор строки по каждому слову:
//   - `type`   — ключевое слово "создаём новый тип данных";
//   - `Config` — имя нашего нового типа (с Большой буквы, чтобы его видели другие пакеты);
//   - `struct` — ключевое слово "это структура (набор полей)";
//   - `{`      — открываем список полей структуры.
type Config struct {
	// HTTPPort — на каком порту наш веб-сервер будет ждать запросов (например, "8080").
	// Разбор строки по каждому слову:
	//   - `HTTPPort` — имя поля (с Большой буквы = публичное);
	//   - `string`   — тип поля: текстовая строка.
	HTTPPort string

	// JWTSecret — секретная фраза, которой сервер подписывает JWT-токены.
	// Разбор строки по каждому слову:
	//   - `JWTSecret` — имя поля;
	//   - `string`    — тип поля: текстовая строка.
	JWTSecret string

	// JWTTTL — сколько времени действует выданный токен (TTL = Time To Live, "время жизни").
	// Тип `time.Duration` — это длительность времени (внутри Go хранит её как количество наносекунд).
	// Разбор строки по каждому слову:
	//   - `JWTTTL`        — имя поля;
	//   - `time.Duration` — тип `Duration` из пакета `time`.
	JWTTTL time.Duration

	// Postgres — вложенная структура! Внутри анкеты `Config` лежит анкета `postgres.Config`
	// с настройками базы данных (хост, порт, логин, пароль, имя базы).
	// Разбор строки по каждому слову:
	//   - `Postgres`        — имя поля;
	//   - `postgres.Config` — тип поля: структура `Config` из пакета `postgres`.
	Postgres postgres.Config
}

// Load — функция, которая загружает настройки из окружения и возвращает готовую структуру.
// В скобках `(*Config, error)` указано, что функция возвращает ДВА значения:
//  1. `*Config` — указатель на созданную структуру настроек (или `nil`, если произошла ошибка).
//  2. `error`   — ошибка (или `nil`, если загрузка прошла успешно).
//
// Разбор строки по каждому слову от начала до конца:
//   - `func`             — ключевое слово "объявляем функцию";
//   - `Load`             — имя функции (с Большой буквы, вызывается из `app.go` как `config.Load()`);
//   - `()`               — пустые скобки: функция не принимает входных параметров;
//   - `(*Config, error)` — функция возвращает два значения: указатель `*Config` и ошибку `error`;
//   - `{`                — открываем тело функции.
func Load() (*Config, error) {
	// ШАГ 1. Читаем время жизни токена.
	// Сначала `getEnv("JWT_TTL", "24h")` ищет переменную окружения JWT_TTL.
	// Если пользователь её не задал, функция вернёт строку по умолчанию: "24h" (24 часа).
	// Затем `time.ParseDuration(...)` превращает строку "24h" в тип `time.Duration`.
	// Примеры строк, которые понимает ParseDuration: "15m" (15 минут), "1h30m", "45s".
	//
	// Разбор строки по каждому слову:
	//   - `ttl, err`                 — создаём две переменные: `ttl` (для длительности) и `err` (для ошибки);
	//   - `:=`                       — оператор "создай переменные и положи в них значения";
	//   - `time.ParseDuration(...)`  — вызываем функцию `ParseDuration` из пакета `time`;
	//   - `getEnv("JWT_TTL", "24h")` — аргумент внутри скобок: вызываем нашу функцию `getEnv`,
	//                                  которая ищет `"JWT_TTL"`, а если её нет — отдаёт `"24h"`.
	ttl, err := time.ParseDuration(getEnv("JWT_TTL", "24h"))

	// Если в переменную JWT_TTL написали ерунду (например, "два дня" или "abc"),
	// ParseDuration вернёт ошибку в переменную `err`.
	// Разбор строки по каждому слову:
	//   - `if`         — если;
	//   - `err != nil` — переменная `err` не равна `nil` (то есть ошибка произошла);
	//   - `{`          — открываем блок обработки ошибки.
	if err != nil {
		// Возвращаем:
		//   1-м значением: `nil` (указателя на Config нет, так как настройка сломана);
		//   2-м значением: новую ошибку, внутри которой через `%w` спрятана исходная ошибка `err`.
		// Разбор строки по каждому слову:
		//   - `return`                                 — выйти из функции и вернуть значения;
		//   - `nil,`                                   — 1-й результат: `nil` вместо `*Config`;
		//   - `fmt.Errorf("invalid JWT_TTL: %w", err)` — 2-й результат: отформатированная ошибка с обёрнутой `err`.
		return nil, fmt.Errorf("invalid JWT_TTL: %w", err)
	}

	// ШАГ 2. Читаем секретный ключ для токенов.
	// `os.Getenv("JWT_SECRET")` просит у системы значение переменной JWT_SECRET.
	// Если такой переменной нет, `os.Getenv` вернёт пустую строку `""`.
	// Разбор строки по каждому слову:
	//   - `jwtSecret`               — имя новой переменной;
	//   - `:=`                      — создать переменную и записать значение;
	//   - `os.Getenv("JWT_SECRET")` — вызвать функцию `Getenv` из пакета `os` для ключа `"JWT_SECRET"`.
	jwtSecret := os.Getenv("JWT_SECRET")

	// Проверяем: если секрет пустой (`== ""`), мы НЕ подставляем значение по умолчанию!
	// Почему? Потому что секретный ключ — это главный замок безопасности.
	// Разработчик обязан задать его явно перед запуском сервера.
	// Разбор строки по каждому слову:
	//   - `if`              — если;
	//   - `jwtSecret == ""` — значение `jwtSecret` равно (`==`) пустой строке `""`;
	//   - `{`               — открываем блок ошибки.
	if jwtSecret == "" {
		// Останавливаем загрузку и возвращаем ошибку.
		// Разбор строки по каждому слову:
		//   - `return`                               — выйти из функции;
		//   - `nil,`                                 — 1-й результат: `nil` вместо `*Config`;
		//   - `fmt.Errorf("JWT_SECRET is required")` — 2-й результат: ошибка "JWT_SECRET обязателен".
		return nil, fmt.Errorf("JWT_SECRET is required")
	}

	// ШАГ 3. Собираем структуру Config и возвращаем её адрес!
	// Значок `&` перед `Config{...}` создаёт структуру в памяти и сразу берёт её АДРЕС,
	// чтобы получился тип `*Config`, как мы и обещали в заголовке функции `func Load() (*Config, error)`.
	// Разбор строки по каждому слову:
	//   - `return`   — вернуть из функции;
	//   - `&Config{` — создать структуру `Config` и оператором `&` взять её адрес в памяти.
	return &Config{
		// Если HTTP_PORT не задан в системе — используем порт "8080".
		// Разбор строки: `HTTPPort:` (имя поля) `getEnv("HTTP_PORT", "8080"),` (значение поля).
		// Разбор строки по каждому слову:
		//   - `HTTPPort:`                   — имя поля структуры `Config`;
		//   - `getEnv("HTTP_PORT", "8080")` — вызов функции чтения переменной `"HTTP_PORT"` (по умолчанию `"8080"`);
		//   - `,`                           — запятая после поля структуры.
		HTTPPort: getEnv("HTTP_PORT", "8080"),
		// Кладём проверенный секретный ключ в поле `JWTSecret`.
		// Разбор строки по каждому слову:
		//   - `JWTSecret:` — имя поля структуры `Config`;
		//   - `jwtSecret,` — переменная с секретным ключом (плюс запятая `,`).
		JWTSecret: jwtSecret,
		// Кладём проверенное время жизни токена в поле `JWTTTL`.
		// Разбор строки по каждому слову:
		//   - `JWTTTL:` — имя поля структуры `Config`;
		//   - `ttl,`    — переменная длительности жизни токена (плюс запятая `,`).
		JWTTTL: ttl,
		// Заполняем вложенную структуру настроек PostgreSQL (`Postgres: postgres.Config{...}`):
		// Разбор строки по каждому слову:
		//   - `Postgres:`         — имя поля в структуре `Config`;
		//   - `postgres.Config{`  — создаём вложенную структуру `Config` из пакета `postgres`.
		Postgres: postgres.Config{
			// Адрес компьютера с базой. По умолчанию "localhost" (этот же компьютер).
			// Разбор строки по каждому слову:
			//   - `Host:`                            — поле хоста БД;
			//   - `getEnv("POSTGRES_HOST", "localhost"),` — читаем `"POSTGRES_HOST"` или берём `"localhost"`.
			Host: getEnv("POSTGRES_HOST", "localhost"),
			// Порт PostgreSQL. По умолчанию стандартный порт "5432".
			// Разбор строки по каждому слову:
			//   - `Port:`                        — поле порта БД;
			//   - `getEnv("POSTGRES_PORT", "5432"),` — читаем `"POSTGRES_PORT"` или берём `"5432"`.
			Port: getEnv("POSTGRES_PORT", "5432"),
			// Имя пользователя БД. По умолчанию "postgres".
			// Разбор строки по каждому слову:
			//   - `User:`                            — поле логина БД;
			//   - `getEnv("POSTGRES_USER", "postgres"),` — читаем `"POSTGRES_USER"` или берём `"postgres"`.
			User: getEnv("POSTGRES_USER", "postgres"),
			// Пароль от БД. По умолчанию пустая строка "".
			// Разбор строки по каждому слову:
			//   - `Password:`                        — поле пароля БД;
			//   - `getEnv("POSTGRES_PASSWORD", ""),` — читаем `"POSTGRES_PASSWORD"` или берём `""`.
			Password: getEnv("POSTGRES_PASSWORD", ""),
			// Имя базы данных, в которой лежат наши таблицы. По умолчанию "habits".
			// Разбор строки по каждому слову:
			//   - `Database:`                        — поле имени базы данных;
			//   - `getEnv("POSTGRES_DB", "habits"),` — читаем `"POSTGRES_DB"` или берём `"habits"`.
			Database: getEnv("POSTGRES_DB", "habits"),
			// Режим шифрования SSL. На локальном компьютере шифрование не нужно ("disable").
			// Разбор строки по каждому слову:
			//   - `SSLMode:`                              — поле режима SSL;
			//   - `getEnv("POSTGRES_SSLMODE", "disable"),` — читаем `"POSTGRES_SSLMODE"` или берём `"disable"`.
			SSLMode: getEnv("POSTGRES_SSLMODE", "disable"),
		},
		// Разбор строки `}, nil`:
		//   - `}`   — закрываем структуру `&Config{...}` (1-е возвращаемое значение);
		//   - `,`   — разделитель возвращаемых значений;
		//   - `nil` — 2-е возвращаемое значение (ошибки нет, всё прошло успешно!).
	}, nil
}

// getEnv — маленькая функция-помощник (helper).
// Она начинается с маленькой буквы `g`, значит она ПРИВАТНАЯ (видна только внутри файла/пакета `config`).
//
// Как работают параметры `(key, defaultValue string)`:
// Если подряд идут параметры одного типа (`string`), в Go можно написать тип один раз в конце!
// То есть `key, defaultValue string` — это то же самое, что `key string, defaultValue string`.
//
// Разбор строки по каждому слову от начала до конца:
//   - `func`                      — объявляем функцию;
//   - `getEnv`                    — имя функции (с маленькой буквы = приватная);
//   - `(key, defaultValue string)` — два входных параметра типа `string`: имя переменной `key` и запасное значение `defaultValue`;
//   - `string`                    — функция возвращает одну строку `string`;
//   - `{`                         — открываем тело функции.
func getEnv(key, defaultValue string) string {
	// Читаем переменную окружения по имени `key` (например, "HTTP_PORT").
	// Если она не пустая (`value != ""`), сразу возвращаем то, что прочитали.
	// Разбор строки по каждому слову:
	//   - `if`                      — если;
	//   - `value := os.Getenv(key)` — читаем переменную `key` из ОС и сохраняем в `value`;
	//   - `;`                       — разделитель подготовки и условия;
	//   - `value != ""`             — условие: `value` не равна пустой строке `""`;
	//   - `{`                       — открываем блок `if`.
	if value := os.Getenv(key); value != "" {
		// Разбор строки: `return value` — возвращаем найденную строку `value`.
		// Разбор строки по каждому слову:
		//   - `return` — выйти из функции и вернуть результат;
		//   - `value`  — прочитанное из окружения значение.
		return value
	}
	// А если переменная не была задана (равна ""), возвращаем запасное значение `defaultValue`.
	// Разбор строки: `return defaultValue` — возвращаем строку по умолчанию.
	// Разбор строки по каждому слову:
	//   - `return`       — выйти из функции и вернуть результат;
	//   - `defaultValue` — запасное значение по умолчанию.
	return defaultValue
}
