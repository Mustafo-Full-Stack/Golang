-- Разбор строки по каждому слову:
--   - `CREATE TABLE`  — команда SQL "создать таблицу";
--   - `IF NOT EXISTS` — "если она ещё не существует" (чтобы при повторном запуске не было ошибки);
--   - `users`         — имя таблицы;
--   - `(`             — открываем список колонок таблицы.
CREATE TABLE IF NOT EXISTS users (
    -- Разбор строки по каждому слову:
    --   - `id`          — имя колонки (уникальный номер пользователя);
    --   - `BIGSERIAL`   — 64-битное целое число, которое PostgreSQL сам увеличивает на +1 (1, 2, 3...);
    --   - `PRIMARY KEY` — первичный ключ (главный уникальный идентификатор строки).
    id            BIGSERIAL PRIMARY KEY,

    -- Разбор строки по каждому слову:
    --   - `name`     — имя колонки (имя пользователя);
    --   - `TEXT`     — тип данных: текст любой длины;
    --   - `NOT NULL` — поле обязательно для заполнения (не может быть пустым `NULL`).
    name          TEXT        NOT NULL,

    -- Разбор строки по каждому слову:
    --   - `email`    — имя колонки (электронная почта);
    --   - `TEXT`     — тип данных: текст;
    --   - `NOT NULL` — поле не может быть пустым.
    email         TEXT        NOT NULL,

    -- Разбор строки по каждому слову:
    --   - `password_hash` — имя колонки (bcrypt-хеш пароля);
    --   - `TEXT`          — тип данных: текст;
    --   - `NOT NULL`      — поле не может быть пустым.
    password_hash TEXT        NOT NULL,

    -- Разбор строки по каждому слову:
    --   - `created_at`  — имя колонки (дата и время регистрации);
    --   - `TIMESTAMPTZ` — дата и время с часовым поясом (Timestamp with Time Zone);
    --   - `NOT NULL`    — не может быть пустым;
    --   - `DEFAULT`     — значение по умолчанию (если мы его не передали);
    --   - `now()`       — встроенная функция PostgreSQL, возвращающая текущий момент времени.
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
-- `);` — закрываем описание таблицы `users`.
);

-- Создаём уникальный индекс по почте в нижнем регистре (`lower(email)`):
-- 1) Запрещает регистрировать две одинаковые почты (например, "test@a.com" и "TEST@a.com").
-- 2) Ускоряет поиск пользователя при входе (`WHERE email = $1`) в тысячи раз!
--
-- Разбор строки по каждому слову:
--   - `CREATE UNIQUE INDEX`   — создать уникальный индекс (запрещает дубликаты);
--   - `IF NOT EXISTS`         — если такой индекс ещё не создан;
--   - `users_email_lower_uniq` — название индекса;
--   - `ON users`              — для таблицы `users`;
--   - `(lower(email));`       — по колонке `email`, приведённой к маленьким буквам.
CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_uniq ON users (lower(email));
